package com.point.desktop

import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Компьютер говорит словами человека, а не хвостом исключения (#596).
 *
 * Замер 06.08.2026: у компьютера девятнадцать отказов, и примерно половина из них была
 * `it.message ?: "Не удалось …"` — то есть человеку показывался текст исключения. На телефоне это
 * лечили отдельно (#541): хвост исключения человеку ничего не говорит, а стоит под объектом первой
 * строкой.
 *
 * **Почему сторож смотрит в исходники.** Отказ — это текст, и проверить его иначе нечем: вызвать
 * все девятнадцать в тесте значит подделать девятнадцать поломок железа и сети. Здесь судится
 * правило, а не поведение: «в отказе не должно быть текста исключения». Правило простое, поэтому и
 * сторож простой — и он сработает на первой же новой строке, написанной по привычке.
 */
class PcSpeaksPlainlyTest {

    private val sources: List<File>
        get() = File("src/main/kotlin/com/point/desktop")
            .walkTopDown().filter { it.isFile && it.extension == "kt" }.toList()

    @Test fun `ни один отказ не показывает человеку текст исключения`() {
        val guilty = sources.flatMap { file ->
            file.readLines().mapIndexedNotNull { i, line ->
                // Ловится ровно форма «отказ, собранный из исключения»: она и была болезнью.
                val fromException = Regex("""ActionResult\.Failure\(\s*\w+\.message""").containsMatchIn(line)
                if (fromException) "${file.name}:${i + 1}" else null
            }
        }

        assertTrue(
            "отказ собран из исключения — человек прочитает хвост стека: $guilty",
            guilty.isEmpty(),
        )
    }

    @Test fun `отказ не обрывается на констатации — в нём есть, что делать`() {
        // Не полный разбор языка, а простая проверка: отказ из одного слова («Не получилось»)
        // человеку бесполезен. Тире или запятая значат, что за констатацией что-то следует.
        //
        // Судится только то, что видит человек. Станция пути («отменено») — это запись в памяти
        // объекта, а не обращение к нему, и советовать ей нечего.
        val short = sources.flatMap { file ->
            // Хвост `[,)]` важен: без него склеенный из нескольких строк отказ судился бы по
            // своему первому куску, и длинный совет читался бы как обрывок.
            Regex("""ActionResult\.Failure\(\s*"([^"]{4,})"\s*[,)]""").findAll(file.readText())
                .map { it.groupValues[1] }
                .filter { it.first().isUpperCase() }
                .filter { text -> text.length < 25 && !text.contains('—') && !text.contains(',') }
                .map { "${file.name}: «$it»" }
                .toList()
        }

        assertTrue("отказ ничего не советует: $short", short.isEmpty())
    }

    @Test fun `исход печати говорит, что произошло, а не в каком состоянии очередь`() {
        // «В очереди „HP“ · проверьте принтер» человек читал как «может быть». Задание ушло — это
        // факт; напечаталось ли, компьютеру отсюда не видно, и обещать это нельзя.
        val print = File("src/main/kotlin/com/point/desktop/DesktopActions.kt").readText()

        assertTrue("исход печати снова описывает очередь", "В очереди «" !in print)
        assertTrue("исход печати не назвал, что произошло", "Отправлено на печать" in print)
    }

    @Test fun `предел и факт не совпадают на экране`() {
        // «Снимок 1 МБ — сервис принимает до 1 МБ» читалось как ложь: округление до целых съедало
        // разницу. Десятые её показывают.
        val ocr = File("src/main/kotlin/com/point/desktop/OcrActions.kt").readText()

        assertTrue("размер снимка снова округляется до целых", "%.1f" in ocr)
    }
}
