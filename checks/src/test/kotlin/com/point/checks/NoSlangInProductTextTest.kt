package com.point.checks

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Человек не читает сленга (решение владельца 02.09.2026: «убери весь ии слоп и сленг»).
 *
 * На экране стояло «тапните, и оно выполнится» и «Тапнуть по нему Point за вас не станет».
 * Человек, который принёс Point счёт из магазина, не обязан знать слово «тап» — он нажимает.
 *
 * Черта проходит по тому, что видно человеку, а не по всему тексту проекта. Внутри кода
 * «тап» — устоявшееся слово на сто пятьдесят мест, и переписывать его значило бы менять
 * словарь разработки ради вида, а не ради человека. Поэтому сторож смотрит только на строки
 * в кавычках у продукта и на страницы сервера — ровно туда, где текст доходит до глаз.
 *
 * Живёт в `:checks` (#1293): проверка обходит исходники всех модулей вместе с компьютером и
 * сервером, а модуля, который собирал бы их разом, в проекте нет.
 */
class NoSlangInProductTextTest {

    private val slang = listOf(
        Regex("""(?iu)(?<![а-яё])тапн[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])свайп[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])скролл[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])кликн[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])юзер[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])фич[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])кейс[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])флоу[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])дефолтн[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])хардкод[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])апдейт[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])деплой[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])мерж[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])таск[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])скоуп[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])бэкенд[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])фронтенд[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])стейт[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])колбэк[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])тултип[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])плейсхолдер[а-яё]*(?![а-яё])"""),
        Regex("""(?iu)(?<![а-яё])эндпоинт[а-яё]*(?![а-яё])"""),
    )

    /** Текст в кавычках — то, что может дойти до экрана. Комментарии сторож не судит. */
    private val quoted = Regex("\"[^\"]*\"")

    private fun productFiles(): List<File> = repo.walkTopDown()
        .onEnter { it.name != "build" && !it.name.startsWith(".") }
        .filter { it.isFile }
        .filter {
            val path = it.invariantSeparatorsPath
            (it.extension == "kt" && path.contains("/src/main/")) ||
                path.endsWith("relay/point_server/pages.py")
        }
        .toList()

    @Test
    fun `сторож и правда смотрит на продукт, а не на пустоту`() {
        assertTrue("исходников продукта не нашлось — сломан поиск, а не продукт", productFiles().size > 100)
    }

    @Test
    fun `в тексте, который видит человек, нет сленга`() {
        val found = productFiles().flatMap { file ->
            val text = file.readText()
            quoted.findAll(text).flatMap { hit ->
                slang.mapNotNull { it.find(hit.value)?.value }.map { word ->
                    val line = text.take(hit.range.first).count { c -> c == '\n' } + 1
                    "${file.relativeTo(repo).invariantSeparatorsPath}:$line — «$word»"
                }
            }
        }.sorted()

        assertEquals(
            "человек читает эти слова с экрана — скажите их по-русски: $found",
            emptyList<String>(),
            found,
        )
    }
}
