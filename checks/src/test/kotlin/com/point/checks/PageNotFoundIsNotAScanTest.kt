package com.point.checks

import java.io.File
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Ненайденная страница не подменяется исходным кадром (#1333).
 *
 * Дефект, ради которого написана карточка, был одним выражением: `detectDocument(...) ?: rgba`
 * — не нашли страницу, отдали исходник, и снаружи это неотличимо от успеха. Кривой снимок
 * уезжал человеку как «скан», а находки с него выходят кашей (#1017, #1007).
 *
 * Поймать возврат этого выражения выполнением нельзя: весь конвейер — нативная OpenCV, а она
 * в JVM-тестах не поднимается (в `OpenCvScanTest` живут только чистые `orderCorners` и
 * `distance`, которым нативная часть не нужна). Поэтому сторож читает сам файл — так же, как
 * остальные проверки этого модуля, и падает он ровно от возврата подмены, а не от переписанной
 * формулировки.
 *
 * Что делать вместо подмены — решает вызывающий: «Скан» и «Скан в PDF» обрабатывают кадр
 * целиком и помечают результат (`META_WHOLE_FRAME`), а не выдают его за выпрямленную страницу.
 */
class PageNotFoundIsNotAScanTest {

    private val scan = File(repo, "executors/src/main/kotlin/com/point/executors/OpenCvScan.kt")

    /** Ищется исходный кадр справа от `?:` — как его ни назови в самом файле. */
    private val substitution = Regex("""\?:\s*(rgba|src|frame|source)\b""")

    @Test
    fun `проверка и правда читает конвейер скана, а не пустоту`() {
        assertTrue("файл конвейера скана не нашёлся — сломан путь, а не продукт", scan.isFile)
        assertTrue("в файле нет поиска страницы — читается не тот файл", "detectDocument" in code(scan.readText()))
    }

    @Test
    fun `ненайденная страница не подменяется исходным кадром`() {
        val guilty = substitution.findAll(code(scan.readText())).map { it.value.trim() }.toList()

        assertTrue(
            "не нашедший страницу конвейер снова отдаёт исходный кадр, и снаружи это " +
                "неотличимо от выпрямленной страницы: $guilty",
            guilty.isEmpty(),
        )
    }
}
