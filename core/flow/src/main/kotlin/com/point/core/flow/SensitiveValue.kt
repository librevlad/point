package com.point.core.flow

/**
 * Как значение показывают человеку, когда показывать его целиком нельзя (#240, #262).
 *
 * Прецедент прямой и живой: на скриншоте переписки первые двенадцать цифр номера карты уехали в
 * «Телефон» с иконкой звонка — рядом с той же картой, **правильно** замаскированной до «•• 2632».
 * Маскировка работала; номер утёк мимо неё другим полем. Урок оттуда: маскировка обязана быть
 * свойством **ключа факта**, а не одного экрана, который о ней помнит.
 *
 * Поэтому реализация одна на всех, кто печатает факты объекта: чек-лист «Point понял» и карточка
 * готовности действий. С появлением схемы «Перевести по реквизитам» (#262) карта стала ключевым
 * значением готового действия — то есть строкой, которую карточка печатает первой, — и вторая
 * копия правила («на том экране маскируем, на этом забыли») разъехалась бы с первой ровно так же,
 * как разъезжаются два счётчика улик.
 *
 * **Значение при этом не подменяется нигде**: в метаданных, в журнале и в переносе на ПК живут
 * дословные цифры (тот же контракт, что у [fieldHint] с ведущими нулями барабана) — маска
 * существует только на экране.
 */
fun maskedForScreen(key: String, value: String): String = when (key) {
    // Номер карты: хвост опознаёт карту человеку, остальное ему на экране не нужно.
    META_ENTITY_PREFIX + "card" -> maskedCard(value)
    else -> value
}

/** «•• 2632» — четыре последние цифры. Короче — маскировать нечего, значит и маски нет:
 *  «•• » перед пустотой сказало бы, что число скрыто, хотя скрывать было нечего. */
private fun maskedCard(value: String): String {
    val digits = value.filter(Char::isDigit)
    return if (digits.length <= CARD_TAIL) value else "•• " + digits.takeLast(CARD_TAIL)
}

private const val CARD_TAIL = 4
