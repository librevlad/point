package com.point.core.flow

import com.point.core.model.Intent
import com.point.core.model.ObjectState

/**
 * Общий порядок действий: намерение, приоритет, имя (ADR-0001 §14, Конституция §8).
 *
 * Правило одно на оба устройства, а жило в двух копиях: `DesktopRegistry` носил в себе
 * оговорку «клаузула повторена, а не переиспользована: desktop не видит :executors», и
 * телефонная политика повторяла те же три ступени в конце своего сравнения (#840).
 *
 * **Intent поднимает совпадающие по смыслу действия и никого не убирает** — это норма
 * конституции, и держать её в двух местах значило бы позволить им разойтись.
 *
 * Устройство вправе добавить свои ступени ПЕРЕД этими — телефон так и делает: закрепление
 * человеком, отсутствие ключа, главная граница «На компьютер», облачное чтение уже
 * прочитанного. Но хвост у обоих один.
 */
fun byIntentThenPriority(
    state: ObjectState,
    intent: Intent?,
): Comparator<Capability> = compareBy(
    { if (intent == null || intent in it.intents(state)) 0 else 1 },
    { it.priority(state) },
    { it.id.value },
)

/**
 * Вопрос этого действия для этого объекта уже закрыт находкой (#1010, #1411).
 *
 * Отвеченный вопрос не предлагается первым заново: расшифрованная запись не зовёт
 * «Расшифровать» главным, прочитанное — «Прочитать». Действие остаётся в списке, но уступает
 * следующему шагу. Правило жило только в телефонной политике, и на компьютере после
 * расшифровки «Расшифровать» по-прежнему стояло первым своим приоритетом.
 *
 * Вопрос — заявленный действием (`meta.answers`), когда он не совпадает с id: «Считать QR»
 * отвечает на qr-content (#1119).
 */
fun alreadyAnswered(capability: Capability, graph: GraphState): Boolean =
    investigationStateOf(graph.obj.metadata, capability.meta.answers ?: capability.id) == InvestigationState.FOUND
