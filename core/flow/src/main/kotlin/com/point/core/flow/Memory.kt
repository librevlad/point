package com.point.core.flow

/**
 * Место, где Point что-то помнит о человеке (#1026).
 *
 * «Забыть всё» стирало перечень истории — и оставляло на устройстве саму копию объекта, слой
 * прочитанных с него слов, граф последнего объекта и переписку с моделью, где перечислены его
 * адрес, сумма, дата и телефон. Экран после этого говорил «Пока ничего не сохранено».
 *
 * Мест несколько, и каждое обязано уметь забывать себя само: иначе следующее хранилище
 * появится, а кнопка о нём не узнает.
 */
fun interface Memory {
    suspend fun forget()
}

/**
 * Забыть всё, что помним, — до конца.
 *
 * Сбой одного места не отменяет остальных: недоступная папка не повод оставить переписку с
 * моделью на диске. Возвращается число мест, которые забыть не вышло, — чтобы «готово»
 * говорилось только тогда, когда это правда.
 */
suspend fun forgetEverything(places: Iterable<Memory>): Int {
    var failed = 0
    places.forEach { place ->
        runCatching { place.forget() }.onFailure { failed++ }
    }
    return failed
}
