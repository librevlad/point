package com.point.core.flow

/**
 * Когда это было, словами Point (#114, дизайн-ревью 04.08.2026).
 *
 * Раньше строку собирал системный `DateUtils.getRelativeTimeSpanString`, а он говорит на языке
 * телефона. На устройстве с английской системой «Недавнее» выглядело так: «Изображение · 3 hours
 * ago», «Запись · 38 minutes ago» — русская подпись и английское время в одной строке. Весь
 * остальной текст Point русский всегда, потому что он написан в коде, а не взят у системы; время
 * оказалось единственным местом, где интерфейс говорил чужим голосом.
 *
 * Считается чистой функцией и потому судится тестом, а не глазами на телефоне с другой локалью.
 */
fun agoLabel(millisAgo: Long): String {
    if (millisAgo < 0) return "только что" // часы телефона перевели назад — не спорим с ними
    val minutes = millisAgo / 60_000
    val hours = minutes / 60
    val days = hours / 24
    return when {
        minutes < 1 -> "только что"
        minutes < 60 -> "$minutes ${plural(minutes, "минуту", "минуты", "минут")} назад"
        hours < 24 -> "$hours ${plural(hours, "час", "часа", "часов")} назад"
        days == 1L -> "вчера"
        days < 7 -> "$days ${plural(days, "день", "дня", "дней")} назад"
        days < 31 -> "${days / 7} ${plural(days / 7, "неделю", "недели", "недель")} назад"
        days < 365 -> "${days / 30} ${plural(days / 30, "месяц", "месяца", "месяцев")} назад"
        else -> "давно"
    }
}

/**
 * Русское склонение при числе: 1 минута, 2 минуты, 5 минут.
 *
 * Правило то же, что в любом русском тексте, и без него подпись читалась бы как машинный перевод —
 * ровно тем, чем она и была.
 */
private fun plural(n: Long, one: String, few: String, many: String): String {
    val mod100 = n % 100
    if (mod100 in 11..14) return many
    return when (n % 10) {
        1L -> one
        2L, 3L, 4L -> few
        else -> many
    }
}
