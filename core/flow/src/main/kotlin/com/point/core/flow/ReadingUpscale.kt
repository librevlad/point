package com.point.core.flow

import kotlin.math.roundToInt

/**
 * Увеличить мелкий кадр **перед** чтением — самое дешёвое улучшение чтения, какое у нас есть (#273).
 *
 * **Откуда число.** Замер зрячих моделей 04.08.2026 (`docs/VISION-MODELS.md`) прогнал одну и ту же
 * ведомость с точно известным содержимым (24 строки) через шесть порч кадра. Пять из шести читались
 * дословно, провалилась одна — «снято издалека», кадр в четверть разрешения: 20 строк из 24 и итог
 * мимо на 8300. Тот же кадр, увеличенный обычной интерполяцией вчетверо, прочитался целиком:
 * 24 из 24, четыре секунды, локально, без сети и без денег. Это единственный известный нам приём,
 * который чинит провал чтения, ничего не отправляя наружу.
 *
 * **Почему это не тот апскейл, который #273 закрыл.** Закрыт был **облачный** апскейл — порождающая
 * модель, которая не проявляет снятое, а дорисовывает правдоподобное; на ведомости дорисованная
 * деталь это цифра, и приезжает она помеченной «прочитано со страницы дословно». Здесь ничего не
 * дорисовывается: интерполяция не добавляет ни одного пикселя содержания, она даёт движку знаки того
 * размера, на котором движки работают. Тот же приём, что у куска строки для перечита
 * ([readingCropUpscale]), — только теперь для целого кадра.
 *
 * **Почему не «всегда».** Увеличение вчетверо — это в шестнадцать раз больше пикселей: время движка
 * и память телефона. Крупный кадр от этого не читается лучше (он и так читается), поэтому правило
 * включения смотрит на две вещи и обе называет числом: [READING_FRAME_PX] — размер кадра,
 * [READING_TEXT_PX] — высоту слова, если её кто-то уже измерил.
 */

/**
 * Во сколько раз увеличить кадр перед чтением. Целое; 1 — «увеличивать не надо», и это обычный
 * случай для фотографии с телефона.
 *
 * Правило читается одной фразой: **знаем буквы — судим по буквам, не знаем — судим по кадру.**
 *
 * - **По кадру** ([targetEdge] = [READING_FRAME_PX]). Число здесь не новое: ровно с ним конвейер уже
 *   живёт с другой стороны. Декодер режет длинную сторону пополам, пока `сторона / 2 >= 2048`
 *   (`TesseractTextRecognizer.OCR_MAX_PX`, `BitmapOutboundFrames.PAGE_MAX_PX`), то есть обычное фото
 *   приезжает движку со стороной в `[2048, 4096)`. Кадр короче 2048 приезжает **ниже всего, на чём
 *   конвейер настраивали**, и увеличение делает его тем же самым кадром, что и уменьшение большого:
 *   одно правило с двух сторон, а не новая ручка.
 * - **По буквам** ([textHeightPx], цель [READING_TEXT_PX]). Высота слова — прямое измерение того
 *   единственного, что движку важно; сторона кадра всегда была только её заменителем. Поэтому,
 *   когда высота известна ([typicalTextHeightPx] по чужому уже прочитанному слою), решает она:
 *   мелкий кадр с крупными буквами (обрезанный заголовок) увеличивать незачем, а страницу с мелким
 *   кеглем — есть зачем, даже если она сама не мала.
 *
 * **Целое, а не дробное** — по той же причине, что у [readingCropUpscale]: дробный масштаб
 * размывает штрих на полпикселя, а именно по штриху отличают 8 от 6 и «т» от «г».
 *
 * **Бюджет памяти отступает последним** ([budgetPx]): лучше увеличить меньше, чем уронить приложение
 * на кадре, который без увеличения был бы прочитан хоть как-то. Он же и есть тот предохранитель,
 * который не даёт правилу «по буквам» раздуть большую страницу с мелким кеглем.
 */
fun readingUpscale(
    widthPx: Int,
    heightPx: Int,
    textHeightPx: Int? = null,
    targetEdge: Int = READING_FRAME_PX,
    budgetPx: Long = READING_FRAME_BUDGET_PX,
): Int {
    if (widthPx <= 0 || heightPx <= 0) return 1
    var scale = if (textHeightPx != null && textHeightPx > 0) {
        stepsTo(textHeightPx.toLong(), READING_TEXT_PX.toLong())
    } else {
        stepsTo(maxOf(widthPx, heightPx).toLong(), targetEdge.toLong())
    }
    while (scale > 1 && widthPx.toLong() * heightPx * scale * scale > budgetPx) scale--
    return scale
}

/** Наименьшее целое увеличение, на котором [have] дорастает до [want], но не выше потолка. */
private fun stepsTo(have: Long, want: Long): Int {
    var scale = 1
    while (scale < MAX_READING_FRAME_UPSCALE && have * scale < want) scale++
    return scale
}

/**
 * Высота типичного слова кадра — то, что в [readingUpscale] названо «плотностью текста».
 *
 * Меряется по **уже прочитанному** слою (`metadata[META_OCR_ATOMS_REF]` пишет `OcrEnricher`): пока
 * страницу никто не читал, про кегль на ней честно ничего не известно, и тогда решает размер кадра.
 *
 * Три вещи, без которых число врало бы:
 * - **медиана, а не среднее**: одна строка заголовка в три раза выше остальных сдвигает среднее и
 *   не сдвигает медиану;
 * - **высота в выпрямленной копии**: атомы несут боксы в сыром кадре (ADR-0001), а у кадра боком
 *   «высота» сырого бокса — это длина слова;
 * - **деление на [FrameTransform.upscale]**: если тот слой сам читался с увеличенного кадра, его
 *   буквы крупнее ровно во столько раз, и без деления правило один раз увеличило бы кадр, а потом
 *   решило бы по своему же результату, что увеличивать больше нечего.
 *
 * `null` — судить не по чему: слов меньше [MIN_TEXT_SAMPLE]. Это не «текста нет», это «медиана по
 * такой горстке расскажет про случайность, а не про кегль», и тогда правило возвращается к размеру
 * кадра — то есть к увеличению, а не к отказу от него.
 */
fun typicalTextHeightPx(layer: AtomLayer): Int? {
    val transform = layer.transform
    val divisor = (transform?.upscale ?: 1).toFloat()
    val heights = layer.atoms
        .filter { it.text.isNotBlank() }
        .map { atom -> (transform?.toUpright(atom.box)?.height ?: atom.box.height) / divisor }
        .filter { it > 0f }
        .sorted()
    if (heights.size < MIN_TEXT_SAMPLE) return null
    return heights[heights.size / 2].roundToInt().coerceAtLeast(1)
}

/**
 * Сторона, ниже которой кадр считается мелким.
 *
 * Не выбрано, а взято: это тот же порог, по которому декодер прореживает большой кадр
 * (`OCR_MAX_PX` / `PAGE_MAX_PX` = 2048), и правило увеличения — его вторая половина. Замеру он не
 * противоречит: провалившийся кадр был 1000 px по длинной стороне, прочитавшийся — 4000, а 2048
 * лежит между ними и уже что-то значит в этом конвейере, в отличие от любого нового числа.
 */
const val READING_FRAME_PX = 2048

/**
 * Высота слова, на которой движок работает уверенно.
 *
 * Ориентир — собственное руководство Tesseract по качеству входа: x-height от 20 px, прописная около
 * 30. Число это суждение, а не наш замер: проверить его нечем, кроме прогона корпуса, и судить его
 * будет он (`docs/CORPUS.md`). Соседняя цель того же семейства названа там же, где живёт:
 * [READING_BAND_PX] = 120 для полосы строки, которую читает зрячая модель, — там читатель другой, и
 * ему нужен другой размер.
 */
const val READING_TEXT_PX = 30

/** Больше растягивать бессмысленно: интерполяция не добавляет того, чего в пикселях нет. Оно же и
 *  есть измеренное на провалившемся кадре ×4. */
private const val MAX_READING_FRAME_UPSCALE = 4

/**
 * Потолок площади увеличенного кадра — 12 мегапикселей.
 *
 * Число названо тем, что за ним стоит: это ровно эталонная ведомость владельца, 4000×3000, — кадр,
 * который конвейер уже проносит целиком сегодня (декод, доворот, Tesseract, отправка). Просить у
 * телефона больше, чем он и так носит, ради увеличенной копии незачем.
 *
 * В памяти это 48 МБ (`ARGB_8888`, 4 байта на пиксель), и на пике рядом ещё живёт исходная копия —
 * та мельче 2048 по стороне по построению, то есть не больше 16 МБ. Шестнадцатикратный рост пикселей
 * от ×4 — это именно то, ради чего предел существует: без него мелкий кадр 1800×1800 попросил бы
 * 51 мегапиксель.
 */
private const val READING_FRAME_BUDGET_PX = 12_000_000L

/** Меньше — не страница, а обрывок: медиана по такой горстке слов судит случайность. */
private const val MIN_TEXT_SAMPLE = 10

/**
 * Кадр был увеличен перед чтением — и во сколько раз (`"3"`).
 *
 * Происхождение видно человеку и метрике, как и остальное «понимание»: пишет ключ `OcrEnricher`
 * (там же, где `META_READING_MODE`), переносит на текстовый результат `OcrAction.ocrMeta`, и он
 * переживает историю и переезд на ПК. Ключа нет — кадр читали как есть.
 *
 * Второй, машинный канал того же факта — сам слой: [FrameTransform.upscale] уезжает в дамп атомов
 * ([AtomCodec]) и в строку `OCR done` ([ocrDoneLine]).
 */
const val META_READ_UPSCALE = "read.upscale"

/**
 * Само увеличение — за швом, как любой side-effect: на телефоне это Android-декодер, а порядок
 * «решить → увеличить → прочитать» обязан проверяться без устройства.
 *
 * Кадр здесь — что угодно (`Bitmap` на телефоне, пара чисел в тесте): ядро остаётся Android-free и
 * про пиксели не знает ничего.
 */
fun interface FrameUpscaler<F> {
    /** Копия кадра, увеличенная целым множителем [scale] (`scale >= 2`). */
    fun scaled(frame: F, scale: Int): F
}

/**
 * Кадр, приготовленный к чтению: он сам и множитель, которым его увеличили.
 *
 * Множитель едет рядом с кадром, а не остаётся в вызывающем: без него координаты прочитанного не
 * вернуть в сырой файл ([FrameTransform.upscale]), а происхождение — не показать человеку
 * ([META_READ_UPSCALE]). Ровно тот же довод, по которому [FrameTransform] едет рядом с байтами
 * отправляемого кадра.
 */
class ReadyFrame<F>(val frame: F, val scale: Int) {
    /** Кадр трогали. */
    val upscaled: Boolean get() = scale > 1
}

/**
 * Приготовить кадр к чтению: решение — [readingUpscale], само увеличение — [upscaler].
 *
 * Увеличивать не надо — возвращается **тот же** кадр и множитель 1: вызывающий по этому и узнаёт,
 * что освобождать нечего (лишняя копия битмапа на 12 Мп — 48 МБ на ровном месте).
 */
fun <F> preparedForReading(
    frame: F,
    widthPx: Int,
    heightPx: Int,
    textHeightPx: Int? = null,
    upscaler: FrameUpscaler<F>,
): ReadyFrame<F> {
    val scale = readingUpscale(widthPx, heightPx, textHeightPx)
    return if (scale <= 1) ReadyFrame(frame, 1) else ReadyFrame(upscaler.scaled(frame, scale), scale)
}
