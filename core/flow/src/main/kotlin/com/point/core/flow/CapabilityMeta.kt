package com.point.core.flow

data class CapabilityMeta(

    val priority: Int = 50,
    val cost: Cost = Cost.LOCAL,
    val latency: Latency = Latency.INSTANT,

    val network: Boolean = false,

    val auth: Boolean = false,

    /**
     * Действие круга устройств человека: чужому сервису оно объект не отдаёт (#920, #1088).
     *
     * Отсюда два следствия, и оба про одно. Компьютеру такое действие не объявляется
     * ([advertisedActions]): объект уже там, и «На компьютер» на его же экране бессмысленно.
     * И вопроса про облако у него не встаёт: «На компьютер» дотягивается до второй машины
     * через сервер и потому объявлено сетевым, а согласия спрашивать не о чем — объект
     * остаётся в круге (`FlowViewModel.leavesCircle`, `DefaultCapabilityRegistry.offlineReason`).
     *
     * Второе следствие гасит запасной ответ. Обычно вопрос поднимает и сама способность:
     * [network] ловит тех, чей единственный исполнитель зовёт модель, назвавшись здешним.
     * У действия своего круга этот ответ погашен — значит, правду про уход наружу сказать
     * больше некому, кроме исполнителя: он обязан назвать себя вторым устройством
     * (`RealizerKind.REMOTE`) либо объявить `RealizerMeta.leavesCircle`. Пометить этим
     * признаком облачную работу ради одной лишь нерекламы — значит молча снять с неё вопрос
     * человеку.
     */
    val localOnly: Boolean = false,

    /**
     * Результат ложится на то устройство, которое действие исполнило (#1034, #1106).
     *
     * Обычно исполнитель — свойство исполнения: кого позвать, решает Resolver, и человеку
     * всё равно, чьими руками сделано, — результат он получает там, где нажал. Но у части
     * действий результат остаётся у исполнителя: ссылка ложится в его буфер, бумага выходит
     * из его принтера. Для таких способностей сосед исполнителем не годится, даже когда он
     * единственный и лучший: «кто нажал, тот и получает» (решение владельца 21.08.2026).
     *
     * Своего исполнителя нет или он отказал — говорится причина отказа, а не подмена
     * устройства: человек просил ссылку здесь, а не доставку файла на компьютер.
     */
    val resultStaysHere: Boolean = false,

    /**
     * Вопрос знания, на который отвечает это действие, — когда он не совпадает с id (#1119).
     *
     * «Считать QR» (read-qr) даёт то, что уже добыто исследованием qr-content: ранжирование
     * опускает отвеченный вопрос вниз (#1152), но сверяет его по id действия — и действие с
     * другим id стояло как новое над уже показанным содержимым. Здесь действие называет свой
     * вопрос само; null — вопрос совпадает с id, как у большинства.
     */
    val answers: com.point.core.model.CapabilityId? = null,

    /**
     * Исследовательская Capability — её результат это знание в Graph, а не новый объект или
     * внешний эффект (ADR-0001 §11).
     *
     * Механизм у неё общий с пользовательским действием, поэтому различие объявляется здесь:
     * ни `produces`, ни `yields`, ни `intents` его выразить не могут — у `Понять` они те же.
     * Planner такие Capability человеку не предлагает, и наружу они не рекламируются.
     */
    val investigation: Boolean = false,

    /**
     * Что действие потенциально принесёт (ADR-0001 §11 — «что потенциально получается»).
     *
     * Discovery ranking пользуется этим, чтобы не запускать дорогое исследование, которое
     * ничего не откроет.
     */
    val mayYield: Set<com.point.core.model.Feature> = emptySet(),

    val mayYieldKinds: Set<com.point.core.model.ObjectKind> = emptySet(),

    /**
     * Действие достаёт то, что было внутри, а не делает новое (#946).
     *
     * Распаковка архива, страницы документа, вложения набора: объект был внутри исходника, и
     * связь между ними — «содержит». Всё остальное — «получено из»: запись, сделанная из
     * текста, внутри текста не лежала.
     *
     * Решение владельца 13.08.2026: связи разные и в графе не сливаются.
     */
    val revealsInside: Boolean = false,

    /**
     * Шаг кончается чужим экраном: Point отдал человека системе, и дальше работу делает он
     * сам — в календаре, в карточке контакта, на карте, в диалоге «Поделиться» (#1131).
     *
     * Подпись такого шага говорит о том, что сделал Point, а возврат в Point без результата
     * её гасит: это отмена человека, а не ошибка. Признак принадлежит действию, а не экрану:
     * список id в UI знал календарь и визитку и не знал «Сохранить контакт», который уводит
     * в то же приложение контактов, — его подпись висела над объектом вечно.
     */
    val handsOff: Boolean = false,

    /**
     * Действие судит об объекте по тому, что о нём известно, — и его ответ есть приговор
     * объекту, а не операции (#1060).
     *
     * Обычный шаг делает своё дело — скопировать, отправить, открыть, — и знание ему нужно
     * лишь настолько, чтобы шаг вообще предлагался. А «Понять» отвечает про сам объект, и
     * вынесенное по недобытому знанию «разобрать нечего» — неправда: снимок ещё читался,
     * человек уже получил отказ, и через минуту над этим отказом встали сто двадцать
     * прочитанных адресов.
     *
     * Признак принадлежит действию, а не экрану. Сравнение id в UI знало бы одно имя, и
     * следующее судящее действие получило бы тот же дефект молча.
     */
    val judgesKnowledge: Boolean = false,
)

enum class Cost { FREE, LOCAL, PAID }

enum class Latency { INSTANT, FAST, SLOW }
