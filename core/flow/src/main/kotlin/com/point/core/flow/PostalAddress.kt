package com.point.core.flow

import com.point.core.model.Provenance

/**
 * Адрес офлайновым правилом формы — второй читатель «куда» (#262, кадры 12 и 14 корпуса).
 *
 * **Зачем.** До сих пор адресом считалось ровно то, что назвал извлекатель сущностей (ML Kit).
 * Замер корпуса поймал его на молчании: на скрине карты Новой Пошты в дословном выводе устройства
 * стоит `Бритвка, Центральна, 586` — населённый пункт, улица и номер дома, всё на одной строке, —
 * и адресом это не признано. Не потому, что там нечего читать, а потому, что модель извлекателя
 * знает адрес в западной записи («12 Main St, Springfield»), а здесь его пишут иначе: улицу
 * называют без слова «вулиця», а дом ставят последним через запятую.
 *
 * **Правило читает СТРУКТУРУ, а не названия.** Словаря топонимов здесь нет и не будет — он врёт
 * ровно там, где название нестандартное, и его ошибку нечем поймать. Форм ровно две, и каждая
 * держится на своём структурном признаке:
 *
 * | форма | чем допущена | кадр |
 * |---|---|---|
 * | `<пункт>, <улица>, <дом>` | последняя часть — номер дома, все прочие — **имена собственные** без цифр | 12 (`Бритвка, Центральна, 586`) |
 * | `<пункт>, <административная единица>` | последнее слово — «обл.», «область», «район», «р-н», «округ» | 14 (`Новониколаевка, Запорожская обл.`) |
 *
 * Слово улицы («вул.», «просп.») формой не требуется — на кадре 12 его нет вовсе, — но если оно
 * есть, дома в строке может и не быть: `вул. Сонячна, 15` опознаётся своим маркером.
 *
 * **Правило размечает, а не решает.** Улика ровно одна ([EvidenceClass.SEMANTIC]), происхождение
 * `ocr` (значение взято со страницы дословно), человек видит «возможно» — та же порода, что
 * [meterReadings] и [geoPoints]. Названный остаточный класс ложных: «Доставка, Київський район» и
 * «Іванов, Петренко, 300» — имена собственные, и от адреса формой они не отличаются вовсе. Цена
 * такой ошибки — лишний пузырёк карты и строка в «Point понял»; цена молчания была выше —
 * действие кадра не ехало никуда.
 *
 * **Правило — второй читатель, а не спорщик.** Зовёт его `entityDelta` (энричер сущностей) только
 * там, где извлекатель промолчал: два писателя одного ключа в одной волне обогащения гонялись бы
 * за значение, и человек видел бы то один адрес, то другой.
 *
 * **Названная граница кадра 14.** На нём эта форма напечатана, но экран обрезал её многоточием:
 * дословно устройство читает `Новониколаевка, Запорожская о...`, и «обл.» в тексте попросту нет.
 * Достраивать «о…» до «область» правило не будет — это гадание, а не чтение. Путь такого кадра —
 * «Понять» по пикселям (контрактный ключ `PLACE`, [META_ENTITY_PLACE]), и он уже есть.
 */

/** Ключ адреса как факта объекта. Тот же, что пишет извлекатель сущностей и «Понять» (`ADDRESS`). */
const val META_ENTITY_ADDRESS = META_ENTITY_PREFIX + "address"

/**
 * Адресные строки [text] в порядке появления, дословно — снят только краевой мусор OCR
 * ([ADDRESS_EDGE_NOISE]: иконка пина, палки, стрелки). Пусто — обычный случай, и в нём вся
 * дешевизна правила.
 */
fun addressLines(text: String): List<String> =
    text.lineSequence()
        .map { it.replace(ADDRESS_EDGE_NOISE, "").trim() }
        .filter { addressForm(it) != null }
        .distinct()
        .toList()

/**
 * Краевой мусор вокруг строки: иконки, палки, стрелки — всё, что не буква и не цифра.
 *
 * **Кроме точки на конце.** Это не мусор, а точка сокращения: «Запорожская обл.» без неё
 * перестаёт быть тем, что напечатано. Мерка тут своя, а не общая с [expandAddressToLine], ровно
 * из-за этой одной точки — там значение уже названо извлекателем, здесь оно рождается правилом.
 */
private val ADDRESS_EDGE_NOISE = Regex("""^[^\p{L}\p{Nd}]+|[^\p{L}\p{Nd}.]+$""")

/**
 * Адрес как факты объекта: значение, происхождение и улика формы. Второй адрес на странице
 * (место отправления и место доставки на одном экране) — в `entity.address.more`: конвенция
 * `.more` (#260) не даёт подтверждению первого стереть запись о втором.
 */
fun addressFacts(text: String): Map<String, String> {
    val lines = addressLines(text)
    val first = lines.firstOrNull() ?: return emptyMap()
    return buildMap {
        put(META_ENTITY_ADDRESS, first)
        // ПРОЧИТАНО: строка взята со страницы дословно, а не выведена (#264).
        put(META_ENTITY_ADDRESS + META_SOURCE_SUFFIX, Provenance.OCR.wire)
        // Улика ровно одна — форма, и считает её [formEvidence] — та же функция, что судит
        // чтение модели. Два счётчика улик разъехались бы на первой правке (#262).
        put(
            META_ENTITY_ADDRESS + META_EVIDENCE_SUFFIX,
            formEvidence(META_ENTITY_ADDRESS, first).joinToString(",") { it.name.lowercase() },
        )
        if (lines.size > 1) put(META_ENTITY_ADDRESS + META_MORE_SUFFIX, altValue(lines))
    }
}

/** Чем строка допущена к званию адреса — или `null`, если ничем. */
internal enum class AddressForm {
    /** `<пункт>, <улица>, <дом>` — последняя часть номер дома либо в строке есть слово улицы. */
    STREET,

    /** `<пункт>, <административная единица>` — «обл.», «область», «район», «р-н», «округ». */
    AREA,
}

/**
 * Форма строки. Общие для обеих форм ограничения — не вкус, а защита от прозы: у адреса частей
 * через запятую немного ([MAX_ADDRESS_PARTS]), каждая короткая ([MAX_PART_WORDS] слова), и пустых
 * среди них нет («Если вас не затруднит,» — предложение, а не адрес).
 */
internal fun addressForm(line: String): AddressForm? {
    if (line.length > MAX_ADDRESS_LINE) return null
    val parts = line.split(',').map { it.trim() }
    if (parts.size < 2 || parts.size > MAX_ADDRESS_PARTS) return null
    if (parts.any { it.isEmpty() || it.words().size > MAX_PART_WORDS }) return null

    val head = parts.dropLast(1)
    val last = parts.last()
    // Части-названия: буквы есть, цифр нет. Названием обязаны быть ВСЕ, кроме последней, —
    // иначе «Оплата 120.00 грн, чек 4402, вул. Сонячна, 15» стало бы адресом целиком.
    if (!head.all { it.isNamePart() }) return null
    // …и названием СОБСТВЕННЫМ ([isProperName], ревью #262) — либо частью со словом улицы.
    if (!head.all { it.isProperName() || it.hasStreetMarker() }) return null

    if (last.words().lastOrNull()?.isAreaMarker() == true) return AddressForm.AREA
    // Дом последним — форма кадра 12: слова улицы в ней нет, зато перед домом стоят и пункт,
    // и улица. Одного названия перед домом мало: «Паринкн Виктор, 300» — это цена в переписке.
    if (HOUSE_NUMBER.matches(last) && (head.size >= 2 || head.any { it.hasStreetMarker() })) {
        return AddressForm.STREET
    }
    // Слово улицы держит форму само: «вул. Сонячна, 15» ML Kit отдаёт именно так (#236).
    if (parts.any { it.hasStreetMarker() } && last.isNamePart()) return AddressForm.STREET
    return null
}

/** Столько знаков — уже не адресная строка, а предложение с запятыми. */
private const val MAX_ADDRESS_LINE = 96

/** Пункт, улица, дом и, редко, ещё одно уточнение. Пятая часть — перечисление, а не адрес. */
private const val MAX_ADDRESS_PARTS = 4

/** «Білгород-Дністровський» — одно слово, «вул. Івана Мазепи» — три. Четыре — уже фраза. */
private const val MAX_PART_WORDS = 3

/** Название: буквы есть, цифр нет. Три буквы подряд — тот же порог, что у [isPlausible]. */
private fun String.isNamePart(): Boolean =
    none(Char::isDigit) && LETTER_RUN.containsMatchIn(this)

/**
 * Имя собственное, а не просто слово без цифр: хотя бы одно слово части начинается с заглавной
 * («м. Павлоград» — да, «до сплати» — нет). Заглавная буква — единственный структурный признак,
 * которым топоним отличается от нарицательного слова, и словаря он не требует: правило
 * по-прежнему не знает ни одного названия.
 *
 * **Зачем признак понадобился** (ревью #262). Без него формой `<пункт>, <улица>, <дом>` был
 * допущен вообще любой ряд «слово, слово, небольшое число» — то есть строка прайса
 * (`Цукор, пачка, 25`), итог чека (`Разом, до сплати, 250`), шапка таблицы (`Дата, номер, 2026`)
 * и любая строка CSV с двумя текстовыми колонками и числом. Названный остаточный класс ложных
 * оказывался в разы шире объявленного, а цена — выше «лишнего пузырька»: `text/csv` для Point
 * обычный текстовый объект, разбор таблиц — самое частое, чем его кормят, и ложный адрес уезжал
 * оттуда и в «Point понял», и в готовность «Построить маршрут», и в граф объектов отдельным узлом.
 *
 * Проверяется **первая буква слова**, а не первый символ: OCR приносит кавычки и скобки, а
 * ««Павлоград»» — то же имя собственное. Часть со словом улицы от требования свободна: «вул.
 * Сонячна» начинается со строчной, но названа маркером ([hasStreetMarker]).
 */
private fun String.isProperName(): Boolean =
    words().any { w -> w.firstOrNull(Char::isLetter)?.isUpperCase() == true }

private val LETTER_RUN = Regex("""\p{L}{3,}""")

private fun String.words(): List<String> = split(SPACES).filter { it.any(Char::isLetterOrDigit) }

private val SPACES = Regex("""\s+""")

/**
 * Номер дома, как его печатают: `15`, `58б`, `12А`, `7/2`, `№ 39`. Больше четырёх цифр — это уже
 * не дом, а сумма, индекс или год. Точка на конце — конец предложения, а не другая форма дома:
 * её [ADDRESS_EDGE_NOISE] оставляет ради «обл.», и обрывать на ней чтение адреса было бы обидно.
 */
private val HOUSE_NUMBER = Regex("""(?iu)(?:№\s?)?\d{1,4}\s?\p{L}?(?:\s?[/-]\s?\d{1,3}\s?\p{L}?)?\.?""")

/**
 * Слово административной единицы — **целым токеном**, а не куском слова: «в нашем районе» не
 * должно объявлять адресом полстроки переписки. Точки и запятые токен не занимают, а [foldOcr]
 * снимает букву, которую распознавание ест («області» приходит как «обпасті», «областi»).
 */
private fun String.isAreaMarker(): Boolean =
    foldOcr(trim { !it.isLetterOrDigit() && it != '-' }) in FOLDED_AREA_MARKERS

/** Список сознательно короткий и дословный: каждая новая строка — новый способ ошибиться
 *  (тот же порядок, что у единиц учёта в [meterReadings] — добавлять с живым кадром в руках). */
private val AREA_MARKERS = listOf("обл", "область", "області", "области", "р-н", "район", "округ")

private val FOLDED_AREA_MARKERS = AREA_MARKERS.map(::foldOcr).toSet()

/**
 * Слово улицы. Сравнение стемами и через [foldOcr] — форм много («вулиця», «вул.», «ул.»), а OCR
 * к тому же ест буквы; тот же приём, что у слов-маркеров трека ([looksLikeTrackMarker]).
 * Сравнение **потокенно**: «вул» внутри слова «Павул» маркером не является.
 */
private fun String.hasStreetMarker(): Boolean =
    words().any { w -> foldOcr(w).trim { !it.isLetterOrDigit() } in FOLDED_STREET_MARKERS }

private val STREET_MARKERS = listOf(
    "вул", "вулиця", "ул", "улица", "просп", "проспект", "пров", "провулок", "переулок",
    "бульв", "бул", "бульвар", "площа", "площадь", "майдан", "наб", "набережна", "набережная",
    "шосе", "шоссе", "проїзд", "проезд",
)

private val FOLDED_STREET_MARKERS = STREET_MARKERS.map(::foldOcr).toSet()
