package com.point.core.flow

import com.point.core.model.CapabilityId

/**
 * Имена способностей, которые знают оба устройства (#840).
 *
 * Конституция (§ «Capability / Realizer»): «Устройство — свойство исполнения, пока результат
 * для человека один и тот же». Имя способности — это и есть то, чем результат называется;
 * если телефон зовёт поиск значений `entities`, а компьютер — `pc-entities`, то для Point
 * это два разных вопроса об одном и том же.
 *
 * Цена расхождения не теоретическая: Investigation State живёт по паре «объект +
 * capabilityId». Объект, у которого компьютер уже нашёл значения, приезжает на телефон — и
 * там вопрос числится неисследованным. Знание о проделанной работе теряется ровно так же,
 * как теряется само знание, если его не везти (#811).
 *
 * Здесь только те имена, которые называют одну работу на обеих сторонах. Действие, чей
 * результат зависит от места (бумага, окно, файл в проводнике), остаётся своим — это
 * разрешено той же нормой.
 */
object KnownCapabilities {

    /** Найти в тексте значения: телефоны, адреса, даты, номера. */
    val ENTITIES = CapabilityId("entities")

    /** Прочитать речь словами. */
    val TRANSCRIBE = CapabilityId("transcribe")

    /** Прочитать слова с кадра. */
    val OCR = CapabilityId("ocr")

    /**
     * Вопрос «что написано на этом кадре» — исследование чтения.
     *
     * Id жил только в `:data` (OcrInvestigation), но состояние этого вопроса ставит и
     * сильное чтение из `:executors` (#1097): знание одно, и имя вопроса у него одно.
     */
    val IMAGE_TEXT = CapabilityId("image-text")

    /**
     * Прочитать сканированный документ постранично.
     *
     * Имя стояло голым литералом в двух файлах — телефонном и компьютерном (#1254). Опечатка
     * в одном из них превратила бы одну работу в две: знание живёт по паре «объект +
     * capabilityId», и документ, прочитанный на компьютере, приехал бы на телефон
     * непрочитанным.
     */
    val READ_DOCUMENT = CapabilityId("read-document")
}
