package com.point.core.flow

/**
 * Пределы, которые человек чувствует, — по одному месту (#861).
 *
 * Каждое из этих чисел — обещание: объект тяжелее просто не поедет. Записанные по копии на
 * устройство, они разъезжаются молча, и человек получает «на телефоне работает, на
 * компьютере нет» без единого слова о том, почему.
 */

/** Сколько весит объект, который ещё можно отдать ссылкой. */
const val MAX_DROP_BYTES = 50L * 1024 * 1024

/** Сколько весит запись, которую ещё берут на расшифровку. */
const val MAX_SPEECH_BYTES = 25L * 1024 * 1024

/**
 * Предел одного действия (#1069): дольше — честный отказ, а не вечное «Идёт».
 *
 * Щедрый нарочно: таблица на эмуляторе строится минутами, облачный скан — тоже, и предел
 * должен резать только зависание, а не работу. Жил у экрана, но обещание это общее: работа,
 * которая хочет уложиться в потолок, обязана знать его из того же места, а не переписывать
 * себе десять минут по памяти (#1243).
 */
const val ACTION_CEILING_MS = 10L * 60 * 1000

/**
 * Сколько страниц набора превращается в таблицу за один заход (#1243).
 *
 * Каждая страница — это отдельные облачные чтения. Без предела набор из сотни снимков
 * упирался в потолок действия и пропадал целиком: файла нет, а бесплатная квота на уже
 * прочитанные страницы потрачена. Это предел цены захода: сколько облачных чтений человек
 * оплатит ожиданием и квотой за один тап. Страницы за ним не пропадают молча — они помечены
 * в самой таблице.
 */
const val MAX_TABLE_PAGES = 20

/**
 * Сколько времени заход «В Excel» читает страницы набора (#1243).
 *
 * Предел страниц — про цену, этот — про время, и одним другой не заменяется: сколько минут
 * уйдёт на страницу, решают чужие бесплатные провайдеры, а не Point. Потолок действия
 * отменяет работу целиком и файла из-под себя не отдаёт — значит, чтение обязано кончиться
 * раньше него само, с уже прочитанным на руках. Остаток до потолка — на сборку и запись
 * файла: человек получает таблицу из тех страниц, за которые уже заплатил.
 */
const val TABLE_READ_BUDGET_MS = ACTION_CEILING_MS - 60_000L

/**
 * Во сколько раз уменьшать снимок, чтобы длинная сторона стала не больше `maxPx`.
 *
 * Считается делением пополам, потому что этого и ждёт декодер: он умеет пропускать пиксели
 * только кратно двум. Цикл был вписан руками и в `Bitmaps`, и в `TesseractTextRecognizer` —
 * арифметика чистая, Android ей не нужен.
 */
fun sampleSizeFor(width: Int, height: Int, maxPx: Int): Int {
    if (maxPx <= 0) return 1
    var sample = 1
    var longEdge = maxOf(width, height)
    while (longEdge / 2 >= maxPx) {
        longEdge /= 2
        sample *= 2
    }
    return sample
}
