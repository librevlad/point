package com.point.core.flow

/**
 * Буфер круга устройств: скопированное здесь ждёт человека и на другом его устройстве (#611).
 *
 * Сценарий владельца, дословно: PDF на телефоне → Point понимает номер карты → «Скопировать» →
 * человек садится за компьютер и **вставляет**. Между «скопировал» и «вставил» не должно быть ни
 * одного лишнего движения: ни «отправить», ни «забрать», ни плитки в шторке.
 *
 * **Почему отдельный контракт, а не вызов синхронизации прямо из действия.** «Скопировать» живёт в
 * чистом Kotlin и о сети знать не должно; здесь у него ровно одна фраза — «вот значение, оно может
 * пригодиться на другом устройстве». Есть ли круг, дозвонились ли, чем шифровать — забота
 * реализации.
 *
 * **Тихая работа.** [offer] ничего не обещает и ни на что не влияет: не дошло — человек всё равно
 * скопировал у себя, и говорить ему об этом нечего. Отказ здесь не событие продукта.
 *
 * **Границы.** Это круг устройств одного человека, объект не покидает его и едет запечатанным —
 * поэтому согласия не требуется (контракт 06.08.2026, граница молчаливого выбора). Умолчание —
 * ничего не делать: сборка без круга ведёт себя как раньше.
 */
fun interface CircleClipboard {

    /** Положить значение в буфер круга. Тихо: исход человеку не показывается. */
    suspend fun offer(text: String)

    companion object {
        /** Круга нет — и предлагать некому. */
        val None = CircleClipboard { }
    }
}
