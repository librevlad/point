package com.point.core.flow

import com.point.core.model.PointObject

/**
 * Внешний глаз — чужой сервис, который читает страницу целиком (#280).
 *
 * **Почему это НЕ [LlmClient].** Специальная OCR-ручка промпта не принимает: она не отвечает на
 * вопрос, а разбирает страницу и отдаёт её текст. Поставь такой сервис в общую цепочку моделей — и
 * «Понять», «Перевести», «В Excel» на снимке получили бы вместо ответа расшифровку страницы, молча
 * и с виду успешно. Отдельный контракт стоит ровно на защите от этого: внешний глаз зовут только
 * там, где просят прочитать текст.
 *
 * **Почему это НЕ [AtomRecognizer].** Тот отдаёт текст **с местом на странице** — на нём стоит слой
 * улик (#257), и пустой слой атомов там законно значит «прочитал и ничего не нашёл». Внешний глаз
 * геометрии не даёт вовсе, и подсунуть его в ту цепочку значило бы либо выдумать координаты, либо
 * всегда проигрывать её правилу «непустой слой выигрывает».
 *
 * **Бросает, а не молчит.** Не дошёл (нет ключа, кончилось бесплатное, сеть) — исключение, которое
 * вызывающий обязан показать человеком отказом. Пустая строка неотличима от пустой страницы, и
 * подмена одного другим — та самая тихая ложь, ради которой заведён сторож [degeneratedReading].
 */
interface ExternalEye {

    /**
     * Есть ли кому читать **на выбранном уровне приватности**.
     *
     * Не «настроен ли ключ»: на уровне «только на телефоне» ключи могут быть все, а глаза нет ни
     * одного — и это законный ответ, а не сбой.
     */
    fun available(): Boolean

    /** Прочитать страницу. Бросает, если ни один глаз не дошёл. */
    suspend fun read(obj: PointObject): ExternalReading
}

/**
 * Что прочитал внешний глаз — и **кто именно**.
 *
 * Имя читателя едет вместе с текстом не для красоты: происхождение значения должно быть видно
 * человеку. Дальше оно ложится в метаданные объекта рядом с текстом, как `engine=on-device` у
 * телефонного движка.
 */
data class ExternalReading(
    val text: String,
    /** Имя читателя для метаданных и текста отказа: `mistral-ocr`. */
    val reader: String,
    /** Куда уезжал кадр, словами человека: «Mistral, Франция (ЕС)». */
    val where: String,
)
