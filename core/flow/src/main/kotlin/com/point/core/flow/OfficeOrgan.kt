package com.point.core.flow

/**
 * Орган, который превращает офисный документ в PDF слайд в слайд (#403).
 *
 * Телефон этого органа не имеет и иметь не будет: его собственный путь был пересказом —
 * из документа вынимался текст и печатался заново. Для договора терпимо, для презентации
 * бессмысленно, а называлось это тем же словом, что и настоящая конвертация на компьютере.
 *
 * Это не устройство в Capability (ADR-0001 §7): результат для человека один и тот же
 * документ, и выбирает он действие, а не исполнителя. Орган решает только одно — есть ли
 * сегодня чем это сделать, и если нет, то чего именно не хватает.
 */
fun interface OfficeOrgan {

    /** `null` — орган есть; иначе — чего не хватает, человеческими словами. */
    fun missing(): String?
}

/** Компьютера нет вовсе — или он не на связи. */
const val NO_PC_WITH_OFFICE = "нужен компьютер с офисом"

/** Компьютер есть, офиса на нём нет — случай, который человек может исправить сам. */
const val NO_OFFICE_ON_PC = "на компьютере нет офиса"

/** Орган на месте: так его видят компьютер и тесты, которым про офис ничего не важно. */
val OfficeAlwaysHere = OfficeOrgan { null }
