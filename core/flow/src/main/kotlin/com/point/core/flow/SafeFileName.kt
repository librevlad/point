package com.point.core.flow

/**
 * Имя, пришедшее снаружи, в путь не годится (#865).
 *
 * Имя файла Point почти всегда получает от кого-то другого: от приложения, которое им
 * поделилось, от сервера, из каталога архива. Что там лежит, решает не Point — а имя тут же
 * становится частью пути, по которому пишется копия объекта.
 *
 * Правило это в проекте знали и раньше — в `KeptLetters` оно записано прямо словами: «Имя
 * письма приходит с сервера — писать по нему куда попало нельзя». Только выполнено оно было
 * пятью разными способами в пяти местах, а в шестом — приёме нескольких файлов разом — не
 * выполнено вовсе. Именно там имя приходит от чужого приложения через системный Share.
 *
 * Что делается и почему:
 *
 * - путь отбрасывается целиком (`Camera/IMG_1.jpg` → `IMG_1.jpg`) — иначе копия уезжает мимо
 *   scratch, а конституция говорит «объект немедленно копируется в scratch при приёме»;
 * - запрещённые файловым системам знаки и управляющие символы заменяются пробелом, а не
 *   выбрасываются: имя остаётся читаемым человеку, а не слипается в кашу;
 * - ведущие точки убираются — так `..` перестаёт быть шагом вверх, а скрытое имя не
 *   заводится молча;
 * - длина ограничивается: слишком длинное имя не создаёт файл вовсе, а обрывает приём.
 *
 * Пустое имя — не ошибка человека, а отсутствие имени: объект получает своё слово, а не
 * падение.
 */
fun safeFileName(raw: String, ifBlank: String = "объект"): String {
    val cleaned = raw
        .replace('\\', '/')
        .substringAfterLast('/')
        .map { if (it.code < 0x20 || it.code == 0x7F || it in FORBIDDEN_IN_NAME) ' ' else it }
        .joinToString("")
        .replace(SPACES, " ")
        .replace(" .", ".")
        .trim(' ', '.')
        .take(MAX_FILE_NAME)
        .trim(' ', '.')
    return cleaned.ifBlank { ifBlank }
}

private const val FORBIDDEN_IN_NAME = ":*?\"<>|…"

private val SPACES = Regex("""\s+""")

/**
 * Предел длины имени. Файловые системы держат 255 байт, но к имени ещё дописываются
 * расширение и суффикс уникальности — предел взят с запасом на них.
 */
const val MAX_FILE_NAME = 120
