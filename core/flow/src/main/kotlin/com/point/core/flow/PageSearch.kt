package com.point.core.flow

/**
 * Одно найденное место на странице (#279): **адрес**, а не номер строки.
 *
 * Найденное — это те же атомы, что захватывает палец в выделении ([SnappedSelection]) и что
 * называет моделью ответ ([AtomAddress.ByIds]). Поиск ничего нового про адресацию не заводит:
 * запрос печатает человек, а место на странице по-прежнему называется набором слов и рамкой.
 */
data class PageMatch(
    /** Захваченные слова в порядке чтения строки. */
    val atoms: List<Atom>,
    /** Рамка находки в координатах сырого кадра — то, что экран подсвечивает. */
    val region: Box,
) {
    /** Метки слов — тот же долговечный адрес, что у выделения и у ответа модели. */
    val ids: List<String> get() = atoms.map { it.id }

    /** Слова находки как они прочитаны — дословно, без свёртки. */
    val text: String get() = atoms.joinToString(" ") { it.text }
}

/**
 * Где на странице лежит [query] (#279).
 *
 * **Правила сравнения — те же, что у свода чтений**: [normConsensus]. Это сознательно, а не для
 * экономии. Свод решает, читают ли два ридера одно и то же; поиск решает, то же ли самое искал
 * человек и написал документ. Вопрос один, и разные ответы на него означали бы, что Point
 * считает «20 842» и «20842» одним числом, когда голосует, и разными — когда ищет. Отсюда всё
 * поведение: регистр, пробелы, дефисы, точки и кавычки различием не считаются, а разрядный
 * пробел внутри числа складывается как оформление; зато пропавшая запятая — другое число, и
 * «1,0» по запросу «10» не находится (урок #294 — тихая ошибка дороже ненайденного).
 *
 * Никакого нечёткого поиска «на глазок»: ни расстояния Левенштейна, ни ремонта букв
 * ([isRepairOf] здесь не участвует). Ремонт живёт там, где два источника читают ОДНО место и
 * спорят; здесь второго чтения нет — есть страница и слово человека. «Похоже на то, что вы
 * искали» на странице, где этого слова нет, — ровно та подмена, которую Point запрещает.
 *
 * Ищется **в пределах строки** ([AtomLayer.lines], то есть по геометрии, а не по порядку выдачи
 * движка): находка, начавшаяся в конце одной строки и продолжившаяся в начале следующей, —
 * утверждение про страницу, которого на странице нет.
 *
 * Запрос, в котором нечего искать ([isSearchable]), — пусто, и это «ещё не искали», а не «не
 * нашлось»: сказать «ничего не нашлось» в ответ на пустое поле было бы враньём.
 */
fun AtomLayer.findOnPage(query: String, page: Int = 0): List<PageMatch> {
    if (!isSearchable(query)) return emptyList()
    val needle = normConsensus(query)
    return lines(atoms.filter { it.page == page })
        .flatMap { line -> matchesInLine(line, needle) }
        // Место — то, на что можно показать пальцем. Два вхождения внутри одного слова
        // («мамамама» по запросу «мама») подсветятся одной рамкой, и счёт «2» рассказывал бы
        // про комбинаторику, а не про страницу: сколько подсвечено — столько и нашлось.
        .distinctBy { it.ids }
}

/**
 * Вхождения [needle] в одной строке страницы.
 *
 * Свёртка считается по атомам, а не по склеенной строке, ровно затем, чтобы каждый символ помнил
 * своё слово: находка обязана вернуть адрес (метки атомов), а не только координаты. Пробелы между
 * словами в стог не кладутся сознательно — [normConsensus] их и так не считает различием, и
 * запрос «Иванов И.» обязан находиться, когда движок разорвал строку на два атома.
 */
private fun matchesInLine(line: List<Atom>, needle: String): List<PageMatch> {
    val hay = StringBuilder()
    val owner = ArrayList<Int>()
    line.forEachIndexed { index, atom ->
        val folded = normConsensus(atom.text)
        hay.append(folded)
        repeat(folded.length) { owner.add(index) }
    }
    val text = hay.toString()
    val found = mutableListOf<PageMatch>()
    var from = 0
    while (from <= text.length - needle.length) {
        val at = text.indexOf(needle, from)
        if (at < 0) break
        val hit = (at until at + needle.length).map { owner[it] }.distinct().map { line[it] }
        found += PageMatch(hit, hit.map { it.box }.reduce(Box::union))
        // Следующее вхождение ищется за найденным: перекрывающиеся совпадения — это одно место
        // на странице, посчитанное дважды.
        from = at + needle.length
    }
    return found
}

/**
 * Есть ли в запросе что искать (#279).
 *
 * Строка из одного оформления — «—», «...», пробелы — складывается [normConsensus] в пустоту, и
 * поиска по ней не бывает. Это **«ещё не искали»**, а не «не нашлось»: правило одно и живёт в
 * одном месте, поэтому экран молчит ровно тогда, когда [findOnPage] отказывается искать.
 */
fun isSearchable(query: String): Boolean = normConsensus(query).isNotEmpty()

/**
 * Что сказать человеку про число находок (#279).
 *
 * Живёт рядом с поиском, а не в экране, потому что ответ обязан быть один: экран показывает
 * места, реализатор отвечает без экрана, и разъехавшиеся формулировки означали бы, что у Point
 * два мнения о том, что он нашёл.
 */
fun foundOnPageLabel(matches: Int): String =
    if (matches == 0) "Ничего не нашлось" else "Нашлось $matches ${placesWord(matches)}"

/** «место / места / мест» — по-русски, а не «мест(а)»: число видит человек, а не разработчик. */
private fun placesWord(n: Int): String {
    val hundred = n % 100
    val ten = n % 10
    return when {
        hundred in 11..14 -> "мест"
        ten == 1 -> "место"
        ten in 2..4 -> "места"
        else -> "мест"
    }
}
