package com.point.core.flow

/**
 * Одно найденное место на странице (#279): **адрес**, а не номер строки.
 *
 * Найденное — это те же атомы, что захватывает палец в выделении ([SnappedSelection]) и что
 * называет моделью ответ ([AtomAddress.ByIds]). Поиск ничего нового про адресацию не заводит:
 * запрос печатает человек, а место на странице по-прежнему называется набором слов и рамкой.
 */
data class PageMatch(
    /** Захваченные слова в порядке чтения строки. */
    val atoms: List<Atom>,
    /** Рамка находки в координатах сырого кадра — то, что экран подсвечивает. */
    val region: Box,
) {
    /** Метки слов — тот же долговечный адрес, что у выделения и у ответа модели. */
    val ids: List<String> get() = atoms.map { it.id }

    /** Слова находки как они прочитаны — дословно, без свёртки. */
    val text: String get() = atoms.joinToString(" ") { it.text }
}

/**
 * Где на странице лежит [query] (#279).
 *
 * **Обещание одно: что напечатано на странице — находится, если это напечатанное набрать.**
 * Отсюда все правила сравнения, и они те же, что у свода чтений ([normConsensus]) по смыслу:
 * регистр, пробелы, дефисы, кавычки и точка-запятая вне числа различием не считаются, разрядный
 * пробел внутри числа — оформление («20 842» находится по «20842»), а пропавшая запятая — другое
 * число, и «1,0» по запросу «10» **не находится** (урок #294 — тихая ошибка дороже ненайденного).
 *
 * **Свёртку поиск считает своей** ([foldForSearch]), и это не разночтение со сводом, а разница
 * задач. Свод сравнивает два чтения **целиком**: он смотрит на токен, решает «это число» и
 * канонизирует его как число. Поиск ищет **кусок внутри строки**, и целостная свёртка на такой
 * работе разъезжается сама с собой: страница складывается по атому, запрос — целиком, и правило
 * «это число» срабатывает на них по-разному. Замер на слоях корпуса (прогон 03.08.2026,
 * `corpus-0803` + `tab-*`): 70 из 1571 соседних пар слов, **напечатанных на странице**, не
 * находились по дословному запросу — «ВЙСЬКТОРГ 78.00» из таблицы договоров, «24.18 мин.» из
 * маршрута, «30.03 Михайло-Лукашеве» из посылки. Хуже того, правило #294 в такой паре
 * переворачивалось: внутри «127*4.32=548,64» сумма «548,64» не находилась собой, зато находилась
 * по «54864» — ровно та тихая ошибка, ради которой правило и написано.
 *
 * Поэтому свёртка здесь **посимвольная**: она решает про символ, а не про токен, и потому
 * переживает и разрез строки на атомы, и поиск куска. Обещания #294 она не смягчает — наоборот,
 * держит их и там, где число слиплось с соседним знаком.
 *
 * Никакого нечёткого поиска «на глазок»: ни расстояния Левенштейна, ни ремонта букв
 * ([isRepairOf] здесь не участвует). Ремонт живёт там, где два источника читают ОДНО место и
 * спорят; здесь второго чтения нет — есть страница и слово человека. «Похоже на то, что вы
 * искали» на странице, где этого слова нет, — ровно та подмена, которую Point запрещает.
 *
 * Ищется **в пределах строки** ([AtomLayer.lines], то есть по геометрии, а не по порядку выдачи
 * движка): находка, начавшаяся в конце одной строки и продолжившаяся в начале следующей, —
 * утверждение про страницу, которого на странице нет.
 *
 * Запрос, в котором нечего искать ([isSearchable]), — пусто, и это «ещё не искали», а не «не
 * нашлось»: сказать «ничего не нашлось» в ответ на пустое поле было бы враньём.
 */
fun AtomLayer.findOnPage(query: String, page: Int = 0): List<PageMatch> {
    val needle = foldForSearch(query)
    if (needle.isEmpty()) return emptyList()
    return lines(atoms.filter { it.page == page })
        .flatMap { line -> matchesInLine(line, needle) }
        // Место — то, на что можно показать пальцем. Два вхождения внутри одного слова
        // («мамамама» по запросу «мама») подсветятся одной рамкой, и счёт «2» рассказывал бы
        // про комбинаторику, а не про страницу: сколько подсвечено — столько и нашлось.
        .distinctBy { it.ids }
}

/**
 * Вхождения [needle] в одной строке страницы.
 *
 * Свёртка считается по **склеенной строке**, а не по атому: движок рвёт строку где придётся, и
 * «1,0» приходит атомами «1,» и «0» так же легко, как одним куском. Свернув каждый атом отдельно,
 * страница получала бы «10» там, где напечатано «1,0», — то есть поиск сам создавал бы число,
 * которого на странице нет. Хозяин символа при этом не теряется: [foldForSearch] сообщает, из
 * какого места сырой строки пришёл каждый оставленный символ, и находка возвращает адрес (метки
 * атомов), а не только координаты.
 *
 * Пробелы между словами в стог не кладутся сознательно — свёртка их всё равно не считает
 * различием, и запрос «Иванов И.» обязан находиться, когда движок разорвал строку на два атома.
 */
private fun matchesInLine(line: List<Atom>, needle: String): List<PageMatch> {
    val raw = StringBuilder()
    val rawOwner = ArrayList<Int>()
    line.forEachIndexed { index, atom ->
        raw.append(atom.text)
        repeat(atom.text.length) { rawOwner.add(index) }
    }
    val hay = StringBuilder()
    val owner = ArrayList<Int>()
    foldForSearch(raw) { ch, at ->
        hay.append(ch)
        owner.add(rawOwner[at])
    }
    val text = hay.toString()
    val found = mutableListOf<PageMatch>()
    var from = 0
    while (from <= text.length - needle.length) {
        val at = text.indexOf(needle, from)
        if (at < 0) break
        val hit = (at until at + needle.length).map { owner[it] }.distinct().map { line[it] }
        found += PageMatch(hit, hit.map { it.box }.reduce(Box::union))
        // Следующее вхождение ищется за найденным: перекрывающиеся совпадения — это одно место
        // на странице, посчитанное дважды.
        from = at + needle.length
    }
    return found
}

/**
 * Есть ли в запросе что искать (#279).
 *
 * Строка из одного оформления — «—», «...», пробелы — складывается в пустоту, и поиска по ней не
 * бывает. Это **«ещё не искали»**, а не «не нашлось»: правило одно и живёт в одном месте,
 * поэтому экран молчит ровно тогда, когда [findOnPage] отказывается искать.
 */
fun isSearchable(query: String): Boolean = foldForSearch(query).isNotEmpty()

/**
 * Свёртка поиска: **решение про символ, а не про токен**.
 *
 * Одна и та же функция складывает и запрос человека, и строку страницы, — иначе поиск сравнивал
 * бы разными правилами то, что обязан признать одним и тем же. Посимвольность здесь несущая:
 * запрос ищется куском внутри строки, а строка склеена из атомов движка, и любое правило, которое
 * смотрит на токен целиком («это число — сложить как число»), на разрезанном входе даёт другой
 * ответ, чем на целом.
 *
 * Что считается оформлением — тот же список, что у свода чтений ([normConsensus]): регистр,
 * пробелы (включая разрядный внутри числа), тире, кавычки и маркер неуверенности «⚠». Точка и
 * запятая — оформление **вне числа** («Отправитель:», «И.») и содержание **внутри числа**: между
 * двумя цифрами разделитель остаётся и приводится к точке, поэтому «6,003» находится по «6.003»,
 * а по «6003» — нет (#294). Остальные знаки — «/», «(», «№», «!» — содержание страницы, и молча
 * стирать их поиск не имеет права.
 *
 * «Между двумя цифрами» — с точностью до оформления с обеих сторон: слева стоит последний
 * **оставленный** символ, справа пропускается пробел. Иначе одно и то же место складывалось бы
 * по-разному в запросе и на странице: человек печатает «2. 1», а движок отдаёт те же знаки двумя
 * атомами без пробела между ними.
 *
 * Разрядная **точка** («1.234,56») от разрядного пробела отличается тем, что её напечатали: чтобы
 * узнать в ней оформление, нужно смотреть на токен целиком, а такое правило снова разъедется на
 * разрезанной строке. Поэтому она остаётся содержанием — человек ищет то, что видит.
 *
 * @param onKeep вызывается на каждый оставленный символ: сам символ и его место в [raw]. Так
 * находка помнит, из какого слова пришёл каждый символ, и возвращает адрес, а не только рамку.
 */
internal fun foldForSearch(raw: CharSequence, onKeep: (Char, Int) -> Unit) {
    var prevKept: Char? = null
    for (i in raw.indices) {
        val c = raw[i].lowercaseChar()
        val kept: Char? = when {
            c.isWhitespace() || c in SEARCH_NOISE -> null
            c == '.' || c == ',' ->
                if (prevKept?.isDigit() == true && nextNonSpaceIsDigit(raw, i)) '.' else null
            else -> c
        }
        if (kept != null) {
            onKeep(kept, i)
            prevKept = kept
        }
    }
}

/** Стоит ли цифра справа от разделителя, если не считать пробелов. */
private fun nextNonSpaceIsDigit(raw: CharSequence, at: Int): Boolean {
    var j = at + 1
    while (j < raw.length && raw[j].isWhitespace()) j++
    return j < raw.length && raw[j].isDigit()
}

/** Та же свёртка, когда хозяин символа не нужен, — для запроса. */
internal fun foldForSearch(raw: CharSequence): String =
    buildString { foldForSearch(raw) { ch, _ -> append(ch) } }

/** Оформление, которое различием не считается. Точки и запятых здесь нет сознательно: внутри
 *  числа они несущие, и решает это [foldForSearch] по соседям, а не список. */
private const val SEARCH_NOISE = "-–—«»„“”\"'‘’⚠"

/**
 * Что сказать человеку про число находок (#279).
 *
 * Живёт рядом с поиском, а не в экране, потому что ответ обязан быть один: экран показывает
 * места, реализатор отвечает без экрана, и разъехавшиеся формулировки означали бы, что у Point
 * два мнения о том, что он нашёл.
 */
fun foundOnPageLabel(matches: Int): String =
    if (matches == 0) "Ничего не нашлось" else "Нашлось $matches ${placesWord(matches)}"

/** «место / места / мест» — по-русски, а не «мест(а)»: число видит человек, а не разработчик. */
private fun placesWord(n: Int): String {
    val hundred = n % 100
    val ten = n % 10
    return when {
        hundred in 11..14 -> "мест"
        ten == 1 -> "место"
        ten in 2..4 -> "места"
        else -> "мест"
    }
}
