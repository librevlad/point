package com.point.core.flow

data class RealizerMeta(

    val priority: Int = 50,
    val kind: RealizerKind = RealizerKind.LOCAL,

    /**
     * Имя исполнителя в evidence знания (#1127).
     *
     * Не человеческая подпись и не показывается на экране: по нему сверяются два прочтения
     * одного вопроса и объясняется расхождение. Пусто — исполнитель называет себя сам
     * (цепочка сервисов знает, кто именно ответил) или знания не приносит вовсе.
     */
    val actor: String = "",

    /**
     * Исход этого исполнителя может прийти позже его ответа (#1073).
     *
     * Сосед отвечает словом — «компьютер ещё работает», — а чем работа кончилась, доезжает
     * потом: отменой у диалога сохранения, отказом принтера, готовым файлом. Признак
     * принадлежит исполнителю, а не экрану: то же умение, сделанное здесь, отвечает исходом
     * сразу. Экран спрашивает признак, а не сверяет класс исполнителя, — иначе позднего
     * исхода ждали бы ровно у одного известного экрану типа и ни у какого другого.
     */
    val outcomeMayArriveLater: Boolean = false,
)

enum class RealizerKind { LOCAL, CLOUD, REMOTE }
