package com.point.core.flow

data class RealizerMeta(

    val priority: Int = 50,
    val kind: RealizerKind = RealizerKind.LOCAL,

    /**
     * Уносит ли этот исполнитель объект за круг устройств человека (#1088).
     *
     * Вид говорит, кто делает работу; уход наружу — отдельный вопрос, и один из другого не
     * выводится. Компьютер круга умеет и то, что делает у себя, и то, что отправляет дальше,
     * в чужой сервис: за второе согласие спрашивается так же, как за облачного исполнителя.
     *
     * Пока признака не было, компьютер объявлял себя облаком, лишь бы согласие не потерялось,
     * — и в порядке исполнителей переставал отличаться от чужого сервиса. По умолчанию наружу
     * уходит тот, кто чужим сервисом и является.
     *
     * Умолчание считается один раз — в момент вызова конструктора. `copy(kind = CLOUD)`
     * пересчитывать его не станет и оставит здесь прежнее `false`: согласие тихо перестанет
     * спрашиваться. Меняешь вид через `copy` — называй `leavesCircle` там же явно.
     */
    val leavesCircle: Boolean = kind == RealizerKind.CLOUD,

    /**
     * Имя исполнителя в evidence знания (#1127).
     *
     * Не человеческая подпись и не показывается на экране: по нему сверяются два прочтения
     * одного вопроса и объясняется расхождение. Пусто — исполнитель называет себя сам
     * (цепочка сервисов знает, кто именно ответил) или знания не приносит вовсе.
     */
    val actor: String = "",
)

/**
 * Кто берётся за работу: сам телефон, второе устройство человека или чужой сервис (#1088).
 *
 * Вид — свойство исполнения, а не отдельная способность (ADR-0001 §7): человек выбирает
 * действие, а кем оно сделано, решает `Resolver`. Насколько исполнитель близок человеку,
 * записано один раз, в [nearness], — правило не расходится по резолверам, не зависит от
 * порядка констант здесь и не решается именем класса.
 */
enum class RealizerKind { LOCAL, REMOTE, CLOUD }
