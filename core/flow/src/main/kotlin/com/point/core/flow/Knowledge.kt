package com.point.core.flow

import com.point.core.model.PointObject

/*
 * Понятое живёт при ОБЪЕКТЕ и только накапливается (#526).
 *
 * Живой случай владельца (05.08.2026): на скане визитки локально нашёлся QR. Тап по «Понять» —
 * облако вернуло поля визитки, про QR оно не знало, и QR с экрана исчез.
 *
 * Затирало при этом не облако. Внутри ОДНОГО чтения аккуратность давно построена: находки
 * сливаются голосованием ([mergeFacts]), известное не переписывается тем, что пришло вторым, спор
 * двух источников виден через `.alt`, происхождение — через `.src`. Терялось всё на СМЕНЕ КАДРА:
 * кадр рождался с пустым набором находок, а его объект переклассифицировался с нуля — по типу и
 * весу файла, то есть без единого признака. Каждый шаг начинал понимать заново.
 *
 * Здесь та же аккуратность поднята на уровень объекта: шаг, вернувший те же байты, только
 * добавляет. Правила голосования при этом не переписываются — они остаются там, где работают.
 */

/**
 * Продолжает ли [after] тот же самый объект, что и [before], — или это уже другой объект?
 *
 * Судим по байтам ([PointObject.uri]), а не по идентификатору: `ObjectStore.put` выдаёт результату
 * шага свежий id, и по id «тот же объект, понятый глубже» неотличим от «родился новый». Ссылка
 * честна в обе стороны: «Понять» возвращает `input.uri` — единственное действие, которое так
 * делает, и делает по определению (оно не производит ничего, кроме понимания), — а всё, что
 * рождает новый объект, пишет ему собственный файл в scratch.
 *
 * Цена ошибки здесь несимметрична, и правило выбрано под неё: не узнать продолжение — значит
 * потерять понятое (то, что чинит #526); принять чужой объект за продолжение — значит приписать
 * ему чужие признаки. Равенство ссылок не ошибается ни в ту, ни в другую сторону — два разных
 * объекта одними байтами в scratch не живут.
 */
fun continuesObject(before: PointObject, after: PointObject): Boolean = before.uri == after.uri

/**
 * Понятое об [known] переезжает на [produced] — шаг только добавляет (#526).
 *
 * Вызывается ТОЛЬКО когда [continuesObject] сказал «это тот же объект»: на чужой объект чужие
 * признаки не переносятся никогда.
 *
 * - **Признаки складываются.** `HAS_QR`, найденный локально, переживает облачное чтение, которое
 *   про QR ничего не сказало. Врать этим нельзя: байты те же самые, значит и всё, что о них уже
 *   знали, по-прежнему правда. Заодно это снимает повторную работу — `Enrichment` не станет
 *   перечитывать движком страницу, которую уже прочитал, только потому, что признак «есть текст»
 *   потерялся по дороге (двадцать-тридцать секунд на каждый шаг).
 * - **Значения: слово шага сильнее, но известное не пропадает.** Ключ, о котором шаг ничего не
 *   сказал, остаётся прежним; ключ, о котором сказал, берётся у шага. Голосованием ([mergeFacts])
 *   это НЕ делается намеренно: там судят сырые чтения против известного, а здесь встречаются две
 *   уже отсуженные карты. Повторный суд над ними стёр бы ровно то, ради чего он существует, —
 *   `mergeFacts` снимает `.alt` при согласии и не переносит аннотации вовсе, так что рассказ шага
 *   про спор двух чтений исчез бы в момент наследования.
 * - **Объект остаётся собой.** Идентичность переезжает вместе со знанием: за id держатся связи
 *   графа ([com.point.core.model.Relation] адресует объекты по id) и запись в «Недавнем» —
 *   `HistoryStore.update` находит её только по id, и со свежим id всё понятое шагом до «Недавнего»
 *   не доезжало вовсе.
 * - **Происхождение не понижается** (#264). Ответ модели, забранный в объект, не становится
 *   «принесённым человеком» оттого, что человек попросил прочитать его ещё раз.
 */
fun carryKnowledge(known: PointObject, produced: PointObject): PointObject = produced.copy(
    id = known.id,
    state = known.state.features.fold(produced.state) { state, feature -> state.with(feature) },
    metadata = known.metadata + produced.metadata,
    provenance = maxOf(known.provenance, produced.provenance),
    sourceObjects = produced.sourceObjects.ifEmpty { known.sourceObjects },
    creatorAction = produced.creatorAction ?: known.creatorAction,
)
