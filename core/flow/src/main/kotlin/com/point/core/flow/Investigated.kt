package com.point.core.flow

import com.point.core.model.ActionResult
import com.point.core.model.Findings

/**
 * Исследование либо принесло знание, либо честно не вышло (#863).
 *
 * Эти пять строк были написаны тринадцать раз — по разу в каждом исследовании. И это не
 * просто повтор: здесь выполняется норма конституции.
 *
 * > Сорвавшееся исследование оставляет знание в `not investigated` или «исследовано
 * > недостаточно» и никогда не переводит его в `not found`.
 *
 * Ровно поэтому срыв — `Failure(recoverable = true)`, а не `Done` с пустыми находками:
 * «не вышло спросить» и «спросили, не нашли» — разные вещи, и вторая закрывает вопрос,
 * которого никто не задавал.
 *
 * Повторённое тринадцать раз, правило держалось на том, что все тринадцать авторов написали
 * одинаково. Достаточно одному вернуть `Done(Findings())` — и сорвавшееся исследование молча
 * объявит «не найдено», а ни один тест этого не увидит: каждый проверяет своё исследование.
 *
 * Человеку выходит только то, что для него написано (#1225): причина исследования, слово
 * слоя-источника ([OwnWords]) или общее слово срыва. Чужой текст исключения — «End-of-File,
 * expected line at offset 25» от разбора PDF — сюда не проходит и остаётся на своём слое.
 *
 * @param whenFailed своя причина срыва — когда чужой текст исключения показывать нельзя.
 *   В нём бывает и путь из недр, и «Central Directory Entry not found» (#570).
 */
suspend fun investigated(whenFailed: String? = null, findings: suspend () -> Findings): ActionResult =
    runCatching { findings() }.fold(
        onSuccess = { ActionResult.Done("", it) },
        onFailure = {
            ActionResult.Failure(whenFailed ?: ownWordsOf(it) ?: INVESTIGATION_FAILED, recoverable = true)
        },
    )

/** Исследование сорвалось, а своей причины у него не нашлось. */
const val INVESTIGATION_FAILED = "исследование не удалось"

/** Текста, за которым шли, у объекта не оказалось. */
const val NO_TEXT_PAYLOAD = "текст объекта недоступен"

/**
 * Сколько текста берётся за один заход разведки.
 *
 * Правило разведки, а не деталь отдельного исследования: четыре из них объявляли это число
 * у себя, и разъехаться им ничто не мешало.
 */
const val INVESTIGATION_TEXT_CHARS = 20_000
