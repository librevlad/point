package com.point.core.flow.capabilities

import com.point.core.flow.Capability
import com.point.core.model.CapabilityId

/**
 * Общий словарь намерений — контракт от 06.08.2026 (`docs/DESKTOP-CONTRACT.md`, И1).
 *
 * > `Capability` никогда не принадлежит устройству.
 *
 * Здесь живут Action, объявленные **один раз на оба устройства**. Реализации остаются у каждого
 * свои: телефон читает снимок Tesseract'ом, компьютер — чужим сервисом, и что из этого выбрать,
 * решает `Resolver`, а не человек и не декларация.
 *
 * До этого словаря одно намерение бывало объявлено дважды: телефоном как `ocr` («Распознать
 * текст»), компьютером как `pc-ocr` («Прочитать в облаке»). Замер на 06.08.2026: **16 из 20**
 * способностей компьютера были чужим идентификатором для намерения, которое телефон уже объявил.
 * Из-за этого компьютер объявлял телефону чтение чужим сервисом рядом с телефонным, локальным и
 * бесплатным — владелец назвал это абсурдом.
 *
 * **Список, а не набор отдельных привязок,** намеренно: каждая следующая способность переезжает
 * сюда одной строкой, и ни телефон, ни компьютер править для этого не нужно. Место, где список
 * пришлось бы дописывать дважды, — это место, где две поверхности однажды разойдутся молча.
 *
 * Порядок переезда — по мере надобности, а не разом: `docs/DESKTOP-CONTRACT.md`, журнал ворот.
 */
fun sharedCapabilities(): List<Capability> = listOf(
    OcrCapability(),
    QrCapability(),
    ArchiveCapability(),
    OfficeCapability(),
    ImageCapability(),
    DropLinkCapability(),
)

/**
 * Идентификаторы общего словаря.
 *
 * Нужны ровно для одного: намерение, объявленное здесь, **не синтезируется второй раз** из
 * объявления соседнего устройства. Иначе на экране встало бы два пузырька одного намерения —
 * «Распознать текст» и «Распознать текст на ПК», — то есть выбор устройства, который контракт
 * запрещает (И2).
 *
 * Считается из самого словаря, а не пишется рядом: второй перечень разошёлся бы с первым.
 */
val sharedCapabilityIds: Set<CapabilityId> get() = sharedCapabilities().map { it.id }.toSet()
