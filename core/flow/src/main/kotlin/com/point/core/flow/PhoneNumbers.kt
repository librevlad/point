package com.point.core.flow

import com.google.i18n.phonenumbers.NumberParseException
import com.google.i18n.phonenumbers.PhoneNumberUtil
import com.google.i18n.phonenumbers.PhoneNumberUtil.PhoneNumberType

/**
 * Телефон судит библиотека, а не самодельное правило (#801).
 *
 * Мерка была одна на всё — «от десяти до тринадцати цифр» — и жила в двух копиях: у ответа
 * модели и у офлайн-движка. Она пропускала номер карты, не отличала украинский номер от
 * американского и считала три разные записи одного номера тремя разными знаниями:
 * `067 636 05 60`, `+380676360560` и `0676360560`.
 *
 * Решение владельца 12.08.2026: «отдать libphonenumber, заодно обогащать знания».
 *
 * Библиотека отвечает на вопрос, существует ли такой номер, и заодно рассказывает то, чего
 * Point не знал вовсе: страну и вид номера. Она же судит, одна это запись или две, и она же
 * показывает номер по-человечески.
 *
 * **Регион.** Номер без `+` разобрать без подсказки страны нельзя: `067…` — украинский
 * мобильный, а в другой стране это другой номер или не номер вовсе. Подсказка приходит
 * снаружи — от локали или SIM, — и `:core:flow` остаётся Android-free.
 */
const val META_ENTITY_PHONE = META_ENTITY_PREFIX + "phone"

object PhoneNumbers {

    private val util: PhoneNumberUtil by lazy { PhoneNumberUtil.getInstance() }

    /**
     * Существует ли такой номер хотя бы в одной из правдоподобных стран.
     *
     * Решение владельца 13.08.2026: «Несколько стран, годится любая». Принятая цена — на
     * грязном OCR ложных номеров станет чуть больше.
     *
     * Здесь спрашивают только про существование, и «хоть в какой-нибудь» — законный ответ.
     * Ни одна из подошедших стран страной номера не становится (#1029): на этот вопрос
     * отвечает [country], и спрашивает он один документ.
     */
    fun exists(text: String, region: String = DEFAULT_REGION): Boolean =
        regionsToTry(text, region).any { parse(text, it) != null }

    /**
     * Страны, по которым ищется номер: страна устройства — **одна из подсказок**, а не
     * приговор (#936).
     *
     * Номер без `+` без подсказки не разобрать. Раньше подсказка была одна и бралась у
     * телефона: у украинца с телефоном на английском страна оказывалась `US`, и его
     * собственные номера переставали существовать — молча, все до единого. Живая охота
     * 13.08.2026: модель ответила `PHONE=067 636 05 60`, а Point выбросил.
     *
     * Страна устройства — не страна документа. Человек в Польше открывает украинский счёт;
     * номер в документе от этого не исчезает. Подсказка приходит **параметром** (#1129):
     * прежде она лежала здесь же изменяемой переменной, и разбор одного и того же текста
     * зависел от того, что записали в неё раньше. Подсказка — вход разбора, а не состояние
     * мира.
     *
     * Список короткий нарочно: чем он длиннее, тем больше случайных чисел окажутся чьими-то
     * настоящими номерами. Здесь страны, откуда к человеку реально приходят документы.
     *
     * Отвечает этот список на единственный вопрос — номер ли это вообще. Знанием о номере он
     * не становится: что бы в нём ни подошло, страну номера называет только сам документ.
     */
    private fun regionsToTry(text: String, region: String): List<String> =
        if (writtenLikeAPhone(text)) (listOf(region.uppercase()) + NEARBY).distinct()
        else listOf(region.uppercase())

    /**
     * Стоит ли вообще искать этот текст по чужим странам.
     *
     * Чем больше стран, тем больше случайных чисел оказываются чьими-то настоящими номерами:
     * «4507 1234» и контрольная цифра накладной начинали проходить за телефон. Поэтому чужие
     * страны пробуются только у того, что **написано как номер**: с плюсом, с разделителями
     * внутри или национальной записью — ведущий ноль и либо группы, либо длина национального
     * номера. Голая длинная цепочка цифр — это идентификатор, а не телефон.
     */
    private fun writtenLikeAPhone(text: String): Boolean {
        val clean = text.trim()
        val digits = clean.count(Char::isDigit)

        // Знак ставит человек, а не случай (#1017). Голая цепочка цифр — идентификатор:
        // «908771 1329» это номер дома, слипшийся с номером магазина, и в чужой стране он
        // оказывался чьим-то настоящим номером.
        //
        // Ведущий ноль — знак национальной записи, и он остаётся: без него «0932423759» с
        // накладной терялся на устройстве с чужой страной (прогон корпуса 19.08.2026). Но
        // длина у такой записи своя: национальный номер человек пишет короче, а «042200002675»
        // с двенадцатью цифрами — товарный штрихкод, и за границу он не идёт.
        val shaped = clean.startsWith("+") ||
            clean.any { it == '-' || it == '(' || it == ')' } ||
            (clean.startsWith("0") && (clean.any { it == ' ' } || digits <= NATIONAL_DIGITS))
        return shaped && digits in PHONE_DIGITS
    }

    /**
     * Сколько цифр бывает в номере, который человек пишет в документе.
     *
     * Короче — это обрывок: «4507 1234» с квитанции и контрольная цифра накладной начинали
     * проходить за телефон, стоило добавить стран. Длиннее — идентификатор.
     */
    private val PHONE_DIGITS = 9..13

    /**
     * Сколько цифр бывает в национальной записи, написанной подряд.
     *
     * Длиннее — идентификатор: товарный штрихкод с ведущим нулём иначе уходит искать себе
     * страну и находит (#1017).
     */
    private const val NATIONAL_DIGITS = 11

    /**
     * Один и тот же номер, записанный по-разному, — одно знание.
     *
     * `067 636 05 60`, `+380676360560` и `0676360560` — одна запись, и ответ не зависит от
     * того, где стоит устройство (#1029). Прежде тождество считалось по E.164, а код страны
     * для номера без `+` брался у первой подошедшей страны: на украинском телефоне
     * `918-682-1551` с чека оказывался немецким, `+1 918-682-1551` рядом — американским, и
     * один номер выходил на экран спором «или:». На американском телефоне — одной строкой.
     *
     * Сверяет библиотека: коды стран сравниваются, когда их назвали оба документа, иначе
     * сравниваются цифры без кода. Страну сама сверка не подсказывает — «одно ли это знание»
     * устройство не решает.
     *
     * Устройство отвечает здесь на единственный вопрос — номер ли это вообще (#936), и это
     * тот же отбор, который решает, попадёт ли текст в граф фактом. Где обе записи прошли
     * отбор, ответ один на всех устройствах; где текст номером не считается, там нет и
     * факта, о тождестве которого спрашивать. Отличается ответ ровно на эту границу и
     * никогда — на страну.
     */
    fun same(left: String, right: String, region: String = DEFAULT_REGION): Boolean {
        if (!exists(left, region) || !exists(right, region)) return false
        return util.isNumberMatch(left.trim(), right.trim()) in ONE_NUMBER
    }

    /**
     * Что библиотека считает одной записью.
     *
     * Обрезанное прочтение (`SHORT_NSN_MATCH`) сюда не входит: «636 05 60» может быть хвостом
     * другого номера, и слить их значит потерять один из двух.
     */
    private val ONE_NUMBER = setOf(
        PhoneNumberUtil.MatchType.EXACT_MATCH,
        PhoneNumberUtil.MatchType.NSN_MATCH,
    )

    /**
     * Как номер показывается человеку: так, как он привык его видеть.
     *
     * Формат даёт только страна, названная документом (#1029). Раньше показ разбирал номер
     * **первой подошедшей** страной из списка подсказок: чек из Оклахомы с честным
     * `918-682-1551` в графе выходил на экран как «+49 9186 821551», а на устройстве с
     * американской локалью — как «(918) 682-1551». Страна в показе зависела от того, где
     * стоит телефон, а не от того, что написано в документе, и человек не мог отличить
     * угаданное от прочитанного.
     *
     * Решение владельца 21.08.2026: не додумывать страну. Документ не назвал её — сказать
     * нечего, и номер печатается так, как он записан (`shown`).
     *
     * Страна устройства решает здесь единственное: повторять ли **уже известный** код — свой
     * человек и так знает, и рядом, в строке знания, по той же причине не называется своя
     * страна словом (#932). Дописать код, которого нет в знании, устройство не может: страна
     * на экране всегда та, что в графе, и на любом устройстве одна и та же — меняется только
     * то, повторять ли её.
     */
    fun human(text: String, region: String = DEFAULT_REGION): String? =
        namedByDocument(text)?.let { number ->
            val format = if (number.countryCode == countryCodeOf(region)) {
                PhoneNumberUtil.PhoneNumberFormat.NATIONAL
            } else {
                PhoneNumberUtil.PhoneNumberFormat.INTERNATIONAL
            }
            util.format(number, format)
        }

    /**
     * Страна номера — только та, которую назвал **сам документ**.
     *
     * Номер без кода страны о своей стране не говорит: `918-682-1551` настоящий и в Америке,
     * и в Германии, а `22 123 45 67` — в Польше, Германии и Франции. Прочитать такую запись
     * можно только с подсказкой, а подсказка — это устройство.
     *
     * Раньше страна называлась, когда из подсказок подошла ровно одна, и это оказалось той же
     * догадкой с другого конца (#1029): список подсказок начинается со страны устройства, а
     * для записи без разделителей он ею и заканчивается. Один и тот же чек из Оклахомы,
     * прочитанный как `918 682 1551`, выходил американским на американском телефоне, немецким
     * на немецком и британским на британском, а `050 111 22 33` из документа вставало на экран
     * украинским `+380 50 111 2233` всюду, кроме Франции, где подошла ещё и она.
     *
     * Решение владельца 21.08.2026: не додумывать страну; регион устройства — только для
     * звонка, не для показа. Спрашивать здесь устройство не о чем: либо страна написана в
     * самом номере, либо её нет.
     */
    fun country(text: String): String? =
        namedByDocument(text)?.let { util.getRegionCodeForNumber(it) }

    /**
     * Номер, чью страну назвал документ: разобранный без единой подсказки.
     *
     * Без подсказки библиотека прочтёт только международную запись — `+1 918-682-1551`.
     * Национальной записи страну даёт подсказка, а не документ, поэтому здесь её и не
     * спрашивают (#1029). Международная запись — это `+`: выход в межгород цифрами
     * (`00380…`) у каждой страны свой, и прочесть его можно только подсказкой устройства,
     * то есть страной документа он не является.
     *
     * Одно и то же место для знания и для показа: страна, которой нет в графе, не смеет
     * появиться на экране, и на любом устройстве она одна и та же.
     */
    private fun namedByDocument(text: String) = parse(text, region = null)

    /**
     * Вид номера словами человека: мобильный, городской. Неизвестное молчит.
     *
     * Вид принадлежит стране (#1029). Пока его брали у первой подошедшей, `918-682-1551` с
     * чека был «городской» на украинском телефоне — немецким городским — и не имел вида
     * вовсе на американском. Страна, которой документ не назвал, не называет и вида.
     */
    fun kind(text: String): String? =
        namedByDocument(text)?.let {
            when (util.getNumberType(it)) {
                PhoneNumberType.MOBILE -> "мобильный"
                PhoneNumberType.FIXED_LINE -> "городской"
                PhoneNumberType.FIXED_LINE_OR_MOBILE -> null
                PhoneNumberType.TOLL_FREE -> "бесплатный"
                PhoneNumberType.PREMIUM_RATE -> "платный"
                else -> null
            }
        }

    private fun countryCodeOf(region: String): Int =
        runCatching { util.getCountryCodeForRegion(region) }.getOrDefault(0)

    private fun parse(text: String, region: String?): com.google.i18n.phonenumbers.Phonenumber.PhoneNumber? {
        val clean = text.trim()
        if (clean.isEmpty()) return null

        // В телефоне не бывает слов. Модель давала чистый «067 636 05 60», а заземление по
        // странице возвращало склейку «Тарасенко Світлана Сергіївна 067 636 05 60» — она и
        // вставала значением телефона (охота 11.08.2026). Библиотека такую склейку разберёт:
        // она ищет номер внутри строки, а нам нужно, чтобы строка номером и была.
        if (WORDY.containsMatchIn(clean)) return null
        return try {
            util.parse(clean, region).takeIf { util.isValidNumber(it) }
        } catch (_: NumberParseException) {
            null
        }
    }

    /**
     * Как показать значение человеку.
     *
     * Номер, вычитанный с кадра, приходит покорёженным: `06 1 ) 2 80-44-2 1`. Библиотека его
     * разобрала — иначе он не прошёл бы отбор и не появился бы на экране, — значит
     * канонический вид у Point есть, и показывать мусор незачем (#932).
     *
     * Канонический вид принадлежит стране, поэтому он есть не всегда (#1029): у номера, чью
     * страну документ не назвал, своей группировки нет — и он показывается так, как записан.
     * Выдумывать нельзя: это относится и к неразобранному, и к разобранному наугад.
     */
    fun shown(text: String, region: String = DEFAULT_REGION): String =
        human(text, region) ?: text

    /**
     * Страна словом человека, а не кодом.
     *
     * `UA` — адрес для машины; на экране должно стоять «Польша». Имена стран уже есть в
     * системе — своего справочника Point не заводит.
     */
    fun countryName(code: String): String? =
        java.util.Locale("", code).getDisplayCountry(java.util.Locale.forLanguageTag("ru"))
            ?.takeIf { it.isNotBlank() && it != code }

    /** Пока страна не подсказана снаружи. */
    const val DEFAULT_REGION = "UA"

    /**
     * Страны, откуда к человеку приходят документы, помимо названной подсказкой.
     *
     * Список держится коротким: каждая лишняя страна превращает часть случайных чисел в
     * чьи-то настоящие номера.
     */
    private val NEARBY = listOf("UA", "PL", "DE", "US")
}
