package com.point.core.flow

/**
 * Выпрямленный кадр того же снимка (#1041).
 *
 * Снятый под углом счёт читается кашей: телефоном становится номер дома (#1017), номером
 * магазина — немецкий телефон (#1007). Убрать перспективу и выбелить бумагу Point умеет
 * давно, но только по просьбе человека и только новым объектом: он должен был сам догадаться
 * нажать «Скан», войти в родившуюся картинку и прочитать уже её — знание оставалось на
 * другом объекте, а не на том, которым поделились.
 *
 * Шов нужен потому, что выпрямление — side effect над графикой устройства и живёт там же,
 * где остальная обработка снимков, а понимание кадра — в исследовании. Нового движка за ним
 * нет: тот же ход, каким готовит страницу «Скан».
 *
 * `null` — выпрямить нечем: обработчика нет на устройстве, страницы на кадре не нашлось, не
 * вышло. Это честный ответ «второго захода не будет», а не ошибка.
 */
fun interface StraightFrame {

    /** Путь к выпрямленной копии кадра или `null`. Исходный кадр не трогается. */
    suspend fun of(path: String): String?
}

/**
 * Текст прочитан с выпрямленной копии, а не с кадра человека (#1041).
 *
 * Тот же след работы, что и [META_READ_UPSCALE]: там сказано, что читали увеличенный кадр,
 * здесь — что читали выпрямленный. Без него знание приходит с кадра, которого человек никогда
 * не видел, и понять происхождение этого текста нечем (ADR-0001 §9). Человеку показывать
 * нечего: provenance внутренний.
 */
const val META_READ_STRAIGHTENED = "read.straightened"
