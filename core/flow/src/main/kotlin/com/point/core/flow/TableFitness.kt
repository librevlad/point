package com.point.core.flow

/**
 * Порог годности таблицы (#493): **негодное не выдаётся за результат.**
 *
 * У проекта есть инвариант «неуверенность не сглаживается» — и он честно исполнялся: слова, которые
 * не удалось отнести ни к чему, ехали в лист видимым блоком с подписью ([UNREAD_CAPTION]), а спорные
 * ячейки помечались ⚠. Но у честности обнаружилась вторая сторона. Когда чтение плохое, механизм
 * честности превращает **плохое чтение в плохой файл**: у владельца из 23 строк листа одиннадцать
 * оказались свалкой обрывков под подписью «непрочитанное», и он открыл не таблицу, а протокол
 * неудачи, отданный как успех.
 *
 * Отказ здесь — не отступление от инварианта, а его вторая половина: сказать «прочитать таблицу не
 * удалось» честнее, чем отдать файл, который сам же и сообщает, что не прочитан.
 *
 * **Пороги — суждение, и они названы вслух.** Ни один не выдуман под случай: доля — та же треть,
 * которой метрика корпуса ([WARNING_WALL_SHARE]) объявляет таблицу проваленной. То есть продукт
 * отказывается ровно там, где его собственная метрика уже говорит «это не результат»; расходиться
 * этим двум числам нельзя.
 */

/**
 * Доля слов страницы, которую можно не разобрать и всё ещё называть результатом.
 *
 * Треть — та же граница, что у [WARNING_WALL_SHARE], и по той же причине: выше неё человек получает
 * не таблицу, а задание перечитать документ самому.
 */
const val UNFIT_UNREAD_SHARE: Double = 1.0 / 3.0

/**
 * Ниже этого числа слов доля — не мера, а случайность.
 *
 * Оговорка та же, что у [MAX_PROMPT_ATOMS]-потолка и у порога «слишком мало прочитанного, чтобы
 * судить» ([weaklyRead]): на бирке из шести слов одно неприсвоенное даёт сразу шестую часть, и
 * отказ означал бы «мы не умеем читать короткие документы». Настоящая страница — это сотни слов;
 * сорок отделяют её от подписи под фотографией с запасом.
 */
private const val MIN_JUDGEABLE_WORDS = 40

/**
 * Ниже этого числа ячеек «стена предупреждений» не считается: на таблице из четырёх ячеек одна
 * спорная — это находка сторожа, а не стена. Шесть строк на четыре колонки — уже таблица.
 */
private const val MIN_JUDGEABLE_CELLS = 24

/**
 * Почему этот лист нельзя отдать человеку как таблицу — его словами; `null` — можно.
 *
 * Три двери в негодность, и каждая закрывается своим числом:
 * - **читать нечего** — ни одна часть документа не собралась, лист состоит из одного
 *   «непрочитанного»;
 * - **прочитано меньше, чем не прочитано** — доля слов, не попавших ни в одну часть документа,
 *   выше [UNFIT_UNREAD_SHARE];
 * - **стена спора** — чтения разошлись на [WARNING_WALL_SHARE] ячеек сетки и больше.
 *
 * У обеих долей есть **пол**: ниже него доля не мера, а случайность, и судить по ней значило бы
 * отказывать коротким документам за их длину. Первая дверь пола не имеет — «не собралось ничего»
 * верно при любом размере страницы.
 *
 * [disputed] — ячейки, о которых спорят **читатели** (расхождение чтений плюс находки логической
 * проверки), а не ячейки, помеченные режимом чтения. Разница принципиальна: на рукописи цифры
 * помечаются все и всегда (#267), и считать эти пометки спором значило бы отказывать в файле каждой
 * рукописи — то есть выключить действие ровно там, где оно нужнее всего.
 */
fun unfitTable(document: DocumentLayout, disputed: Int, gridCells: Int): String? {
    val read = document.readWords
    val unread = document.unreadWords
    if (read == 0 && unread > 0) {
        return "Прочитать таблицу не удалось: ни одной части документа со страницы не собралось"
    }
    if (unread + read >= MIN_JUDGEABLE_WORDS && unread.toDouble() / (unread + read) >= UNFIT_UNREAD_SHARE) {
        return "Прочитать таблицу не удалось: больше трети страницы разобрать не вышло"
    }
    if (gridCells >= MIN_JUDGEABLE_CELLS && disputed.toDouble() / gridCells >= WARNING_WALL_SHARE) {
        return "Прочитать таблицу не удалось: чтения разошлись больше чем на трети ячеек"
    }
    return null
}

/**
 * Сколько строк заголовка пережило свод чтений — и это **не то же число**, которое назвало ведущее
 * чтение (#493).
 *
 * [SheetPlan.headerRows] красит шапку по позиции: первые N строк сетки. До свода это верно по
 * построению, после — нет. [reconcile] выравнивает строки по содержимому, и находка второго чтения,
 * которой у первого не было, законно встаёт **выше** шапки: тогда шапкой красится строка данных, и
 * файл заявляет заголовком то, что заголовком не является. Ровно та «жирная ложь», против которой
 * поле [SheetPlan.headerRows] и заводилось.
 *
 * Проверка простая и без догадок: строки заголовка ведущего чтения обязаны стоять в своде на своих
 * местах, сверху и в том же порядке. Не стоят — шапки нет (`0`): не покрасить лучше, чем покрасить
 * чужое.
 */
fun survivedHeaderRows(lead: List<List<String>>, consensus: List<List<String>>, headerRows: Int): Int {
    if (headerRows <= 0) return 0
    val n = minOf(headerRows, lead.size, consensus.size)
    if (n < headerRows) return 0
    val same = (0 until n).all { i -> rowKey(lead[i]) == rowKey(consensus[i]) }
    return if (same) headerRows else 0
}

/** Строка как одно значение для сверки: те же правила складывания, что у голосования чтений. */
private fun rowKey(row: List<String>): String =
    row.joinToString("") { normConsensus(it) }
