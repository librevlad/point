package com.point.core.flow

/**
 * Ориентация страницы судится **метрикой прочитанного**, а не гаданием (#262 → design v3 §3).
 *
 * Первый замер корпуса назвал узкое место прямо: 7 кадров из 22 повёрнуты (два — вверх ногами),
 * и до разбора дело не доходит вовсе — движок читает боковые строки как мусор. Поворот
 * снимка — не «улучшайзер»: это условие, без которого всё остальное бессильно.
 *
 * Гадать по EXIF нельзя — у фото бумаги на столе его нет; спрашивать модель нельзя — она
 * стоит денег и живёт после явного тапа. Поэтому здесь то же, что везде в движке: **проба и
 * измерение**. Страницу читают в нескольких поворотах, и каждое чтение получает счёт
 * ([readingScore]); побеждает поворот, который прочитал больше и увереннее — и только если
 * выигрыш **заметен** ([MIN_ORIENTATION_GAIN]), иначе остаёмся в исходном кадре: слабое
 * различие — шум, а не знание.
 */

/**
 * Сколько осмысленного прочитано: сумма по словам «уверенность × длина», где слово считается
 * словом, если в нём хотя бы [MIN_WORD_CHARS] символов и большинство из них — буквы или цифры.
 *
 * Мусор перевёрнутой страницы — короткие огрызки с низкой уверенностью, и он этот счёт не
 * набирает. Число внутреннее и сравнимо **только между чтениями одного кадра одним ридером**
 * (ADR-0001: уверенности разных ридеров несравнимы), поэтому наружу как «качество» не уходит.
 */
fun readingScore(layer: AtomLayer): Double = layer.atoms.sumOf { atom ->
    val text = atom.text.trim()
    val readable = text.count(Char::isLetterOrDigit)
    if (text.length < MIN_WORD_CHARS || readable * 2 < text.length) {
        0.0
    } else {
        atom.confidence.toDouble() * readable
    }
}

/** Короче этого — не слово, а огрызок: единичные символы дают шум в обе стороны. */
private const val MIN_WORD_CHARS = 2

/**
 * Во сколько раз чтение должно быть лучше исходного, чтобы поворот считался доказанным.
 * Меньший выигрыш — шум распознавания, и он не стоит подмены системы координат.
 */
const val MIN_ORIENTATION_GAIN = 1.3

/** Повороты, которые имеет смысл пробовать: страница лежит боком или вверх ногами. */
val ORIENTATION_ANGLES = listOf(90, 180, 270)

/**
 * Стоит ли вообще пробовать повороты: прочитанное пусто, каша ([looksLikeOcrGarbage]) или
 * счёт ниже [WEAK_READING_SCORE]. Хорошо прочитанную страницу не крутим — четыре прохода OCR
 * стоят секунд, а инвариант «первый экран без тяжёлой работы» держится только тем, что
 * распознавание и так живёт в медленной волне.
 */
fun looksMisoriented(layer: AtomLayer): Boolean {
    val text = layer.text
    return text.isBlank() || looksLikeOcrGarbage(text) || readingScore(layer) < WEAK_READING_SCORE
}

/**
 * Ниже этого счёта чтение слабое даже для короткой этикетки. Порог намеренно низкий: лишний
 * прогон на короткой, но честно прочитанной странице стоит секунд в медленной волне, а
 * непрочитанный кадр стоит всей задачи (на корпусе — треть кадров).
 */
private const val WEAK_READING_SCORE = 25.0

/**
 * Выбор ориентации: [base] — чтение как есть, [rotated] — «угол → чтение». Возвращает угол
 * победителя либо `0`, если ни один поворот не выиграл заметно.
 *
 * Ничья и близкие счета — за исходным кадром: подменять систему координат ради шума значит
 * ломать адреса атомов на ровном месте.
 */
fun bestOrientation(base: AtomLayer, rotated: Map<Int, AtomLayer>): Int {
    val baseScore = readingScore(base)
    val best = rotated.maxByOrNull { readingScore(it.value) } ?: return 0
    val bestScore = readingScore(best.value)
    val gain = if (baseScore <= 0.0) bestScore else bestScore / baseScore
    return if (bestScore > 0.0 && gain >= MIN_ORIENTATION_GAIN) best.key else 0
}
