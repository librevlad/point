package com.point.core.flow

/**
 * Откуда берётся подсказка страны для разбора номеров (#1129).
 *
 * Раньше подсказка лежала изменяемой переменной в `:core:flow`: её писал Android-слой при
 * старте, а читал весь разбор. Результат зависел от того, что записали раньше, — и по графу
 * этого видно не было. Страна — **вход** разбора, а не состояние мира.
 *
 * Значение приходит от устройства (SIM, язык) один раз и дальше не меняется: это app-scoped
 * зависимость, а не глобальный синглтон. Кому подсказка нужна — просит её у себя в
 * конструкторе, как любую другую зависимость.
 */
fun interface PhoneRegion {

    fun code(): String
}

/** Пока страна не подсказана: разбор всё равно обязан быть одинаковым от вызова к вызову. */
val DEFAULT_PHONE_REGION = PhoneRegion { PhoneNumbers.DEFAULT_REGION }
