package com.point.core.flow

/**
 * Ящик, по ссылке на который ЧУЖОЙ человек кладёт файл **тебе** (#388).
 *
 * Обратная сторона «Дать ссылку». У того, кто отправляет, нет ни Point, ни аккаунта, ни ключа — он
 * открывает ссылку браузером, видит страницу с выбором файла и отправляет; файл приезжает в Point
 * обычным путём и становится объектом.
 *
 * **Цена та же и названа так же прямо.** Ключа пары устройств у чужого браузера быть не может,
 * поэтому этот файл релей видит — в отличие от всего, что возят спаренные телефон и компьютер.
 * Ссылка неугадываема (160 бит) и живёт сутки; кто её показывает, тот это принимает.
 */
interface DropInbox {

    /**
     * Завести ящик и вернуть ссылку для другого человека; `null` — нет релея, нет сети, отказ.
     *
     * Молчание здесь неотличимо от отказа намеренно: человеку в обоих случаях нужно одно — узнать,
     * что ссылки не будет.
     */
    suspend fun open(): DropInboxBox?

    /**
     * Подождать файл в ящике. Куда лечь файлу, решает вызывающий: [target] по имени файла отдаёт
     * путь — тот же шов, что у файлов, забираемых с компьютера.
     *
     * Раньше здесь был `null` и на «пока никто ничего не положил», и на «сеть упала»: экран не мог
     * их отличить и держал «Ждём файл…» вечно (#114). Теперь разница названа типом.
     */
    suspend fun await(box: DropInboxBox, target: (name: String) -> String): DropWait
}

/**
 * Чем кончился круг ожидания (#114).
 *
 * Ожидание, которое не может кончиться, — не ожидание, а обман: человек с выключенным Wi-Fi
 * смотрел на «Ждём файл…» столько, сколько выдержит. Пустой круг и отказ сети — разные новости, и
 * человеку они нужны разными.
 */
sealed interface DropWait {
    /** Файл приехал и лежит на диске. */
    data class Arrived(val arrival: DropArrival) : DropWait

    /** Круг прошёл, никто ничего не положил — норма, можно ждать дальше. */
    data object Empty : DropWait

    /** Сеть или сервер отказали: ждать нечего, пока это не починится. */
    data class Failed(val reason: String) : DropWait
}

/**
 * Что честно написать под ссылкой тому, кто ждёт файл: [failures] — сколько кругов ожидания подряд
 * закончились отказом.
 *
 * Один сорвавшийся круг — ещё не новость: сеть моргает, и кричать об этом значит пугать зря.
 * Три подряд — уже состояние, и молчать о нём нельзя. Ссылка при этом остаётся живой: ящик стоит
 * на сервере сутки, и сказать иначе было бы второй ложью поверх первой.
 */
fun receiveWaitStatus(failures: Int): String = when {
    failures < 1 -> "Ждём файл…"
    failures < 3 -> "Связь пропала — пробую снова…"
    else -> "Нет связи с сервером Point. Ссылка не потерялась: файл придёт, когда связь вернётся."
}

/** Заведённый ящик: [id] — адрес на релее, [link] — то, что показывают человеку. */
data class DropInboxBox(val id: String, val link: String)

/** Что приехало: файл на диске, его имя и тип — ровно то, из чего родится объект. */
data class DropArrival(val path: String, val name: String, val mime: String)

/** Адрес ящика из случайных байт (нужно 20 — те же 160 бит, что у ссылки на скачивание). */
fun dropInboxId(random: ByteArray): String =
    java.util.Base64.getUrlEncoder().withoutPadding().encodeToString(random)

/**
 * Правила адреса — те же, что проверяет релей: base64url и не короче 22 знаков.
 *
 * Длина здесь не педантизм: страница приёма открыта без секрета, и короткий адрес можно было бы
 * подобрать перебором. Правило продублировано на обеих сторонах намеренно — сторона, которая
 * принимает чужие запросы, не имеет права полагаться на вежливость другой.
 */
fun isDropInboxId(id: String): Boolean =
    id.length in 22..64 && id.all { it in 'a'..'z' || it in 'A'..'Z' || it in '0'..'9' || it == '-' || it == '_' }

/**
 * Имя приехавшего файла, годное для диска.
 *
 * Его назвал ЧУЖОЙ человек, и доверять ему нельзя: `../../secret` — это не имя, а попытка выйти из
 * своего каталога. Разделители и ведущие точки срезаются здесь, в чистой логике, а не в каждом
 * месте, где имя превращается в путь; пустой остаток — «файл», потому что объект без имени хуже
 * объекта с общим именем.
 */
fun dropFileName(raw: String): String {
    val base = raw.replace('\\', '/').substringAfterLast('/').trim().trimStart('.')
    val safe = base.filter { it.code >= 0x20 && it !in "\\/:*?\"<>|" }.take(120)
    return safe.ifBlank { "файл" }
}

/** Ссылка страницы приёма; `null` — релея нет или адрес ящика не наш. */
fun dropInboxLink(relayUrl: String, id: String): String? {
    val base = relayUrl.trim().trimEnd('/')
    if (base.isBlank() || !isDropInboxId(id)) return null
    return "$base/u/$id"
}
