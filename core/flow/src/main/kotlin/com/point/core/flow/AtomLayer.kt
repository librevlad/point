package com.point.core.flow

/**
 * Прямоугольник на странице в координатах кадра. Чистый Kotlin: ядро остаётся Android-free,
 * поэтому здесь нет ни `RectF`, ни `Rect`.
 */
data class Box(val left: Float, val top: Float, val right: Float, val bottom: Float) {
    val centerX: Float get() = (left + right) / 2f
    val centerY: Float get() = (top + bottom) / 2f
    val height: Float get() = bottom - top

    fun contains(x: Float, y: Float): Boolean = x in left..right && y in top..bottom

    /** Есть ли общая точка — касание краем считается (щедрость к неточному пальцу, #259). */
    fun intersects(other: Box): Boolean =
        left <= other.right && other.left <= right && top <= other.bottom && other.top <= bottom

    /** Наименьший прямоугольник, накрывающий оба. */
    fun union(other: Box): Box =
        Box(minOf(left, other.left), minOf(top, other.top), maxOf(right, other.right), maxOf(bottom, other.bottom))
}

/**
 * Атом — наименьшая адресуемая единица прочитанного: слово или его кусок с местом на странице.
 *
 * **Атом никогда не существует вне родительского объекта** (ADR-0001). Он адресуем, но не узел
 * графа: на одной странице их тысячи, и узлом становится то, что имеет смысл для человека —
 * трек-номер, а не слово.
 */
data class Atom(
    val id: String,
    val text: String,
    val box: Box,
    /**
     * Насколько уверен был **этот** ридер, от 0 до 1.
     *
     * Число внутреннее и между ридерами несравнимое (ADR-0001), поэтому наружу как «уверенность
     * значения» оно не уходит. Его работа другая: показать, куда идти перечитывать.
     */
    val confidence: Float = 1f,
    /**
     * Кто прочитал. Правило «уверенность между ридерами несравнима» неприменимо, пока атом не
     * помнит своего ридера: со вторым ридером (#257 п.1) агрегация без этого поля тихо сравнила
     * бы несравнимое. Пустая строка — синтетика тестов, не устройство.
     */
    val reader: String = "",
    /** Версия ридера: та же модель вчера и сегодня читает по-разному, и спор двух чтений одного
     *  ридера разных версий — законный сигнал, а не дубликат. */
    val readerVersion: String = "",
    /** Страница исходника, с нуля. Один снимок — всегда 0; контракт обязан пережить PDF. */
    val page: Int = 0,
)

/**
 * Слой улик объекта: всё, что прочитал ридер, в том виде, в каком оно лежит на странице.
 *
 * Существует, потому что адрес значения — **область, а не порядковый номер строки**. Порядок
 * строк OCR — ложь про двухколоночный документ, а 14-значный трек с посылочного экрана приходит
 * тремя кусками, и «ответ = один идентификатор» такого не выдерживает (#257, #258).
 */
class AtomLayer(
    val atoms: List<Atom>,
    /**
     * Текст, который отдал сам ридер, если он это умеет.
     *
     * Не второе чтение: координаты и текст приходят из одного прохода движка, поэтому они
     * согласованы по построению. Смысл в другом — у движка есть собственный анализ раскладки, и
     * на двухколоночном документе он различает колонки, а сборка по горизонтальным полосам
     * склеивает левую строку с правой. Раз он знает больше — его текст и побеждает.
     *
     * `internal`, не `private`: [AtomCodec] обязан кодировать именно исходное поле — записав
     * вычисленный [text], дамп приписал бы движку текст, которого движок не отдавал.
     */
    internal val readerText: String? = null,
    /**
     * Как координаты атомов попали в сырой кадр: преобразование той копии, которую читал движок
     * (уменьшенной и довёрнутой), в исходный файл. Атомы уже в сырых координатах — но без
     * сохранённого преобразования (#257 п.2) обратный путь потерян: кроп сомнительного слова из
     * той же копии, что видел движок, или сверка двух чтений требуют именно его. `null` —
     * координаты родились сразу в сыром кадре, преобразовывать нечего.
     *
     * Выравнивание (deskew/dewarp) — не это преобразование: оно появится отдельным срезом со
     * своей метрикой качества и живёт поверх сырого кадра, а не вместо него.
     */
    val transform: FrameTransform? = null,
    /**
     * Почему слой не дочитан до конца; `null` — читали до конца, пусто так пусто.
     *
     * Появилось из живого прогона #262: чтение, упёршееся в предел времени, возвращало ту же
     * пустоту, что и честно пустая страница, — и снаружи «время вышло» было неотличимо от
     * «текста нет». Это две разные новости, и различать их обязан сам слой: он персистится и
     * уезжает в фикстуры, а пометка в чужом логе с ним не путешествует. Известные причины:
     * [INCOMPLETE_TIMEOUT] — предел времени; свободный текст — локальный сбой ридера
     * («decode failed» и подобное).
     */
    val incomplete: String? = null,
) {

    /**
     * Атомы, чей центроид лежит внутри [region], в исходном порядке слоя.
     *
     * Именно центроид, а не пересечение: у соседней строки край бокса заходит в область на
     * пиксель-другой на любом реальном фото, и по пересечению в значение попала бы подпись из
     * строки ниже.
     */
    fun atomsIn(region: Box): List<Atom> =
        atoms.filter { region.contains(it.box.centerX, it.box.centerY) }

    /**
     * Текст области — атомы в порядке чтения, а не в порядке выдачи ридера.
     *
     * Порядок выдачи ридером — не порядок страницы: Tesseract возвращает куски так, как их нашёл,
     * и собранный по этому порядку 14-значный трек оказывается перемешанным. Поэтому порядок
     * восстанавливается по геометрии.
     */
    fun textIn(region: Box): String =
        readingOrder(atomsIn(region)).joinToString(" ") { it.text }

    /**
     * Атомы, разложенные по строкам, и внутри строки — слева направо.
     *
     * Строка определяется **полосой**, а не равенством `top`: на реальном фото лист не идеально
     * ровный, а буквы разной высоты, поэтому верхние края слов одной строки расходятся на
     * несколько пикселей. Сортировка по `top` на таком входе переставляет куски номера местами —
     * ровно то, из-за чего 14-значный трек собирается неправильно и тихо отдаётся как валидный.
     *
     * Порог — половина высоты самого атома, а не константа в пикселях: страница может прийти в
     * любом разрешении, и абсолютный допуск, подобранный под одно фото, соврёт на другом.
     */
    fun readingOrder(subset: List<Atom> = atoms): List<Atom> = lines(subset).flatten()

    /**
     * Атомы, которые ридер прочитал неуверенно, — куда идти перечитывать.
     *
     * Слой их **не удаляет**. Выбрасывание сомнительного — ровно то, из-за чего 14-значный трек
     * умер в фильтре правдоподобия: улику стёрли, чтобы не мусорить в интерфейсе, и самое
     * полезное на экране исчезло вместе с мусором. Выдать сомнительное за прочитанное — вторая
     * крайность и тихая ложь. Поэтому третий путь: всё остаётся, а сомнительное помечено.
     */
    fun doubtful(below: Float): List<Atom> = atoms.filter { it.confidence < below }

    /**
     * Весь слой как текст: слова строки через пробел, строки — через перевод строки.
     *
     * Перевод строки здесь несущий, а не косметика. Это значение уедет туда, где сегодня стоит
     * `recognize(): String`, а его потребители режут результат по `\n` (`layoutOf`). Склеенная в
     * одну строку страница развалит раскладку ещё до того, как её кто-то увидит.
     */
    val text: String
        get() = readerText
            ?: lines(atoms).joinToString("\n") { line -> line.joinToString(" ") { it.text } }

    /**
     * Атомы, разложенные по строкам страницы (полосы по центроиду, см. [readingOrder]).
     *
     * Публичные, потому что строка — единица представления слоя наружу: индекс слов для
     * модели (#258) и будущий предпросмотр выделения показывают страницу построчно, и
     * каждый из них, собирая полосы заново, разошёлся бы с [text] на косой строке.
     */
    fun lines(subset: List<Atom> = atoms): List<List<Atom>> {
        val lines = mutableListOf<MutableList<Atom>>()
        subset.sortedBy { it.box.centerY }.forEach { atom ->
            val line = lines.lastOrNull()
            val sameLine = line != null &&
                kotlin.math.abs(line.last().box.centerY - atom.box.centerY) <= atom.box.height / 2f
            if (sameLine) line.add(atom) else lines.add(mutableListOf(atom))
        }
        return lines.map { it.sortedBy { atom -> atom.box.left } }
    }
}
