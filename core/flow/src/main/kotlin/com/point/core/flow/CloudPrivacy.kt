package com.point.core.flow

/**
 * Насколько далеко человек разрешает уходить своим объектам (#280).
 *
 * **Развилка, которую это закрывает.** Раньше приватность была границей в коде: сервис, который
 * логирует присланное, в цепочку не попадал вовсе. Звучит строго, а на деле решало за человека —
 * и отнимало у него ровно то, ради чего он поставил Point: бесплатное распознавание того, что
 * телефон не берёт. Решение владельца (04.08.2026): **приватность — настройка у человека, а не
 * фильтр при отборе.** В цепочку входят все живые бесплатные читатели, ранжированные по тому,
 * насколько хорошо они читают даром; куда именно попадает кадр — отдельный столбец, который видно.
 *
 * **Чего эта настройка НЕ делает.** Она не отправляет ничего сама и не отменяет согласия. Объект
 * уезжает наружу только после явного тапа, и человек по-прежнему видит, куда (`cloudDestination`).
 * Настройка отвечает на другой вопрос: кому вообще **можно предлагать** его прочитать.
 *
 * Порядок объявления — от самого свободного к самому закрытому, и это не украшение: умолчание
 * стоит первым, потому что человек, не открывавший настройки, должен получать максимум бесплатного.
 *
 * **Средний уровень строится по обещанию сервиса, а не по флагу страны** (перемер #490). Прежде он
 * назывался «Только Европа» и на бумаге звучал строже умолчания, а на деле подсовывал человеку
 * ровно тот сервис, который на бесплатном тарифе **учится на присланном** (Mistral, Франция), и
 * отсекал тех, кто письменно обещал не учиться (Groq и Cerebras — оба в США). Настройка, которая
 * успокаивает вместо того, чтобы защищать, хуже отсутствующей: человек считает, что закрылся, и
 * шлёт туда как раз то, чего не отправил бы. Юрисдикция никуда не делась — она видна человеку в
 * [ReaderPrivacy.where] у каждого читателя, — но решает не она, а сказанное сервисом про себя.
 */
enum class PrivacyLevel {

    /** Умолчание: читает всякий бесплатный, кто читает. Больше всего распознаётся даром. */
    FREE_FIRST,

    /** Наружу — только к тем, кто письменно обещал не учиться на присланном и не хранить его. */
    NO_TRAINING,

    /** Ничего не уходит. Остаётся то, что телефон умеет сам. */
    DEVICE_ONLY,
    ;

    /** Название уровня на экране настроек — языком продукта, без слова «провайдер». */
    val title: String
        get() = when (this) {
            FREE_FIRST -> "Максимум бесплатного"
            NO_TRAINING -> "Не учатся на моём"
            DEVICE_ONLY -> "Только на телефоне"
        }

    /**
     * Что человек выбирает, одной строкой.
     *
     * Каждая строка называет и выигрыш, и цену: выбор без цены — это не выбор, а уговаривание.
     */
    val what: String
        get() = when (this) {
            FREE_FIRST ->
                "Читают все бесплатные сервисы, какие есть, — так распознаётся больше всего даром. " +
                    "Часть из них учится на присланном и держит его у себя."
            NO_TRAINING ->
                "Наружу — только к тем, кто письменно обещал не учиться на присланном и не хранить его. " +
                    "Их меньше, и трудную страницу они возьмут не всегда."
            DEVICE_ONLY ->
                "Ничего не уходит с телефона. Остаётся то, что он читает сам, — фото документов ему даются плохо."
        }

    companion object {
        /** Максимум бесплатного — то, чего человек ждёт, ничего не настраивая. */
        val DEFAULT = FREE_FIRST

        /**
         * Прежнее имя уровня — не «чужое», а своё же вчерашнее.
         *
         * Человек, выбравший «Только Европа», просил закрыться сильнее умолчания. Отдать его на
         * [DEFAULT] значило бы молча снять настройку приватности — худший сорт сбоя, потому что он
         * невидим. Поэтому старое имя приводит на нынешний строгий уровень.
         */
        private const val WAS_EUROPE_ONLY = "EUROPE_ONLY"

        /** Забытое или чужое имя — не повод падать и не повод молча ослабить выбранное. */
        fun of(name: String?): PrivacyLevel = when (name) {
            WAS_EUROPE_ONLY -> NO_TRAINING
            else -> entries.firstOrNull { it.name == name } ?: DEFAULT
        }
    }
}

/**
 * Что сервис **письменно** обещал про присланное (перемер #490).
 *
 * Не догадка, не репутация и не флаг страны — сказанное на его собственной странице. Разница между
 * «обещал не учиться» и «промолчал» здесь такая же существенная, как между «нет» и «не сказал»: у
 * OCR.space написано «all uploaded documents are deleted after processing» и **ни слова** про
 * обучение, и выдавать это за обещание нельзя.
 */
enum class ReaderPromise {

    /** «Не будем учиться на присланном и не станем его хранить» — сказано прямо (Groq, OVH). */
    NO_TRAINING,

    /** Сказано обратное: учится по умолчанию, хранит, или читают живые люди (Mistral, Gemini). */
    TRAINS,

    /** Не сказано ничего. Молчание — не обещание (OCR.space про обучение, SambaNova). */
    UNKNOWN,
    ;

    /** Та же правда словами человека — рядом с адресатом, а не в сноске. */
    val what: String
        get() = when (this) {
            NO_TRAINING -> "обещал не учиться на присланном и не хранить его"
            TRAINS -> "учится на присланном и держит его у себя"
            UNKNOWN -> "про обучение на присланном не сказал ничего"
        }
}

/**
 * Что известно про чужой глаз, кроме того, как он читает.
 *
 * Столбец, а не приговор: [promise] никого больше не выбрасывает из цепочки — он рассказывает
 * человеку, чем оплачено бесплатное, и отбирает только на строгом уровне. Умолчание честное: про
 * неизвестный сервис нельзя обещать, что он ничего не хранит, — поэтому «не сказал ничего».
 *
 * Страна живёт в [where] текстом, а не флагом: она **видна** человеку и ни на что не влияет сама
 * по себе. Уровень приватности строится по [promise] — см. разбор у [PrivacyLevel].
 */
data class ReaderPrivacy(
    /** Куда попадает кадр, словами человека: «Mistral, Франция (ЕС)». */
    val where: String,
    /** Что сервис сказал про присланное — то, что различает уровень [PrivacyLevel.NO_TRAINING]. */
    val promise: ReaderPromise = ReaderPromise.UNKNOWN,
)

/**
 * Можно ли предлагать этот глаз на выбранном уровне.
 *
 * Вся развилка «кому можно» живёт здесь одной чистой функцией, а не расползается по цепочкам: иначе
 * уровень «только на устройстве» держался бы на том, что каждый вызывающий не забыл его спросить.
 *
 * Лестница обязана быть настоящей: всё, что пропущено строгим уровнем, пропускается и свободным.
 * Прежний средний уровень это правило нарушал по смыслу — пропускал учащегося на присланном и
 * отсекал обещавшего не учиться, — и это стерегут тесты.
 */
fun allowedAt(level: PrivacyLevel, privacy: ReaderPrivacy): Boolean = when (level) {
    PrivacyLevel.FREE_FIRST -> true
    PrivacyLevel.NO_TRAINING -> privacy.promise == ReaderPromise.NO_TRAINING
    PrivacyLevel.DEVICE_ONLY -> false
}

/**
 * Отбор цепочки под уровень — **с сохранением порядка**.
 *
 * Порядок в списке — это ранжирование по тому, кто лучше читает даром (замер, а не мнение). Отбор
 * не имеет права его пересобирать: иначе настройка приватности начала бы втихую менять качество
 * чтения, и человек не смог бы связать одно с другим.
 */
fun <T> allowedBy(level: PrivacyLevel, readers: List<T>, privacyOf: (T) -> ReaderPrivacy): List<T> =
    readers.filter { allowedAt(level, privacyOf(it)) }

/**
 * Общая цепочка моделей — **один адресат**, и обещать за неё нельзя ничего.
 *
 * Внутри неё маршрутизаторы и бесплатные тарифы разных стран, и кто именно ответит, решается в
 * рантайме. Сказать человеку «здесь не учатся», когда следующим в очереди может встать кто угодно,
 * — ровно та ложь, от которой лечит `cloudDestination`. Поэтому на строгом уровне цепочка моделей
 * молчит целиком, а читают только те, про кого мы знаем адрес и обещание поимённо.
 */
val AI_CHAIN_PRIVACY = ReaderPrivacy(
    where = "сервер AI-провайдера",
    promise = ReaderPromise.UNKNOWN,
)

/**
 * Выбранный уровень — за интерфейсом, как и всякий side-effect.
 *
 * Чтение синхронное (его спрашивают перед каждым сетевым шагом, и лишний прыжок в корутину тут
 * ничего не даёт), запись — suspend, как у соседних настроек.
 */
interface CloudPrivacySettings {
    fun level(): PrivacyLevel
    suspend fun setLevel(level: PrivacyLevel)
}

