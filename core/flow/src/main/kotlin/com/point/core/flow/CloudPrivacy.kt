package com.point.core.flow

/**
 * Насколько далеко человек разрешает уходить своим объектам (#280).
 *
 * **Развилка, которую это закрывает.** Раньше приватность была границей в коде: сервис, который
 * логирует присланное, в цепочку не попадал вовсе. Звучит строго, а на деле решало за человека —
 * и отнимало у него ровно то, ради чего он поставил Point: бесплатное распознавание того, что
 * телефон не берёт. Решение владельца (04.08.2026): **приватность — настройка у человека, а не
 * фильтр при отборе.** В цепочку входят все живые бесплатные читатели, ранжированные по тому,
 * насколько хорошо они читают даром; куда именно попадает кадр — отдельный столбец, который видно.
 *
 * **Чего эта настройка НЕ делает.** Она не отправляет ничего сама и не отменяет согласия. Объект
 * уезжает наружу только после явного тапа, и человек по-прежнему видит, куда (`cloudDestination`).
 * Настройка отвечает на другой вопрос: кому вообще **можно предлагать** его прочитать.
 *
 * Порядок объявления — от самого свободного к самому закрытому, и это не украшение: умолчание
 * стоит первым, потому что человек, не открывавший настройки, должен получать максимум бесплатного.
 */
enum class PrivacyLevel {

    /** Умолчание: читает всякий бесплатный, кто читает. Больше всего распознаётся даром. */
    FREE_FIRST,

    /** Наружу — только к европейским сервисам. Их меньше, и берут они не всё. */
    EUROPE_ONLY,

    /** Ничего не уходит. Остаётся то, что телефон умеет сам. */
    DEVICE_ONLY,
    ;

    companion object {
        /** Максимум бесплатного — то, чего человек ждёт, ничего не настраивая. */
        val DEFAULT = FREE_FIRST

        /** Забытое или чужое имя — не повод падать и не повод молча закрыться сильнее. */
        fun of(name: String?): PrivacyLevel =
            entries.firstOrNull { it.name == name } ?: DEFAULT
    }
}

/**
 * Что известно про чужой глаз, кроме того, как он читает.
 *
 * Столбец, а не приговор: [logsRequests] никого больше не выбрасывает из цепочки — он рассказывает
 * человеку, чем оплачено бесплатное. Умолчание честное: про неизвестный сервис нельзя обещать, что
 * он ничего не хранит.
 */
data class ReaderPrivacy(
    /** Куда попадает кадр, словами человека: «Mistral, Франция (ЕС)». */
    val where: String,
    /** Сервер в Европе — то, что различает уровень [PrivacyLevel.EUROPE_ONLY]. */
    val europe: Boolean = false,
    /** Бесплатно в обмен на данные: запрос логируется или его читают живые рецензенты. */
    val logsRequests: Boolean = true,
)

/**
 * Можно ли предлагать этот глаз на выбранном уровне.
 *
 * Вся развилка «кому можно» живёт здесь одной чистой функцией, а не расползается по цепочкам: иначе
 * уровень «только на устройстве» держался бы на том, что каждый вызывающий не забыл его спросить.
 */
fun allowedAt(level: PrivacyLevel, privacy: ReaderPrivacy): Boolean = when (level) {
    PrivacyLevel.FREE_FIRST -> true
    PrivacyLevel.EUROPE_ONLY -> privacy.europe
    PrivacyLevel.DEVICE_ONLY -> false
}

/**
 * Отбор цепочки под уровень — **с сохранением порядка**.
 *
 * Порядок в списке — это ранжирование по тому, кто лучше читает даром (замер, а не мнение). Отбор
 * не имеет права его пересобирать: иначе настройка приватности начала бы втихую менять качество
 * чтения, и человек не смог бы связать одно с другим.
 */
fun <T> allowedBy(level: PrivacyLevel, readers: List<T>, privacyOf: (T) -> ReaderPrivacy): List<T> =
    readers.filter { allowedAt(level, privacyOf(it)) }

/**
 * Общая цепочка моделей — **один адресат**, и обещать про неё Европу нельзя.
 *
 * Внутри неё маршрутизаторы и бесплатные тарифы разных стран, и кто именно ответит, решается в
 * рантайме. Сказать человеку «это Европа», когда следующим в очереди может встать кто угодно, —
 * ровно та ложь, от которой лечит `cloudDestination`. Поэтому на уровне «только Европа» цепочка
 * моделей молчит целиком, а читают только те, про кого мы знаем адрес поимённо.
 */
val AI_CHAIN_PRIVACY = ReaderPrivacy(
    where = "сервер AI-провайдера",
    europe = false,
    logsRequests = true,
)

/**
 * Выбранный уровень — за интерфейсом, как и всякий side-effect.
 *
 * Чтение синхронное (его спрашивают перед каждым сетевым шагом, и лишний прыжок в корутину тут
 * ничего не даёт), запись — suspend, как у соседних настроек.
 */
interface CloudPrivacySettings {
    fun level(): PrivacyLevel
    suspend fun setLevel(level: PrivacyLevel)
}

/** Название уровня на экране настроек — языком продукта, без слова «провайдер». */
val PrivacyLevel.title: String
    get() = when (this) {
        PrivacyLevel.FREE_FIRST -> "Максимум бесплатного"
        PrivacyLevel.EUROPE_ONLY -> "Только Европа"
        PrivacyLevel.DEVICE_ONLY -> "Только на телефоне"
    }

/**
 * Что человек выбирает, одной строкой.
 *
 * Каждая строка называет и выигрыш, и цену: выбор без цены — это не выбор, а уговаривание.
 */
val PrivacyLevel.what: String
    get() = when (this) {
        PrivacyLevel.FREE_FIRST ->
            "Читают все бесплатные сервисы, какие есть, — так распознаётся больше всего даром. " +
                "Часть из них оставляет присланное у себя."
        PrivacyLevel.EUROPE_ONLY ->
            "Наружу — только к европейским сервисам. Их меньше, и трудную страницу они возьмут не всегда."
        PrivacyLevel.DEVICE_ONLY ->
            "Ничего не уходит с телефона. Остаётся то, что он читает сам, — фото документов ему даются плохо."
    }

