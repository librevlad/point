package com.point.core.flow

/**
 * Транспортная ошибка провайдера — не слова для человека: «Software caused
 * connection abort» уходил на экран как исход «В Excel» (живая находка владельца,
 * 2026-08-09). Общий словарь обеих сторон: канал переводит такие ошибки в
 * человеческое «связь оборвалась», не теряя честности отказа.
 */
fun looksLikeNetworkFailure(error: String): Boolean =
    NETWORK_FAILURE_HINTS.any { error.contains(it, ignoreCase = true) }

fun looksLikeQuotaFailure(error: String): Boolean =
    QUOTA_FAILURE_HINTS.any { error.contains(it, ignoreCase = true) }

/**
 * Нечем открыть — человеческими словами и с выходом (#675/#679): системное
 * «No Activity found to handle Intent { … dat=geo: … }» уходило человеку в лицо.
 */
fun noAppFor(scheme: String?): String = when (scheme?.lowercase()) {
    "tel" -> "На этом устройстве нечем звонить — номер можно скопировать"
    "smsto", "sms" -> "На этом устройстве нет приложения сообщений — номер можно скопировать"
    "mailto" -> "На этом устройстве нет почты — адрес можно скопировать"
    "geo" -> "На этом устройстве нет карт — адрес можно скопировать"
    "http", "https" -> "На этом устройстве нет браузера — ссылку можно скопировать"
    else -> "На этом устройстве нечем это открыть — значение можно скопировать"
}

/**
 * Исполнителя под этот объект нет (#857).
 *
 * Раньше телефон падал здесь строкой `No realizer for capability=…`, и она долетала до
 * экрана: `FlowViewModel` показывает `e.message`. Человек не заводил ни «realizer», ни
 * «capability» — и ответа на свой вопрос из этой строки не получал. Компьютер в том же
 * месте отказывал словами.
 *
 * Нет исполнителя — это честный отказ, а не сбой.
 */
const val NO_WAY_HERE_REASON = "Это действие для такого объекта не выполняется"

const val FREE_LIMIT_SPENT = "бесплатное чтение на сегодня закончилось"

/**
 * Что человек читает, когда бесплатное на сегодня кончилось (#840).
 *
 * Прежняя фраза — «Бесплатные лимиты чтения исчерпаны — вернитесь позже, платить не идём» —
 * выдавала нашу кухню: «лимиты чтения» человек нигде не заводил, а «платить не идём» это
 * вообще наше внутреннее решение, а не его дело. Сказано то, что его касается: сегодня
 * больше не выйдет, завтра выйдет.
 */
const val FREE_LIMITS_SPENT_TEXT = "На сегодня бесплатное чтение закончилось — попробуйте завтра"

private val NETWORK_FAILURE_HINTS = listOf(
    "resolve host", "No address associated", "Unable to resolve",
    "connection abort", "Network is unreachable", "Failed to connect",
    "timed out", "timeout", "Connection reset", "Broken pipe",
)

/**
 * Признак «уперлись в бесплатный предел». Первое — объявленное слово, остальное — следы
 * чужих ответов, которые к нам приходят как есть.
 *
 * До #859 признак держался на скобках `(402)` и `(429)`, случайно уцелевших в человеческой
 * фразе: переписать фразу по-человечески значило молча потерять признак. Теперь фраза одна
 * и объявлена, а коды остались только для чужих строк.
 */
private val QUOTA_FAILURE_HINTS = listOf(FREE_LIMIT_SPENT, FREE_LIMITS_SPENT_TEXT, "(402)", "(429)")
