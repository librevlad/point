package com.point.core.flow

/**
 * Выбеленная копия кадра, по которой читают (#1046).
 *
 * Фото документа, снятое с рук, остаётся фотографией: тень от руки, градиент от окна,
 * синеватый оттенок камеры, серая бумага. Движок на таком кадре не видит строк — замер
 * 04.08.2026 показал, что неровный свет рассыпает сетку таблицы и структура документа не
 * собирается вовсе.
 *
 * Это первая ступень того же второго захода, который завёл #1041, а не вторая дорога рядом:
 * плохое чтение → подготовить кадр → прочитать снова. Ступеней две, и порядок у них не
 * произвольный. Выбеливание не двигает слова: геометрия кадра остаётся геометрией снимка, и
 * прочитанное возвращается на него вместе с координатами — подсветка найденного, `at.region`
 * и вырезка ячейки продолжают работать. Выпрямление ([StraightFrame]) слова двигает, и от
 * второго захода после него остаётся только текст. Поэтому бережное пробуется первым.
 *
 * Реализация трогает пиксели и файлы, поэтому она за интерфейсом.
 */
fun interface PaperWhitener {

    /**
     * Выбелить кадр, лежащий по пути [path].
     *
     * `null` — выбелить нечем или не вышло. Это ответ про попытку, а не про объект:
     * читается тогда только сам снимок.
     */
    suspend fun whitened(path: String): WhitenedFrame?
}

/**
 * Копия кадра и то, во сколько раз она мельче снимка.
 *
 * Выбеливать снимок в полном размере незачем: читатель всё равно уменьшает кадр до своего
 * потолка, а обработка в полный размер стоила бы десятков мегабайт. [shrink] — во сколько
 * раз копия уменьшена (делением пополам, как умеет декодер), и он же возвращает прочитанные
 * слова на снимок человека.
 */
class WhitenedFrame(val path: String, val shrink: Int) {

    init {
        require(shrink >= 1) { "shrink must be >= 1, was $shrink" }
    }
}

/**
 * Тот же слой, но в координатах снимка человека (#1046).
 *
 * Слова прочитаны на уменьшенной копии, а показывать, вырезать и подсвечивать их придётся
 * на самом снимке: по координатам слов встают подсветка найденного, `at.region` у знания и
 * вырезка ячейки. Оставить их в координатах копии значило бы промахиваться мимо ровно на
 * тех кадрах, ради которых второй заход и делался.
 */
fun AtomLayer.inSourceFrame(shrink: Int): AtomLayer {
    if (shrink <= 1) return this
    return AtomLayer(
        atoms = atoms.map { atom ->
            atom.copy(
                box = Box(
                    atom.box.left * shrink,
                    atom.box.top * shrink,
                    atom.box.right * shrink,
                    atom.box.bottom * shrink,
                ),
            )
        },
        readerText = readerText,

        // Перевод координат к файлу удлиняется во столько же раз: слова уже перенесены на
        // снимок, и обратный ход (`toUpright`) обязан считать по тому же множителю.
        transform = transform?.copy(sample = transform.sample * shrink),
        incomplete = incomplete,
    )
}
