package com.point.core.flow

/**
 * Что Point помнит о вещах человека — одним местом (#1026).
 *
 * Память про объекты лежит в четырёх местах: перечень «Недавнего», копии самих объектов,
 * снимок текущего разбора и журнал обменов с моделью. «Забыть всё» знало только про первое,
 * поэтому человек нажимал «Забыть всё», читал «Пока ничего не сохранено» — и оставался с
 * объектом, вычитанным из него знанием и перепиской на устройстве.
 *
 * Это не новое хранилище: здесь один вопрос к тем же хранилищам, у которых он раньше не
 * задавался целиком. Настройки, ключи и аккаунт памятью об объектах не являются и сюда не
 * входят: у них свои двери.
 */
interface PointMemory {

    /** Сколько объектов Point помнит и сколько места занимает всё, что он про них держит. */
    suspend fun footprint(): HistoryFootprint

    /**
     * Забыть всё, что обещано: записи, копии объектов, снимок разбора, журнал обменов.
     *
     * Возвращает то, чего человек лишился, — чтобы экран сказал, что именно сделано, а не
     * промолчал.
     */
    suspend fun forgetAll(): HistoryFootprint
}

/**
 * Что убрано — словами человека (#1026).
 *
 * Молчание после «Убрать всё» читалось как «не сработало»: экран не менялся ничем. Здесь
 * сказано ровно то, что произошло, — и «забывать было нечего» тоже исход, а не пустота.
 */
fun forgottenText(gone: HistoryFootprint?): String {
    if (gone == null) return "Забыть не вышло — попробуйте ещё раз"
    val weight = humanWeight(gone.bytes)
    if (gone.count == 0 && weight == null) return "Забывать было нечего"
    val things = gone.count.toLong()
    val what = if (things == 0L) {
        "всё, что оставалось"
    } else {
        "$things " + plural(things, "объект", "объекта", "объектов")
    }
    return "Забыто: " + what + (weight?.let { " · $it" } ?: "")
}
