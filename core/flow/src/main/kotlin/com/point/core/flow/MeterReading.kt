package com.point.core.flow

import com.point.core.model.Provenance

/**
 * Показание счётчика — факт, которого у объекта не было **вовсе** (#262).
 *
 * Прецедент — трек (#260, [trackFacts]): у корпуса владельца три кадра из двадцати двух, где
 * человек пришёл передать показание (вода `154 м³`, водомер, электричество `20842 кВт·ч`), и
 * измерить их было нечем — не потому, что действие сложное, а потому, что самого факта никто не
 * писал. Схема без факта лгала бы в обе стороны, поэтому факт заводится вместе со схемой.
 *
 * **Форма — число рядом с единицей учёта.** Это ровно та же порода правила, что «14 цифр — похоже
 * на накладную»: дешёвая, офлайновая, ошибающаяся. Поэтому она **размечает, а не решает**
 * (#232, #258): улика ровно одна — [EvidenceClass.SEMANTIC], — и карточка честно скажет
 * «возможно», пока второй независимый класс не принесёт тот, кто смотрел на слой страницы
 * ([fieldEvidence]: подпись «Показання» рядом со значением — это уже другой класс).
 *
 * **Почему минимум [METER_MIN_DIGITS] цифры.** «Залито 2 м³ бетону» и «спожито 12 м³» — объёмы в
 * прозе, а не показания табло; настоящие кадры корпуса дают `154` (вода) и `20842`
 * (электричество). Порог — не вкус, а два живых примера против двух живых ложных.
 *
 * **Значение — только цифры показания**, единица живёт своим ключом ([META_ENTITY_METER_UNIT]).
 * Иначе правило и модель поссорились бы на глифе: OCR читает «кВтч», модель пишет «кВт·ч», и
 * [normConsensus] (складывает пробелы и точки, но не «·») объявил бы ложный спор о числе,
 * которое оба прочитали одинаково.
 */
data class MeterReading(
    /** Цифры показания, дословно со страницы: `20842`, `154,3`. */
    val value: String,
    /** Единица учёта, дословно: `кВт·ч`, `м³`. Она и есть причина считать число показанием. */
    val unit: String,
)

/**
 * Показание счётчика как факт объекта: тот же ключ читает схема «Передать показание счётчика»
 * ([ACTION_SCHEMAS]) и пишет «Понять» (контрактный ключ `METER`) — два независимых источника
 * одного факта встречаются в [mergeFacts], цифры неприкосновенны, спор виден.
 */
const val META_ENTITY_METER = META_ENTITY_PREFIX + "meter"

/**
 * Единица учёта показания — **факт, а не аннотация**: `.unit` не входит в [isAnnotationKey],
 * поэтому голосование источников её касается наравне с прочими значениями. Она отвечает на
 * «какой это счётчик» (вода или электричество) — то есть куда показание передавать, — и
 * поэтому стоит в схеме побочным полем, а не выбрасывается как «формат».
 */
const val META_ENTITY_METER_UNIT = META_ENTITY_METER + ".unit"

/** Ниже этого число рядом с единицей — объём в прозе («2 м³ бетону»), а не показание табло. */
internal const val METER_MIN_DIGITS = 3

/** Выше — уже не показание, а номер счётчика, стоящий рядом с той же единицей. */
internal const val METER_MAX_DIGITS = 8

/**
 * Столько ли цифр в целой части, сколько бывает на табло.
 *
 * **Одна реализация границы на обоих судей** — правило ([meterReadings]) и валидатор чтения
 * модели ([semanticFits]). Два счётчика формы разъехались бы на первой правке, и «модель
 * прочитала то, чего правило не приняло бы» стало бы невидимым. Дробная часть не считается:
 * `154,3` — то же трёхзначное показание, у которого просто есть десятые.
 */
internal fun meterDigitsFit(value: String): Boolean =
    value.substringBefore(',').substringBefore('.').count(Char::isDigit) in
        METER_MIN_DIGITS..METER_MAX_DIGITS

/**
 * Показания счётчика в [text] в порядке появления, без повторов (одно и то же число с той же
 * единицей в шапке и в таблице — одно показание).
 *
 * Границы числа стерегутся с обеих сторон: длинный номер счётчика рядом с «кВт·ч» не даёт
 * обрезка-показания (тот же урок, что у [waybillNumbers] — «рахунок 202045149154939512» не трек).
 * **Разрядный пробел — часть числа, а не граница** (ревью #262): «20 842 кВт·ч» обязано читаться
 * целиком, иначе правило пишет `842` и помечает его `src=ocr` — то есть выдаёт выдуманное
 * значение за прочитанное дословно. Пробел внутри значения безопасен: [normConsensus] его
 * складывает, поэтому «20 842» правила и «20842» модели — согласие, а не спор.
 *
 * **Названная граница:** объём потребления стоит рядом с той же единицей, что и показание
 * («спожито за місяць 250 кВт·ч»), и формой они не отличаются вовсе. Правило поэтому и
 * **размечает, а не решает**: улика ровно одна, и человек видит «возможно».
 */
fun meterReadings(text: String): List<MeterReading> =
    METER_SHAPED.findAll(text)
        .map { MeterReading(it.groupValues[1].trim(), it.groupValues[2].trim()) }
        .filter { meterDigitsFit(it.value) }
        .distinctBy { it.value.filter(Char::isDigit) + "|" + it.unit.lowercase() }
        .toList()

/**
 * Показание как факты объекта: значение, единица, происхождение и улика формы. Несколько
 * показаний на странице (день/ночь, вода и свет одним счётом) — все в `entity.meter.more`:
 * подтверждение первого моделью не имеет права стереть запись о втором (конвенция `.more`, #260).
 *
 * **Названная граница:** `.more` несёт числа без единиц — единица записана у первого показания.
 * Второе показание не теряется, теряется его подпись; чинить это стоит только тогда, когда
 * появится действие, которое передаёт оба разом.
 */
fun meterFacts(text: String): Map<String, String> {
    val readings = meterReadings(text)
    val first = readings.firstOrNull() ?: return emptyMap()
    // Одно и то же число, снятое с двух счётчиков разом («154 м³» холодной и горячей), — не
    // «второе показание»: в `.more` идут РАЗНЫЕ значения, иначе строка «или:» спорит сама с собой.
    val values = readings.map { it.value }.distinct()
    return buildMap {
        put(META_ENTITY_METER, first.value)
        put(META_ENTITY_METER_UNIT, first.unit)
        // ПРОЧИТАНО: правило нашло эти цифры дословно в распознанном тексте, а не вывело их (#264).
        put(META_ENTITY_METER + META_SOURCE_SUFFIX, Provenance.OCR.wire)
        // Улика ровно одна — форма. «Не судили» и «улик мало» обязаны выглядеть по-разному (#264).
        put(META_ENTITY_METER + META_EVIDENCE_SUFFIX, EvidenceClass.SEMANTIC.name.lowercase())
        if (values.size > 1) put(META_ENTITY_METER + META_MORE_SUFFIX, altValue(values))
    }
}

/**
 * Показание без ведущих нулей барабана — **подсказка, а не значение** (#262).
 *
 * Живые кадры устройства приходят с барабана дословно: `00001154` (это 154 м³), `007145`,
 * `0208425`. Обрезать нули молча правило права не имеет — **сколько разрядов значащие, знает
 * поставщик услуги, а не Point**: где-то передают все восемь, где-то последние пять, и «умная»
 * обрезка меняла бы переданное показание, оставаясь помеченной `src=ocr`, то есть выдавала бы
 * своё число за прочитанное дословно (ровно та болезнь, которую ревью #262 уже ловило на
 * разрядном пробеле). Но и оставить человека наедине с `00001154` — значит заставить его
 * считать нули самому.
 *
 * Поэтому нули не трогаются в факте и убираются в подсказке: [meterFacts] пишет дословное
 * `00001154`, а карточка готовности показывает рядом «обычно передают 1154» — оба числа видно,
 * и видно, какое из них со страницы.
 *
 * `null` — подсказывать нечего: ведущих нулей нет (`20842`) либо подсказка совпала бы со
 * значением (`0` — это и есть ноль). Прецедент молчания — [provenanceLabel] и
 * [readingModeLabel]: норма не подписывается, иначе подпись превращается в шум и перестаёт
 * читаться там, где она важна. Барабан из одних нулей (`000`) — законный ноль, а не пустота:
 * подсказка `0`, потому что пустая строка на её месте была бы худшим исходом — «показание
 * есть, а числа нет».
 *
 * **И молчит про то, что числом не признано** (ревью #262). Писателей у факта трое, и один из
 * них — модель (контрактный ключ `METER` в «Понять»), а форма её ответа улику даёт, но ничего
 * не блокирует ([semanticFits] размечает, а не решает, а `judgeFields` в «Понять» отклоняет
 * только невозможную контрольную цифру). Значит в `entity.meter` законно ложится `0 показань` или
 * `00154 м³` — слово, прилипшее к цифрам, или единица, которой полагается жить своим ключом.
 * Срезать у такой строки «нули» значило бы посоветовать человеку передать «показань»: Point
 * выдал бы за обычную практику то, чего он вовсе не прочитал. Поэтому подсказка выводится
 * только из числа табло — цифры, разрядные пробелы, одна дробная часть, — а на всём прочем
 * молчит, и молчание тут дешевле догадки.
 *
 * **Названные границы.**
 * - Нули съедают бюджет разрядов: `000011540` — девять цифр, и [meterDigitsFit] не примет его
 *   вовсе. Чинить это стоит вместе с решением, считать ли границу по значащим цифрам (тогда
 *   десятизначный номер счётчика с ведущим нулём пройдёт как показание), и с живым кадром
 *   девятипозиционного барабана в руках, а не «на всякий случай».
 * - «Понять» просит у модели ТОЛЬКО цифры показания, и модель **может** вернуть `1154` там,
 *   где правило прочло `00001154` (обязать её к этому контракт не обязывает — `METER=00154`
 *   дословно тоже законный ответ, см. `UnderstandRealizerTest`). Тогда [mergeFacts] запишет
 *   спор, карточка скажет «или: 1154». Это честно — два источника прочли **разное дословно**,
 *   — и чинить это сворачиванием нулей в [normConsensus] нельзя: там же голосуют телефоны, у
 *   которых ведущий ноль часть номера.
 */
fun meterWithoutDrumZeros(value: String): String? {
    val v = value.trim()
    if (!v.startsWith('0') || !DRUM_NUMBER.matches(v)) return null
    val cut = v.indexOfFirst { it == ',' || it == '.' }
    val whole = if (cut < 0) v else v.substring(0, cut)
    val fraction = if (cut < 0) "" else v.substring(cut)
    // Разрядный пробел внутри нулей — тоже оформление барабана, а не граница числа: «000 154».
    val significant = whole.replaceFirst(DRUM_ZEROS, "")
    // Сравнение с **обрезанным** значением: пробел по краям — не то различие, ради которого
    // карточке стоит открывать рот, иначе у « 0 » завелась бы «подсказка» «0».
    return (significant.ifEmpty { "0" } + fraction).takeIf { it != v }
}

/** Ведущие нули барабана вместе с разрядными пробелами между ними. */
private val DRUM_ZEROS = Regex("^[0\\s\\u00A0]+")

/** Число, каким его пишет табло: цифры, разрядные пробелы, одна дробная часть — и ничего ещё. */
private val DRUM_NUMBER = Regex("\\d+(?:[\\s\\u00A0]\\d+)*(?:[.,]\\d+)?")

/**
 * Подсказка к прочитанному полю — то, что человек, скорее всего, передаст, — либо `null`,
 * когда подсказывать нечего. Значение полем не подменяется никогда ([FieldReading.hint]).
 *
 * **Почему функция, а не ключ метаданных** — развилка #262, решённая в пользу вывода в момент
 * чтения. Соблазн был записать `entity.meter.plain` рядом с фактом; против — три вещи, каждая
 * из которых этот код уже кусала:
 * 1. **Метаданные факта — то, что прочитано со страницы.** Производная, которой не читал никто,
 *    легла бы туда значением без происхождения: `Provenance.OCR` про неё соврал бы (её нет на
 *    странице), `RULE` — тоже (правило её не выводило, это оформление). Хуже того, [factKeyOf]
 *    берёт **первый неаннотационный ключ** — подсказка могла бы стать «фактом узла», а чтобы
 *    этого не случилось, пришлось бы завести общий суффикс-аннотацию ради одного поля.
 * 2. **Значение живёт дальше:** голосование [mergeFacts], ремонт [isRepairOf], подтверждение
 *    человеком. Записанная подсказка после любого из них указывает на прежнее значение — и
 *    молча: это ровно те «два источника истины», от которых лечит `ValueProvenance`.
 * 3. **Писателей у факта трое** (правило в двух энричерах и контрактный ключ «Понять»), и ключ
 *    пришлось бы писать в каждом — то есть однажды забыть в одном.
 *
 * Вывод в момент чтения стоит один проход по строке и разъехаться со значением не может.
 *
 * Развилка «`when` по ключу против `if` внутри [ActionSchema.readiness]» решена по прецеденту
 * [semanticFits]: место, где решается «у этого поля есть подсказка», ровно одно, и готовность
 * действий не обязана знать про барабаны счётчиков. Сегодня поле здесь одно — трек и телефон
 * подсказки не получают сознательно: их ведущий ноль часть номера, а не оформление.
 */
fun fieldHint(key: String, value: String): String? = when (key) {
    META_ENTITY_METER -> meterWithoutDrumZeros(value)
    else -> null
}

/**
 * Единицы учёта, которые пишут на счётчиках и в квитанциях здесь. Список сознательно короткий и
 * дословный: каждая новая строка — это новый способ ошибиться, и добавлять её стоит с живым
 * кадром в руках, а не «на всякий случай».
 */
private val METER_UNITS = listOf(
    "кВт·ч", "кВт*ч", "кВт.ч", "кВтч", "кВт·год", "кВт*год", "кВт.год", "кВтгод", "kWh", "kW·h",
    "м³", "м3", "куб.м", "м.куб", "m³", "m3",
    "Гкал", "Gcal",
)

/**
 * Число с единицей: `(?iu)` — регистронезависимость **с юникодом** (без `u` «КВТ·Ч» мимо: флаг
 * Java без `UNICODE_CASE` складывает только ASCII). Длинные единицы стоят в альтернативе раньше
 * коротких, иначе «кВт·ч» съедалось бы куском «кВт.ч» → «кВтч».
 *
 * Число читается в двух формах, и разрядная стоит первой, иначе она разобралась бы последней
 * тройкой: `20 842` (группы ровно по три — «20 4514» так не склеится) либо сплошное. Сколько
 * цифр законно, решает не регекс, а [meterDigitsFit] — граница живёт в одном месте.
 */
private val METER_SHAPED = Regex(
    "(?iu)(?<![\\d.,])((?:\\d{1,3}(?:[\\s\\u00A0]\\d{3})+|\\d{1,$METER_MAX_DIGITS})" +
        "(?:[.,]\\d{1,3})?)" +
        "\\s{0,2}(" +
        METER_UNITS.sortedByDescending { it.length }.joinToString("|") { Regex.escape(it) } +
        ")(?![\\p{L}\\d])",
)
