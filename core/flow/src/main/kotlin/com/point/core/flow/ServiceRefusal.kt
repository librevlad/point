package com.point.core.flow

/**
 * Слова человеку, когда чужой сервис отказал (#859).
 *
 * Функция `refusal(code)` была объявлена девять раз, и у пяти облачных читалок совпадала
 * почти дословно:
 *
 * ```
 * 402 -> "$READER: бесплатный лимит исчерпан (402) — покупать не идём, пробуем следующий"
 * 429 -> "$READER: слишком часто (429) — пробуем следующий"
 * ```
 *
 * Это те же фразы, которые чинил #847, только уцелевшие: «покупать не идём» — наше решение
 * про бюджет, «пробуем следующий» — наша механика перебора, `ocr-space` и `llamaparse` —
 * внутренние имена, а `(402)` — код протокола на экране.
 *
 * Правило в проекте уже было записано тестом `OpenAiCompatibleClientTest`: «отказ сервиса
 * написан словами — без кода, без слова HTTP и без чужого ответа». Оно выполнялось у одного
 * клиента из девяти. Теперь слова одни, и это же делает признак «уперлись в лимит» надёжным:
 * цепочка узнаёт его по объявленному слову, а не по скобкам с числом, случайно уцелевшим
 * во фразе.
 *
 * @param hint что человек может сделать — если может. Без подсказки отказ просто называет,
 *   что произошло.
 */
fun serviceRefusal(code: Int, hint: String? = null): String {
    val what = when (code) {
        401, 403 -> KEY_NOT_TAKEN
        402, 429 -> FREE_LIMITS_SPENT_TEXT
        404 -> "Сервис не отвечает по этому адресу"
        413 -> "Файл великоват — сервис его не берёт"
        in 500..599 -> "Сервис сейчас не отвечает"
        else -> "Сервис отказал"
    }
    return if (hint.isNullOrBlank()) what else "$what — $hint"
}

/**
 * Сервис ответил, но взять из ответа нечего (#859).
 *
 * Шесть читалок писали это своими словами — «$READER: ответ не разобран — пробуем
 * следующий». Человеку в этой фразе не адресовано ничего: ни `ocr-space`, ни наш перебор
 * очереди. Ему адресован сам факт — прочитать не вышло.
 */
const val UNREADABLE_ANSWER = "Сервис ответил непонятно — прочитать не вышло"

/** Объявленное слово про непринятый ключ: по нему же узнаётся исход обращения (#1236). */
const val KEY_NOT_TAKEN = "Сервис не принял ключ"

/**
 * Сервис ответил «всё хорошо» кодом, а внутри ответа — отказ (#1259).
 *
 * Так отвечает OCR.space: код 200, `IsErroredOnProcessing=true` и английское поле
 * `ErrorMessage`, которое уходило человеку дословно — «ocr-space: Invalid API key» на
 * русском экране. Переводчик кодов сюда не попадал, потому что код был успешный. Разбор —
 * по тем же признакам, какими Point читает и чужие транспортные строки: чужой текст остаётся
 * на своём слое, человеку — своё слово.
 */
fun serviceRefusalInAnswer(said: String): String = when {
    looksLikeKeyRefusal(said) -> KEY_NOT_TAKEN
    looksLikeTooBig(said) -> serviceRefusal(413)
    looksLikeQuotaFailure(said) -> FREE_LIMITS_SPENT_TEXT
    else -> SERVICE_DID_NOT_READ
}

