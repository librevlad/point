package com.point.core.flow

/**
 * Выделение человека, притянутое к атомам (#259).
 *
 * Выделение — **не новая подсистема, а тот же контракт адресации** (design v3 §9): polygon
 * рисует человек вместо модели. Долговечный адрес захваченного — [ids] (набор атомов), а не
 * прямоугольник: он идёт в тот же валидируемый резолвер ([AtomLayer.resolve] c
 * [AtomAddress.ByIds]), что и ответ модели, и переживает перерисовку области. [region] —
 * представление для глаз: рамка, которую экран показывает вместо кривого пальца.
 *
 * Пустой захват ([atoms] пуст) — законное состояние, не ошибка: человек обвёл пиксели, где
 * движок ничего не прочитал (рукопись, штамп, фото в фото). Рамка остаётся исходной (только
 * выпрямленной), и это честный вход для будущего пути «непрочитанного» — кроп по сырым
 * координатам с происхождением.
 *
 * О связности: двухстрочный или разнесённый захват резолвится через [AtomLayer.resolve] с
 * `disjoint=true` — и для выделения это **не порок**. Флаг ловит порванную связь «ответ модели ↔
 * координаты»; здесь координаты назвал сам человек, его полигон — истина, а не предположение.
 * Потребитель адреса выделения не имеет права превращать разнесённость в предупреждение.
 */
data class SnappedSelection(
    /**
     * Внешние границы захвата одной рамкой — для кропа. Рисовать поверх страницы надо
     * [lineRegions]: внешняя рамка на несколько строк накрывает и то, что между ними не
     * захвачено, и показ такой рамки утверждал бы захват слова, которого в [atoms] нет
     * (ревью #284). Без захвата — выпрямленная исходная.
     */
    val region: Box,
    /** Захваченные атомы в порядке чтения страницы. */
    val atoms: List<Atom>,
    /** Текст захваченного в порядке чтения — то, что экран показывает до вызова модели. */
    val text: String,
    /** Рамки по строкам захвата — единственный честный способ подсветить многострочный захват:
     *  внутри строки захват непрерывен (осевая рамка не перепрыгивает слово), между строками —
     *  ничего лишнего не нарисовано. */
    val lineRegions: List<Box> = emptyList(),
) {
    val ids: List<String> get() = atoms.map { it.id }
}

/**
 * Притягивает кривую рамку человека к атомам: захват — атомы, чей бокс **пересекает** рамку,
 * итоговая область — объединение их боксов.
 *
 * Рамка живёт **на одной странице** ([page]): человек рисует по конкретному развороту, а
 * координаты атомов разных страниц лежат в одном пространстве — без фильтра выделение на
 * первой странице PDF молча захватило бы слова со всех остальных. ([AtomLayer.atomsIn] несёт
 * то же плоское допущение — для области, которую рисует модель, страницу выберет вызов;
 * выравнивать оба адреса по странице — работа PDF-среза.)
 *
 * Пересечение, а не центроид — сознательное расхождение с резолвером значений
 * ([AtomLayer.atomsIn]). У них разные ошибки с разной ценой (#259, граница Copilot):
 *
 * - резолвер судит **адрес, названный моделью**, и обязан быть строгим — по пересечению в
 *   значение затекла бы подпись из соседней строки, край которой заходит в область на пиксель;
 * - притягивание судит **палец человека**, и обязано быть щедрым — обвёл номер впритык или
 *   зацепил полслова, а система «честно не нашла» поле рядом — это новый способ соврать.
 *
 * Щедрость безопасна ровно потому, что захват **показывается до вызова модели**: лишнее слово
 * видно и убирается пальцем, а тихо потерянное не видно никому. Расширение идёт по целым
 * атомам — слово не режется пополам ни по ширине, ни по высоте строки.
 *
 * «Расширяется до целых спанов **и строк**» из #259 здесь прочитано так: строка, задетая рамкой
 * хоть на долю высоты, отдаёт задетые слова **целиком** (бокс слова — полная высота строки) —
 * вертикальное достраивание даёт само пересечение. Достраивание строки **по ширине** сознательно
 * не делается: оно захватывало бы соседей по строке, которых палец не трогал, — на строке
 * «подпись: значение» обвод значения тащил бы подпись в каждый захват.
 *
 * [raw] — в координатах **сырого кадра слоя**, тех же, что `box` атомов; превью-координаты
 * конвертирует вызывающий через [AtomLayer.transform] до вызова.
 */
fun AtomLayer.snapSelection(raw: Box, page: Int = 0): SnappedSelection {
    // Палец ведут из любого угла: рамка жеста приходит и «перевёрнутой» (точка нажатия правее
    // или ниже точки отпускания), а перевёрнутый Box не пересекается ни с чем — молча пустой
    // захват был бы ровно той ложью, которую этот контракт запрещает (ревью #284).
    val frame = Box(
        minOf(raw.left, raw.right),
        minOf(raw.top, raw.bottom),
        maxOf(raw.left, raw.right),
        maxOf(raw.top, raw.bottom),
    )
    val hit = readingOrder(atoms.filter { it.page == page && it.box.intersects(frame) })
    if (hit.isEmpty()) return SnappedSelection(frame, emptyList(), "")
    return SnappedSelection(
        region = hit.map { it.box }.reduce(Box::union),
        atoms = hit,
        text = hit.joinToString(" ") { it.text },
        lineRegions = lines(hit).map { line -> line.map { it.box }.reduce(Box::union) },
    )
}
