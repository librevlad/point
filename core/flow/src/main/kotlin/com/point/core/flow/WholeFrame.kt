package com.point.core.flow

/**
 * Страницу на снимке не нашли, и человеку отдан весь кадр (#1333).
 *
 * Прежде такой кадр был помечен ровно так же, как настоящая выпрямленная страница: снаружи
 * «не нашлось» было неотличимо от успеха, и кривой снимок уезжал дальше как «скан» — а
 * находки с него выходят кашей (#1017, #1007). Пометка живёт на самом объекте, а не в строке
 * прогресса: строка гаснет, объект остаётся, и опереться на неё могут оба — человек глазами
 * и следующий шаг (#1041).
 *
 * Значение — слова человеку, как у [META_UNUSABLE_REASON]: их собирает [wholeFrameNote], одна
 * на оба пути скана — на снимок поодиночке и на набор снимков в PDF.
 */
const val META_WHOLE_FRAME = "page.whole-frame"

/** Один снимок, и страницы на нём не нашли (#1333). */
const val WHOLE_FRAME_INSTEAD_OF_PAGE = "Страницу целиком не нашёл — обработан весь снимок"

/**
 * Слова о кадрах, которые пошли целиком, потому что страницы на них не нашли (#1333).
 *
 * `null` — сказать нечего: страницу нашли везде. Одна и та же фраза достаётся снимку,
 * который человек сканирует поодиночке, и набору снимков, который уезжает в PDF: правило
 * «ненайденная страница за скан не выдаётся» одно, и звучать оно обязано одинаково.
 */
fun wholeFrameNote(wholeFrames: Int, pages: Int): String? = when {
    wholeFrames <= 0 -> null
    pages <= 1 -> WHOLE_FRAME_INSTEAD_OF_PAGE
    wholeFrames == 1 -> "Страницу целиком не нашёл на одном снимке из $pages — он обработан как есть"
    else -> "Страницу целиком не нашёл на $wholeFrames снимках из $pages — они обработаны как есть"
}
