package com.point.core.flow

/**
 * Слово, которое слой-источник написал для человека сам (#1225).
 *
 * Граница «своё / чужое» проходила по `it.message`, а по нему её не видно: одним и тем же
 * путём шли и собственные человеческие причины («текст объекта недоступен», «Файл не
 * открылся…»), и чужой текст исключения — «End-of-File, expected line at offset 25» от
 * разбора PDF. Закрыть все сообщения одной фразой значило потерять первые; пропускать всё —
 * показывать вторые.
 *
 * Поэтому слово объявляется там, где известно, что произошло, — тем же способом, каким
 * запечатан движок выреза (#992): слой бросает [OwnWords]. Всё прочее — чужой текст: он
 * остаётся на своём слое, а человеку достаётся общее слово срыва.
 */
class OwnWords(said: String) : IllegalStateException(said)

/** Сказать человеку своими словами и оборвать шаг. */
fun ownWords(said: String): Nothing = throw OwnWords(said)

/** Своё слово — если слой его объявил. Чужой текст сюда не проходит. */
fun ownWordsOf(failure: Throwable): String? =
    (failure as? OwnWords)?.message?.takeIf { it.isNotBlank() }
