package com.point.core.flow

import kotlin.coroutines.AbstractCoroutineContextElement
import kotlin.coroutines.CoroutineContext
import kotlin.coroutines.coroutineContext

/**
 * Кто попросил это действие — человек за этим устройством или другое устройство (#591).
 *
 * Почти всем реализациям знать это не нужно и не должно быть нужно: устройство есть свойство
 * исполнения, а не выбор человека. Но есть работа, у которой ответ зависит именно от этого, и
 * печать — её образец.
 *
 * Тап по «Напечатать» **здесь**: человек сидит перед экраном, и ему нужен обычный диалог печати —
 * принтер, формат, страницы, двусторонняя. Просьба **с телефона**: за компьютером никого нет, и
 * диалог там повиснет, а задание не уйдёт вовсе.
 *
 * Сделано элементом контекста корутины, тем же приёмом, что и канал стадий ([ActionProgress]): у
 * контракта действия десятки реализаций, и добавлять всем параметр ради нужды одной значило бы
 * переписать их все. Кто спрашивает — спрашивает; остальные не знают и правильно делают.
 */
class RequestOrigin(val here: Boolean) : AbstractCoroutineContextElement(Key) {
    companion object Key : CoroutineContext.Key<RequestOrigin>
}

/**
 * Человек ли сейчас перед этим устройством.
 *
 * Умолчание `true` — «считаем, что человек рядом»: вне действия (в тестах, в обогащении) спросить
 * некого, и осторожнее показать диалог, который человек закроет, чем молча сделать не то.
 */
suspend fun askedHere(): Boolean = coroutineContext[RequestOrigin]?.here ?: true
