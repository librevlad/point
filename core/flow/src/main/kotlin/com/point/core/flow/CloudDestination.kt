package com.point.core.flow

import com.point.core.model.CapabilityId

/**
 * Что уйдёт и что вернётся, если человек разрешит (#388, #560).
 *
 * Диалог согласия говорил одно и то же про все сетевые действия: «файл уйдёт на сервер
 * AI-провайдера». Для «Понять» это правда, а для «Дать ссылку» — нет: там файл уезжает на релей
 * Point и лежит по ссылке сутки. Спрашивать согласие, называя не того адресата, — это просить
 * доверия и тут же его тратить. Отсюда ветки: у каждого обещания свой текст.
 *
 * **Чего здесь нет и почему (#560).** Живой снимок с телефона владельца: «Снимок уйдёт на сервер
 * распознавания и вернётся текстом. Первым читает Mistral OCR (Франция, ЕС); не ответит он —
 * следующий по очереди. Кому вообще можно предлагать, вы задаёте в настройке…». Ответ владельца:
 * «мне не интересно, что Mistral во Франции и кто там вообще читает». Мы много обсуждали
 * приватность как происхождение и адресата — и это по инерции переехало в текст, который человек
 * читает в момент тапа. А у него там один вопрос: **уходит или нет** и что он получит взамен.
 *
 * Поэтому вопрос вмещается в одну мысль — *что уходит* и *что вернётся*, — а порядок цепочки,
 * страны и обещания провайдеров остаются знанием продукта о себе. Кого Point выбирает сам, он
 * называет **после** работы, в происхождении результата (`ExternalEye.where`), и в настройке
 * «Куда можно отправлять», куда человек приходит именно за этим выбором.
 *
 * Имя сервиса в тексте появляется ровно там, где человек **выбрал его сам** — [aiService], ключ
 * с экрана ключей. Оно приходит подстановкой, а не написано здесь буквой: имени сервиса,
 * выбранного Point, в этом файле нет ни одного, и это стережёт тест.
 */
fun cloudDestination(
    capabilityId: CapabilityId,
    /**
     * Имя сервиса, которому уедет объект по AI-ветке, — `null`, если назвать его нечем (#538).
     *
     * Точка входа только одна: `providerForBaseUrl(config.baseUrl)?.name`. Свой прокси в каталоге
     * не значится, и выдумывать ему имя нельзя — тогда остаётся честное умолчание.
     */
    aiService: String? = null,
): String = when (capabilityId.value) {
    "drop-link" ->
        "Файл уедет на сервер Point и сутки будет открыт любому, у кого есть ссылка. " +
            "Потом ссылка перестанет работать."

    // Идентификаторы — те, что реально объявлены у OcrCapability и CloudOcrCapability. Здесь
    // стояли «cloud-ocr»/«cloud-ocr-direct», которых в приложении нет ни одного: ветка не
    // срабатывала никогда, и человеку, тапнувшему «Распознать в облаке», показывали умолчание
    // про «сервер AI-провайдера». Тест не ловил, потому что сам передавал те же несуществующие
    // имена. Промах ровно того сорта, против которого весь этот файл: адресат назывался не тот.
    "ocr", "ocr-cloud" ->
        "Снимок уйдёт на сервер распознавания и вернётся текстом."

    // AI-ветка называет адресата поимённо, когда он известен (#538). «Сервер AI-провайдера» —
    // это не адресат, а класс адресатов: человеку, который минуту назад сам выбрал сервис и
    // вписал его ключ, Point отвечал так, будто не знает, куда отправляет. Знает: имя выводится
    // из адреса по каталогу. Спрашивать согласие ЗАНОВО при смене сервиса — отдельный вопрос,
    // здесь он не решается: меняется только то, КАК назван адресат.
    else -> if (aiService != null) {
        "Объект уйдёт на сервер $aiService и вернётся результатом."
    } else {
        "Объект уйдёт на сервер AI-провайдера и вернётся результатом."
    }
}

/**
 * Какое обещание даёт это действие (#114): показать модели — или выложить в открытый доступ.
 *
 * Признак — сама способность, а не флаг «сетевое»: «Дать ссылку» кладёт файл на сервер открытым,
 * и разрешение, данное когда-то ради «Понять», за это отвечать не может.
 */
fun cloudScopeOf(capabilityId: CapabilityId): CloudScope = when (capabilityId.value) {
    "drop-link" -> CloudScope.PUBLIC_LINK
    else -> CloudScope.MODELS
}

/** Заголовок вопроса: у публичной ссылки другое обещание — и звучать он обязан иначе. */
fun cloudAskTitle(scope: CloudScope): String = when (scope) {
    CloudScope.PUBLIC_LINK -> "Выложить файл по ссылке?"
    CloudScope.MODELS -> "Отправить в облако?"
}

/** Слово на кнопке согласия: человек соглашается с тем, что написано на ней, а не вообще. */
fun cloudAskConfirm(scope: CloudScope): String = when (scope) {
    CloudScope.PUBLIC_LINK -> "Выложить"
    CloudScope.MODELS -> "Разрешить"
}
