package com.point.core.flow

import com.point.core.model.CapabilityId

/**
 * Куда именно уйдёт объект, если человек разрешит (#388).
 *
 * Диалог согласия говорил одно и то же про все сетевые действия: «файл уйдёт на сервер
 * AI-провайдера». Для «Понять» это правда, а для «Дать ссылку» — нет: там файл уезжает на релей
 * Point и лежит по ссылке сутки. Спрашивать согласие, называя не того адресата, — это просить
 * доверия и тут же его тратить.
 *
 * Правило чистое и потому проверяется тестом: спросить у человека можно только то, что ему
 * сказали правдиво.
 */
fun cloudDestination(capabilityId: CapabilityId): String = when (capabilityId.value) {
    "drop-link" ->
        "Файл уедет на сервер Point и будет доступен по ссылке — любому, у кого она есть, " +
            "в течение суток. Потом ссылка перестанет работать сама."

    "cloud-ocr", "cloud-ocr-direct" ->
        "Снимок уйдёт на сервер распознавания и вернётся текстом. Ничего не отправляется " +
            "без вашего согласия."

    else ->
        "Объект уйдёт на сервер AI-провайдера и вернётся результатом. Ничего не отправляется " +
            "без вашего согласия."
}
