package com.point.core.flow

/**
 * Кадр, подготовленный к отправке модели (#828).
 *
 * Ужать снимок и закодировать его умеет каждое устройство по-своему: телефон — через
 * Bitmap, компьютер — своими средствами. Сама цепочка провайдеров об этом знать не должна:
 * она собирает запрос, а не работает с картинками.
 *
 * `null` — вложения не будет: файла нет, он пуст или слишком велик. Это не ошибка, а честный
 * ответ «отправляем без кадра».
 */
fun interface FrameForModel {

    fun of(path: String, mime: String): InlineFrame?

    /**
     * Отпустить всё, что помнилось (#1245).
     *
     * Готовый кадр — это многомегабайтная строка в памяти, и живёт она ровно столько же,
     * сколько копия объекта: копию отпускает `ObjectStore.clear()`, он же отпускает и кадр.
     * Готовилке без памяти забывать нечего — поэтому по умолчанию ничего не делает.
     */
    fun forget() = Unit

    companion object {

        /** Кадры не готовятся вовсе — запрос уходит текстом. Для тестов и для чистых сборок. */
        val NONE: FrameForModel = FrameForModel { _, _ -> null }
    }
}

/** Готовый кадр: содержимое в base64 и тип, которым его называют модели. */
class InlineFrame(val base64: String, val mime: String)

/**
 * Тот же кадр готовится один раз, а не на каждую попытку провайдера (#1245).
 *
 * Цепочка перебирает исполнителей одного за другим, и каждый строил кадр заново: с полными
 * списками моделей один неизменный снимок декодировался, ужимался и кодировался до полутора
 * десятков раз за один тап — и даже мгновенно отказавший сервис стоил полного кодирования,
 * потому что кадр готовится до обращения к сети. Готовилка — общий шов всех клиентов,
 * поэтому память живёт здесь, а не в каждом из них.
 *
 * Помнится последний готовый кадр: следующий объект вытесняет предыдущий, и в памяти никогда
 * не лежит больше одного снимка. Срок жизни — до `ObjectStore.clear()`: копия объекта и кадр,
 * сделанный из неё, отпускаются вместе.
 */
fun FrameForModel.oncePerPath(): FrameForModel = FramePreparedOncePerPath(this)

private class FramePreparedOncePerPath(private val prepare: FrameForModel) : FrameForModel {

    // Клиенты цепочки живут в одном обходе, но спросить могут и из разных потоков: ссылка
    // на готовое меняется целиком, поэтому половины чужой памяти никто не увидит.
    @Volatile private var last: Remembered? = null

    override fun of(path: String, mime: String): InlineFrame? {
        last?.let { if (it.path == path && it.mime == mime) return it.frame }

        // Помнится только удача (#1239). «Кадра не будет» приходит и тогда, когда попытка
        // сорвалась — ужатие снимка падает на нехватке памяти и молча становится `null`.
        // Запомнить такое значит для всей остальной цепочки и для всех следующих тапов по
        // тому же объекту решить, что картинки нет: запрос уйдёт без неё, а модель либо
        // ответит NO_IMAGE, либо сочинит чтение. Сорвавшаяся попытка приговором не бывает.
        val frame = prepare.of(path, mime) ?: return null
        last = Remembered(path, mime, frame)
        return frame
    }

    override fun forget() {
        last = null
    }

    private class Remembered(val path: String, val mime: String, val frame: InlineFrame)
}
