package com.point.core.flow

/**
 * Кадр, подготовленный к отправке модели (#828).
 *
 * Ужать снимок и закодировать его умеет каждое устройство по-своему: телефон — через
 * Bitmap, компьютер — своими средствами. Сама цепочка провайдеров об этом знать не должна:
 * она собирает запрос, а не работает с картинками.
 *
 * `null` — вложения не будет: файла нет, он пуст или слишком велик. Это не ошибка, а честный
 * ответ «отправляем без кадра».
 */
fun interface FrameForModel {

    fun of(path: String, mime: String): InlineFrame?

    companion object {

        /** Кадры не готовятся вовсе — запрос уходит текстом. Для тестов и для чистых сборок. */
        val NONE: FrameForModel = FrameForModel { _, _ -> null }
    }
}

/** Готовый кадр: содержимое в base64 и тип, которым его называют модели. */
class InlineFrame(val base64: String, val mime: String)
