/** Что написано, пока человек в браузере: сверить код — его работа, и она названа. */
fun signInWaitingLine(code: String): String = "Подтвердите вход в браузере · код $code"

/** Заголовок круга. Не «настройки» и не новый раздел — тот же экран, что был экраном компьютера. */
const val MY_DEVICES_TITLE = "Мои устройства"

/** Вид устройства словом. */
fun deviceKindLabel(kind: DeviceKind): String = when (kind) {
    DeviceKind.PHONE -> "Телефон"
    DeviceKind.PC -> "Компьютер"
}

/**
 * «На связи» / «был вчера» — время последнего контакта человеческими словами.
 *
 * Пороги те же, что у [linkLabel] для живой связи: устройство, отозвавшееся минуту назад, — «на
 * связи». Дальше счёт идёт крупно (минуты → часы → «вчера» → дни): точность до секунды здесь никому
 * не нужна, а «последний раз 47 минут назад» читается дольше, чем «меньше часа назад».
 */
fun lastSeenLabel(lastSeenMillis: Long?, now: Long): String {
    if (lastSeenMillis == null) return "ещё ни разу не выходило на связь"
    val ago = now - lastSeenMillis
    return when {
        ago < 0 -> "на связи"
        ago < LIVE_MS -> "на связи"
        ago < 60 * 60_000L -> "меньше часа назад"
        ago < 24 * 60 * 60_000L -> "сегодня"
        ago < 48 * 60 * 60_000L -> "вчера"
        else -> "${ago / (24 * 60 * 60_000L)} дн. назад"
    }
}

/** Граница «на связи»: две минуты молчания ещё не молчание. */
private const val LIVE_MS = 2 * 60_000L

/**
 * Отказ по коду ответа сервера — что случилось и что делать.
 *
 * Чистая функция, поэтому судится тестом: воспроизвести пальцами 401 или кончившийся вход нельзя.
 * Разница между «сервер не отвечает» и «сервер отказал» — это разница между «подождите» и
 * «войдите заново», и слепить их в одно «ошибка» значит отправить человека чинить не то (#465).
 */
fun accountRefusal(status: Int?): SignIn.Refused = when (status) {
    null -> SignIn.Refused(
        what = "До сервера Point не дозвониться",
        fix = "Проверьте интернет и попробуйте ещё раз — ничего не потеряно.",
    )
    401, 403 -> SignIn.Refused(
        what = "Вход не подтверждён",
        fix = "Откройте страницу входа заново и завершите вход в браузере.",
    )
    404, 410 -> SignIn.Refused(
        what = "Вход просрочен",
        fix = "Страница входа живёт пять минут. Нажмите «Войти через Google» ещё раз.",
    )
    429 -> SignIn.Refused(
        what = "Сервер Point просит подождать",
        fix = "Слишком много попыток подряд. Повторите через минуту.",
    )
    else -> SignIn.Refused(
        what = "Сервер Point ответил отказом ($status)",
        fix = "Попробуйте ещё раз; если повторится — сервер сейчас не в порядке.",
    )
}

/**
 * Что сказать, когда пропуск устройства перестал действовать.
 *
 * Отключённое устройство получает `401` на следующем же запросе, стирает своё состояние и
 * показывает вход. Молчаливый выход был бы худшим из вариантов: человек решил бы, что Point сломан.
 */
val ACCOUNT_REVOKED: SignIn.Refused = SignIn.Refused(
    what = "Это устройство отключили от аккаунта",
    fix = "Войдите снова, чтобы вернуть его в круг.",
)
