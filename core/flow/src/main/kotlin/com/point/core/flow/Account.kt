package com.point.core.flow

/**
 * Аккаунт Point (#472, #473) — «человек → его устройства» вместо пары «этот телефон ↔ этот ПК».
 *
 * Модель и слова живут здесь, в чистом Kotlin, потому что вход одинаков на телефоне и на
 * компьютере: одна механика, две витрины. Всё, что можно посудить тестом без сети и без экрана,
 * посужено здесь — включая тексты, которые человек читает.
 *
 * **Устройство не держит учётных данных Google вовсе.** Ни `client_secret`, ни пароля, ни токена
 * Google на устройстве не появляется: браузер разговаривает с нашим сервером, сервер — с Google, а
 * устройству возвращается только собственный пропуск. Отсюда и форма: [PointAccount] — это
 * `device_id` плюс непрозрачный `device_token`, и ничего сверх.
 */

/** Телефон или компьютер — вид устройства в круге. */
enum class DeviceKind { PHONE, PC }

/**
 * Пропуск устройства: то, что остаётся на устройстве после входа.
 *
 * [deviceToken] — 256 бит случайности, выданные сервером; в базе сервера лежит только его SHA-256.
 * Отзывается поимённо («потерял телефон»), поэтому и не JWT: непрозрачный токен умирает в ту же
 * секунду, как человек нажал «Отключить».
 */
data class PointAccount(
    val deviceId: String,
    val deviceToken: String,
    val email: String,
    val deviceName: String,
    val kind: DeviceKind,
)

/**
 * Устройство круга — как его видит человек на «Моих устройствах».
 *
 * [lastSeenMillis] `null` значит «ни разу не выходило на связь», и это не то же, что «давно»:
 * первое — про новичка, второе — про молчание. [self] — «это устройство», чтобы человек не отключил
 * то, в руках у которого держит Point, не понимая, что делает.
 */
data class CircleDevice(
    val id: String,
    val kind: DeviceKind,
    val name: String,
    val lastSeenMillis: Long? = null,
    val self: Boolean = false,
)

/**
 * Что сейчас происходит со входом — состояние единственного нового экрана.
 *
 * Четыре состояния названы явно, а не собраны из флагов: «ждём браузера» отличается от «не вошёл»
 * не спиннером, а тем, что человеку есть что сверить (код) и есть чем выйти («Отменить»).
 */
sealed interface SignIn {

    /** Ещё не входили — экран с одной кнопкой. */
    data object SignedOut : SignIn

    /**
     * Человек ушёл в браузер. [code] показывается и здесь, и на странице подтверждения: совпали —
     * подтверждается свой вход, а не чужой.
     */
    data class Waiting(val loginId: String, val code: String, val url: String) : SignIn

    /** Вошли. Дальше экран уступает место объекту. */
    data class SignedIn(val account: PointAccount) : SignIn

    /**
     * Не вышло. [what] — что случилось, [fix] — что с этим делать: «ошибка» без продолжения
     * оставляет человека ровно там, откуда он пришёл (то же правило, что у отказа ключа, #465).
     */
    data class Refused(val what: String, val fix: String) : SignIn
}

/**
 * Начало входа: что сервер ответил на «я хочу войти».
 *
 * [claimToken] — второй пропуск, и он существует не для красоты. `loginId` лежит в адресе страницы,
 * которую человек открывает **в браузере**: он есть в истории, в расширениях, в чужих глазах через
 * плечо. Забирать по нему пропуск ко всем объектам аккаунта было бы дырой, поэтому забор идёт с
 * токеном, который знает только устройство (решение сервера, #471).
 */
data class LoginStart(
    val loginId: String,
    val claimToken: String,
    val code: String,
    val url: String,
)

/**
 * Чем ответил сервер на «покажи мой круг».
 *
 * Три ответа, а не «список или ничего»: «не дозвонились» и «это устройство отключили» чинятся
 * разным — первое подождать, второе войти заново. Пока они были одним `null`, отозванный телефон
 * молча показывал «сервер не отвечает» и оставался сломанным до следующей отправки.
 */
sealed interface CircleAnswer {
    data class Circle(val devices: List<CircleDevice>) : CircleAnswer

    /** Не дозвонились — прошлое знание остаётся в силе. */
    data object Unreachable : CircleAnswer

    /** Пропуск больше не действует: устройство отключили из круга. */
    data object Revoked : CircleAnswer
}

/** Чем кончился один опрос сервера, пока человек в браузере. */
sealed interface LoginPoll {
    /** Ещё не подтвердил — ждём дальше. */
    data object Pending : LoginPoll
    data class Ready(val account: PointAccount) : LoginPoll
    data class Refused(val what: String, val fix: String) : LoginPoll
}

