package com.point.core.flow

/**
 * Проверка ключа живым запросом (#465) — «работает» говорит сам сервис, а не мы.
 *
 * До этого «Сохранить» записывал ключ на диск и молчал: узнать, подошёл он или нет, человек мог
 * только следующим действием, которое к тому времени успевало провалиться. Между «вставил» и
 * «понял, что настроил правильно» лежал целый флоу, и в этом промежутке ошибиться можно было
 * незаметно — лишний пробел, ключ от другого сервиса, кончившаяся квота.
 *
 * Проверка — **только по явному тапу**: сеть в Point не ходит сама, и экран ключа не исключение.
 * Уходит в сервис одно короткое слово, придуманное нами ([KEY_PROBE_PROMPT]); объект человека при
 * проверке не отправляется никуда.
 */
interface AiKeyCheck {
    /** Постучаться в сервис с этим ключом. Не бросает: неудача — это тоже ответ ([KeyProbe.error]). */
    suspend fun check(config: UserAiConfig): KeyProbe
}

/**
 * Что вернула попытка достучаться до сервиса — сырьё приговора.
 *
 * [status] `null` значит «до ответа не дошли вовсе»: сеть, DNS, таймаут. Различие несущее — «нет
 * связи» и «сервис отказал» чинятся по-разному, и слепить их в одно «ошибка» значит отправить
 * человека чинить не то.
 *
 * Ключа здесь быть не может: всё, что приходит от сервиса, проходит через [withoutKey] на границе,
 * до того как попасть сюда, — приговор показывают на экране, и секрету там не место.
 */
data class KeyProbe(
    val status: Int? = null,
    /** Что ответила модель (при успехе) — им и доказывается «работает». */
    val reply: String? = null,
    /** Текст отказа сервиса или транспортной неудачи — уже без ключа. */
    val error: String? = null,
)

/** Приговор проверки — словами человека, а не кодом ответа. */
sealed interface KeyVerdict {
    /** Работает: сервис принял ключ и модель ответила. [reply] — её собственные слова. */
    data class Works(val reply: String) : KeyVerdict

    /** Не получилось: [what] — что именно не так, [fix] — что с этим делать. */
    data class Refused(val what: String, val fix: String) : KeyVerdict
}

/** Слово, которое уходит в сервис на проверке. Короткое и наше: объект человека тут ни при чём. */
const val KEY_PROBE_PROMPT: String = "Ответь одним словом: готово"

/**
 * Приговор по ответу сервиса — чистая функция, поэтому судится тестом, а не руками с телефоном.
 *
 * Каждый исход назван тем, что человек может с ним сделать. «Ошибка» без продолжения — худшее, что
 * можно сказать тому, кто пять минут назад завёл аккаунт ради этого ключа: она не отличает
 * опечатку от кончившейся квоты, а чинятся они по-разному.
 */
fun keyVerdict(probe: KeyProbe): KeyVerdict {
    val status = probe.status
        ?: return KeyVerdict.Refused(
            what = "Не дозвонились до сервиса",
            fix = "Похоже, нет связи — или адрес сервиса набран с опечаткой. " +
                "Проверьте интернет и нажмите «Проверить и включить» ещё раз.",
        )
    return when {
        status in 200..299 -> {
            val reply = probe.reply?.trim().orEmpty()
            if (reply.isEmpty()) {
                KeyVerdict.Refused(
                    what = "Ключ приняли, но ответа не прислали",
                    fix = "Обычно дело в имени модели. Выберите сервис в списке выше — имя подставится само.",
                )
            } else {
                KeyVerdict.Works(reply.take(PROOF_CHARS))
            }
        }
        status == 401 || status == 403 -> KeyVerdict.Refused(
            what = "Ключ не подошёл",
            fix = "Скопируйте ключ целиком, без пробелов по краям, и проверьте, что он от того сервиса, " +
                "который выбран выше.",
        )
        status == 402 -> KeyVerdict.Refused(
            what = "Сервис просит оплату",
            fix = "У этого ключа нет бесплатного доступа. Возьмите ключ у другого сервиса из списка выше — " +
                "там отмечено, где бесплатный уровень есть.",
        )
        status == 404 -> KeyVerdict.Refused(
            what = "Сервис не знает такой модели",
            fix = "Выберите сервис в списке выше — адрес и имя модели подставятся сами.",
        )
        // Про «второй ключ, Point переключится на него сам» здесь было написано зря (#535). Слот
        // ключа ОДИН — [UserAiConfig] хранит один ключ, один адрес, одну модель, — и никакой
        // очереди провайдеров за ним нет. Цена вранья тут выше обычной: человек упёрся в квоту,
        // то есть ему нужно СЕЙЧАС, и совет отправлял его заводить второй аккаунт ради
        // переключения, которого не случится. Осталось то, что правда: подождать — или вписать
        // сюда ключ другого сервиса вместо этого.
        status == 429 -> KeyVerdict.Refused(
            what = "Ключ верный, но квота на сейчас исчерпана",
            fix = "Бесплатный лимит кончился. Подождите несколько минут и нажмите «Проверить и " +
                "включить» ещё раз — или возьмите ключ у другого сервиса из списка выше и " +
                "впишите его сюда вместо этого.",
        )
        status == 400 -> KeyVerdict.Refused(
            what = "Сервис не понял запрос",
            fix = "Чаще всего это имя модели. Выберите сервис в списке выше, чтобы оно подставилось само.",
        )
        status in 500..599 -> KeyVerdict.Refused(
            what = "Сервис сейчас не отвечает",
            fix = "Это не про ваш ключ — у сервиса неполадки. Попробуйте через несколько минут.",
        )
        else -> KeyVerdict.Refused(
            what = "Сервис отказал (код $status)",
            fix = detailOrHint(probe.error),
        )
    }
}

/** Незнакомому коду ответа помогает только то, что сервис сказал сам, — но коротко и без ключа. */
private fun detailOrHint(error: String?): String {
    val said = error?.trim()?.replace(Regex("\\s+"), " ").orEmpty()
    return if (said.isEmpty()) {
        "Что именно не так, сервис не сказал. Попробуйте другой сервис из списка выше."
    } else {
        "Сервис ответил: ${said.take(DETAIL_CHARS)}"
    }
}

/**
 * Убрать ключ из чего угодно, что пришло от сервиса и может попасть на экран или в лог.
 *
 * Некоторые сервисы возвращают запрос обратно в тексте отказа, а некоторые адреса носят ключ прямо
 * в строке запроса. Один такой ответ, показанный карточкой отказа, — и секрет лежит на экране (а
 * при отправке отчёта о падении уезжает вместе с ним). Дешевле вычеркнуть его на границе, чем
 * доверять каждому сервису.
 */
fun withoutKey(text: String, key: String): String {
    val secret = key.trim()
    if (secret.length < MIN_SECRET) return text
    return text.replace(secret, "…")
}

/**
 * Похоже ли содержимое буфера на ключ — чтобы «Вставить из буфера» не подсовывало в поле
 * скопированный абзац текста.
 *
 * Судит грубо и намеренно: ключи у сервисов разные, и строгая маска отвергала бы верные. Всё, на
 * чём здесь стоит настаивать, — это одно слово подходящей длины из печатных знаков.
 */
fun looksLikeApiKey(text: String?): Boolean {
    val candidate = text?.trim().orEmpty()
    if (candidate.length !in MIN_KEY..MAX_KEY) return false
    return candidate.none { it.isWhitespace() } && candidate.all { it.code in 0x21..0x7E }
}

/**
 * Ключ, каким его можно показать: начало и хвост, середина закрыта (#447).
 *
 * Владелец, открыв настройки с уже заданным ключом: «задан он или нет — непонятно». И это была
 * правда экрана: поле закрыто точками, и пустое от заполненного отличалось их числом. Приговор
 * живой проверки отвечает на тот же вопрос, но только после тапа, — а человек, зашедший
 * посмотреть, тапать не собирался.
 *
 * Хвост — то, чем человек отличает свой ключ OpenRouter от своего же ключа Groq, не открывая
 * менеджер паролей. Короткий ключ показывается точками: у него нечего показать, не открыв половину.
 */
fun maskedKey(apiKey: String): String {
    val key = apiKey.trim()
    if (key.isEmpty()) return ""
    if (key.length < MIN_MASKABLE) return "•".repeat(key.length.coerceAtMost(MASK_DOTS))
    return "${key.take(MASK_EDGE)}…${key.takeLast(MASK_EDGE)}"
}

/**
 * Что сказать про ключ, лежащий в поле, — одной строкой и без обещаний.
 *
 * Три состояния, а не два: ключа нет вовсе; ключ лежит на устройстве; ключ набран, но ещё не
 * сохранён. Третье раньше не различалось никак — человек, вставивший ключ и закрывший экран, терял
 * его молча.
 *
 * Про «работает» здесь не сказано ни слова: это знает только сервис ([keyVerdict]), и подменять его
 * ответ видом ключа значило бы ровно то враньё, ради которого заводилась живая проверка.
 */
fun keySetLabel(apiKey: String, saved: Boolean): String {
    val key = apiKey.trim()
    return when {
        key.isEmpty() -> "Ключа пока нет — без него AI-действия молчат."
        saved -> "Ключ на устройстве: ${maskedKey(key)}"
        else -> "Ключ набран, но ещё не сохранён: ${maskedKey(key)}"
    }
}

/** Короче этого показывать нечего: начало и хвост сомкнулись бы, открыв ключ целиком. */
private const val MIN_MASKABLE = 12
private const val MASK_EDGE = 4
private const val MASK_DOTS = 8

/** Сколько слов модели показать как доказательство. Ответ на проверку короткий по построению. */
private const val PROOF_CHARS = 80

/** Сколько чужого текста показать в отказе — довод, а не дамп. */
private const val DETAIL_CHARS = 160

/** Короче этого вычёркивать опасно: вырезали бы случайные совпадения из осмысленного текста. */
private const val MIN_SECRET = 8

private const val MIN_KEY = 16
private const val MAX_KEY = 400
