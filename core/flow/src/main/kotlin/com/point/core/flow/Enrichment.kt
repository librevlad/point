package com.point.core.flow

import com.point.core.model.CapabilityId
import com.point.core.model.Feature
import com.point.core.model.PointObject
import com.point.core.model.Relation
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.emptyFlow

/**
 * Порт цикла Progressive Understanding (RFC §11).
 *
 * Механизм под ним — обычный: Capability → Resolver → Realizer. Отдельного контракта
 * исследования не существует (ADR-0001 §11).
 */
interface Enrichment {

    /**
     * [answeredElsewhere] — вопросы этого объекта, на которые ответ пришёл мимо прохода
     * (#1242).
     *
     * «Прочитать сильнее» закрывает вопрос чтения за секунды, а начатое до него офлайн-чтение
     * того же снимка греет телефон ещё минуты и кладёт поверх сильного своё слабое. Пришедший
     * сюда вопрос прерывает **своё** исследование и только его: соседние вопросы прохода идут
     * дальше, и их поздний результат остаётся знанием объекта.
     */
    fun enrich(obj: PointObject, answeredElsewhere: Flow<CapabilityId> = emptyFlow()): Flow<EnrichmentUpdate>
}

data class EnrichmentUpdate(
    val features: Set<Feature>,
    val metadata: Map<String, String>,
    val running: List<String>,
    val objects: List<PointObject> = emptyList(),
    val relations: List<Relation> = emptyList(),

    /**
     * Состояние операции, а не знания: шаги, которые сорвались (ADR-0001 §9, §18).
     * Провал не переводит знание в `NOT_FOUND` и не стирает найденное раньше.
     *
     * Не только исследования и не только выбранное человеком: сюда же попадает работа,
     * которую Point завёл сам, — например сорвавшийся показ объекта (#1271). Имя такому
     * шагу нужно затем же, зачем всякой неудаче операции: чтобы упрёк не слился с чужим, —
     * а не затем, чтобы объявить его способностью.
     */
    val failed: List<FailedInvestigation> = emptyList(),

    /**
     * Тоже состояние операции: шаг не закончился, а ждёт человека (ADR-0001 §18).
     * Ожидание не является исходом и знанием не становится.
     */
    val awaiting: List<AwaitingInvestigation> = emptyList(),
)

data class FailedInvestigation(
    val id: CapabilityId,
    val label: String?,
    val reason: String,
)

data class AwaitingInvestigation(
    val id: CapabilityId,
    val label: String?,
    val prompt: String,

    val needsImage: Boolean = false,
)

const val META_OCR_TEXT_REF = "ocr.text.ref"

/**
 * Где в прочитанном тексте документа начинается каждая страница (#1014, решение владельца
 * 19.08.2026): пары «номер страницы:смещение» через запятую — `1:0,2:154,5:901`.
 *
 * «Прочитать документ» склеивает страницы в один текст пустой строкой, и граница страницы в
 * нём терялась: «Найти в документе» могло сказать «нашлось три места», но не «где». Сам текст
 * остаётся прежним — его читают разговор, перевод и «В Word», — а границы лежат рядом,
 * знанием о том же прочтении.
 *
 * Номер — настоящий номер страницы в документе, а не счёт прочитанных: страницы, на которых
 * ничего не прочиталось или чтение сорвалось, здесь просто нет.
 *
 * Ключ — пометка при прочтении (`ocr.text.ref.…`), а не отдельное знание: текст ушёл
 * ([withoutKnowledge]) — уходят и его границы, перечитали — границы приходят свежими
 * ([REFRESHABLE_KNOWLEDGE]), а не спорят с прежними через «или». В дорогу на другое
 * устройство они едут вместе с текстом и указывают в него же.
 */
const val META_OCR_TEXT_PAGES = "$META_OCR_TEXT_REF.pages"

/**
 * На каком листе книги найден период (#1417): признак `HAS_PERIOD` — про книгу, а продлевать надо
 * тот лист, где даты подряд и стоят. Пусто — книга об именах листов не рассказала.
 */
const val META_PERIOD_SHEET = "period.sheet"

/**
 * Прочитанный текст **значением**, а не ссылкой на файл устройства (#811).
 *
 * `ocr.text.ref` указывает на scratch-файл того телефона, где читали, и при переносе на
 * компьютер ведёт в никуда: снимок приезжал «непрочитанным», и человеку предлагали
 * распознать его заново. Знание, живущее ссылкой на локальный файл, не переносимо по
 * построению — поэтому на ту сторону едет само содержимое.
 */
const val META_READ_TEXT = "read.text"

/**
 * Кем объект был там, откуда приехал (ADR-0001 §20).
 *
 * «На той стороне это тот же объект, а не новый». Перенос заводил новую вещь с новым
 * именем в списке, и вернувшийся с компьютера объект вставал рядом со своим исходником
 * как посторонний. Идентичность едет вместе с ним и знанием об объекте не является:
 * это адрес узла, а не факт о вещи.
 */
const val META_ORIGIN_ID = "origin.id"

/** Длиннее в дорогу не берём: это уже документ, а не знание о нём. */
const val READ_TEXT_TRAVEL_LIMIT = 100_000

/**
 * Сколько знаков читать в дорогу: на один больше, чем едет (#1014).
 *
 * Читавшие ровно по пределу не могли отличить текст длиной в предел от обрезанного — и
 * обрезок уезжал на ту сторону без единой пометки. По лишнему знаку [knowledgePackedForTravel]
 * видит, что текст длиннее дороги, и называет обрезок обрезком ([META_OCR_TEXT_CUT]).
 */
const val READ_TEXT_TRAVEL_READ = READ_TEXT_TRAVEL_LIMIT + 1

/**
 * Прочитанный текст доехал сюда не целиком: значение — сколько знаков доехало (#1014).
 *
 * В дорогу текст обрезается ([READ_TEXT_TRAVEL_LIMIT]), и на той стороне обрезок ложился
 * файлом как текст документа — ничем не помеченный. «Найти в документе» искало по нему и
 * про слово со страницы 45 шестидесятистраничного договора отвечало «Ничего не нашлось»:
 * ответ о документе, большую часть которого поиск не видел. Потеря знания при переносе —
 * дефект; раз весь текст в дорогу не берётся, та сторона обязана хотя бы знать, что у неё
 * только начало.
 *
 * Ключ — пометка при прочтении, как и границы страниц ([META_OCR_TEXT_PAGES]): уходит вместе с
 * текстом ([withoutKnowledge]) и едет с ним дальше. Значение — длина обрезка, а не «да»:
 * пометка говорит только о том тексте, с которым приехала, и текст другой длины, легший
 * потом под той же ссылкой, ею не оговаривается.
 */
const val META_OCR_TEXT_CUT = "$META_OCR_TEXT_REF.cut"

/**
 * Какие страницы документа просмотрены до конца и сколько их в документе всего — `1-100,102/110`
 * (карточка «Не отвечать «Ничего не нашлось» по скану, прочитанному не целиком», 28.11.2026).
 *
 * Скан на 110 страниц телефон читал сотню страниц и честно говорил «100 из 110», а «Найти в
 * документе» на слово со 107-й отвечало «Ничего не нашлось» — ответ обо всём документе, хвост
 * которого никто не видел. Сколько прочитано, знало только сообщение человеку, а знание
 * документа — нет; и дочитать хвост было нечем: дверь чтения закрывалась, едва у документа
 * появлялся текст.
 *
 * Просмотренной считается страница, которую читатель довёл до ответа: с текстом или пустая —
 * пустой лист тоже прочитан, и «2 из 3» о скане с чистой страницей было неправдой. Сорвавшаяся
 * и не нарисованная страницы не просмотрены (`not investigated` ≠ `not found`).
 *
 * Ключ — пометка при прочтении, как границы страниц ([META_OCR_TEXT_PAGES]): текст ушёл
 * ([withoutKnowledge]) — уходит и счёт, перечитали — приходит свежим ([REFRESHABLE_KNOWLEDGE]),
 * в дорогу едет вместе с текстом. У документа, на прочитанных страницах которого текста пока
 * нет, ключ лежит и без самого текста: пустые страницы тоже просмотрены, и второй раз читать их
 * незачем.
 */
const val META_OCR_TEXT_COVERAGE = "$META_OCR_TEXT_REF.coverage"

/** Ссылка, по которой лежит прочитанный текст этого устройства, — её и надо прочитать в дорогу. */
fun textRefForTravel(meta: Map<String, String>): String? =
    meta[META_OCR_TEXT_REF]?.takeIf { it.isNotBlank() }

/**
 * Файл с текстом, который человек должен видеть у этого объекта, — или `null` (#995).
 *
 * Текст — знание документа, а не второй объект рядом с ним, и показывать его надо у самого
 * документа. Компьютер показывал текст только у объекта вида «текст» и только из его
 * собственного файла: человек нажимал «Извлечь текст», слышал «текст у самого документа» —
 * и не видел на экране ни строчки. Правило одно на обе поверхности: сначала прочитанное,
 * потом собственное содержимое там, где оно и есть текст.
 */
fun shownTextRef(obj: PointObject): String? =
    textRefForTravel(obj.metadata)
        ?: obj.uri.value.takeIf { obj.state.kind == com.point.core.model.ObjectKind.TEXT && it.isNotBlank() }

/**
 * Знание собирается в дорогу (#811, #995).
 *
 * Ссылка на прочитанный текст — путь в scratch этого устройства, и на той стороне она ведёт
 * в никуда: объект приезжал «непрочитанным», и там первым делом предлагали прочитать его
 * заново. Поэтому едет само содержимое, а ссылка не едет вовсе — даже когда прочитать файл
 * не вышло: мёртвый путь только притворяется знанием. Не едут тогда и пометки при нём
 * ([withoutKnowledge], #1242): «здесь прочитано сильнее» без самого прочтения — ложная
 * подпись, и на той стороне она отправляет в «или» уже второе обычное перечитывание, а снять
 * её нечем. Текст доехал — пометки едут с ним: прочтение было сильным на самом деле.
 *
 * [text] — то, что лежит по ссылке, прочитанное с запасом в один знак ([READ_TEXT_TRAVEL_READ]);
 * `null`, если прочитать не удалось.
 *
 * Длиннее дороги — едет начало, и оно названо обрезком ([META_OCR_TEXT_CUT], #1014): иначе
 * та сторона принимала начало за весь текст документа и отвечала о документе по нему.
 */
fun knowledgePackedForTravel(meta: Map<String, String>, text: String?): Map<String, String> {
    if (textRefForTravel(meta) == null) return meta
    val carried = text?.takeIf { it.isNotBlank() }
        ?: return withoutKnowledge(meta, setOf(META_OCR_TEXT_REF))
    val travelling = carried.take(READ_TEXT_TRAVEL_LIMIT)
    val packed = meta - META_OCR_TEXT_REF + (META_READ_TEXT to travelling)
    if (travelling.length == carried.length) return packed
    return packed + (META_OCR_TEXT_CUT to travelling.length.toString())
}

/** Текст, приехавший значением: его надо положить файлом этого устройства (#811). */
fun textArrivedFromTravel(meta: Map<String, String>): String? =
    meta[META_READ_TEXT]?.takeIf { it.isNotBlank() }

/**
 * Знание приехало и снова становится знанием этой стороны (#811, #995).
 *
 * [ref] — куда приехавший текст лёг здесь, или `null`, если положить не вышло. Признак
 * «текст есть» ставится тут, а не едет отдельным полем протокола: он следует из того, что
 * текст лёг. Без этого перенос терял понятое — та сторона звала делать уже сделанное.
 *
 * Текст не лёг — знания о прочтении здесь нет, и пометок при нём тоже (#1242): приехавшая
 * «здесь прочитано сильнее» осталась бы без всякого текста и заперла бы перечитывание.
 */
fun knowledgeArrivedFromTravel(meta: Map<String, String>, ref: String?): com.point.core.model.Findings {
    if (textArrivedFromTravel(meta) == null) return com.point.core.model.Findings(metadata = meta)
    val kept = ref?.takeIf { it.isNotBlank() }
        ?: return com.point.core.model.Findings(
            metadata = withoutKnowledge(meta, setOf(META_READ_TEXT, META_OCR_TEXT_REF)),
        )
    return com.point.core.model.Findings(
        features = setOf(Feature.HAS_TEXT),
        metadata = meta - META_READ_TEXT + (META_OCR_TEXT_REF to kept),
    )
}

/**
 * Полученное с другого устройства знание становится знанием этого — одним правилом (#1097).
 *
 * Текст приходит значением, и здесь ему нужен файл: `knowledgeArrivedFromTravel` ставит
 * признак «текст есть» только вместе со ссылкой на него. Мест приёма несколько, и каждое
 * писало эту пару шагов себе; место, которое их не написало (`landNeighbourOutcome` —
 * результат работы, не уложившейся в бюджет ответа), оставляло текст полем протокола: файла
 * с ним не появлялось, признака тоже, а состояние вопроса рядом приходило как «найдено» —
 * закрытый вопрос без единой строки текста у человека.
 *
 * [store] — куда положить текст здесь. Не получилось — знание не принято, и признак не
 * ставится: ссылка, которая никуда не ведёт, знанием не является.
 */
suspend fun knowledgeLandedFromTravel(
    meta: Map<String, String>,
    store: ObjectStore?,
): com.point.core.model.Findings {
    val arrived = textArrivedFromTravel(meta) ?: return com.point.core.model.Findings(metadata = meta)
    val kept = store?.let { place ->
        runCatching {
            place.newScratchFile("txt").also { java.io.File(it.value).writeText(arrived) }.value
        }.getOrNull()
    }
    return knowledgeArrivedFromTravel(meta, kept)
}

/**
 * Признак «текст документа прочитан» выводится из своей улики, а не помнится отдельно (#995).
 *
 * Улика знания — файл, где этот текст лежит (`ocr.text.ref`). Помнились они врозь, и врозь
 * же расходились в обе стороны:
 *
 * - ссылка переживает перезапуск (она метаданные и ложится в журнал), а признак `HAS_TEXT` —
 *   свойство состояния и не переживает: у уже прочитанного документа дверь «Извлечь текст»
 *   рисовалась заново (DSK-040), ради чего `accepts` на признак и завязали;
 * - файл лежит в папке самого человека, и он вправе его убрать или перенести — тогда
 *   признак оставался, дверь не рисовалась, а показывать было нечего.
 *
 * Улика на месте — знание есть; улики нет — знания нет, и вопрос снова **не исследован**, а
 * не «исследован, не найдено» (Конституция: `not investigated` ≠ `not found`). Поэтому
 * мёртвая ссылка уходит вместе с признаком — и вместе с пометками при ней ([withoutKnowledge],
 * #1242): «прочитано сильнее» без самого прочтения отправляет в «или» следующее обычное
 * перечитывание, и текст документа перестаёт обновляться вовсе.
 *
 * [textAlive] — есть ли ещё файл по ссылке; спрашивается у той стороны, у которой свой диск.
 */
fun knowledgeOfReadText(obj: PointObject, textAlive: (String) -> Boolean): PointObject {
    val ref = textRefForTravel(obj.metadata) ?: return obj
    if (textAlive(ref)) return obj.copy(state = obj.state.with(Feature.HAS_TEXT))
    return obj.copy(
        state = obj.state.copy(features = obj.state.features - Feature.HAS_TEXT),
        metadata = withoutKnowledge(obj.metadata, setOf(META_OCR_TEXT_REF)),
    )
}

