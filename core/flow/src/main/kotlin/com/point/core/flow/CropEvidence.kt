package com.point.core.flow

/**
 * Улика к спорному фрагменту документа (#267): адрес куска **исходного кадра**, который человек
 * сверяет глазами, не открывая исходник.
 *
 * Подсветка (первая половина #267) честно говорит «сюда смотри», но не говорит, **на что** —
 * чтобы проверить, надо выйти из Word, найти фотографию и глазами отыскать ту самую строку.
 * На продовольственной ведомости владельца (фото 4000×3000, ~35 строк × 8 колонок) живой прогон
 * пометил 387 ячеек из ~430: маршрут «выйди и найди» повторяется сотни раз и не проходится.
 * Кроп кладёт пиксели рядом с текстом — и сверка становится взглядом, а не походом.
 *
 * @param imagePath сырой файл, из которого резать: кроп берётся из исходных пикселей, а не из
 *   уменьшенной копии, которую читал движок.
 * @param region место в координатах **сырого** кадра — атомы слоя уже приведены к нему
 *   ([FrameTransform.toRaw]), поэтому преобразовывать здесь нечего.
 * @param uprightDegrees на сколько довернуть вырезанный кусок по часовой стрелке, чтобы человек
 *   прочёл его как на экране: телефон хранит поворот в EXIF и держит пиксели боком, а координаты
 *   живут в сыром кадре. Ноль — файл и так стоит ровно.
 * @param purpose для чего вырезан кусок — от этого и только от этого зависит его размер
 *   ([CropPurpose]).
 */
data class CropEvidence(
    val imagePath: String,
    val region: Box,
    val uprightDegrees: Int = 0,
    val purpose: CropPurpose = CropPurpose.GLANCE,
)

/**
 * Для чего вырезан кусок кадра. Резак один, а читателей у куска два, и размер им нужен
 * **противоположный** — поэтому назначение едет вместе с адресом (#273).
 *
 * У куска, который смотрит человек, размер ограничен сверху: полоса строки ведомости — почти вся
 * ширина кадра, и в колонку документа она всё равно не влезет, а вес файла вырастет на каждую из
 * двенадцати улик. У куска, который **читает модель**, всё наоборот: он и есть весь её вход, и
 * каждый выброшенный пиксель — выброшенная буква.
 *
 * Разницу эту стоило назвать раньше: перечит спорной ячейки (#346) звал тот же резак, что улика в
 * Word (#267), и получал её размер — тот, что выбран для картинки внутри документа.
 */
enum class CropPurpose {
    /** Картинка рядом с текстом: человек сверяет её взглядом. Ужимается, не увеличивается. */
    GLANCE,

    /** Вход модели: кусок читают, а не разглядывают. Не ужимается; мелкий — увеличивается. */
    READING,
}

/**
 * Во сколько раз увеличить вырезанный кусок перед тем, как отдать его модели (#273).
 *
 * **Почему увеличивать вообще, а не только «не ужимать».** Ужатие — грех, за который уже
 * заплачено и который уже измерен: серия чтений эталонной ведомости (#360) показала, что наш
 * пре-даунскейл стоит чтения, и полный кадр уезжает модели целиком. Увеличение — другая половина
 * той же мысли и работает там, где кадр родился мелким: строка таблицы на **снимке экрана**
 * (кадр 06 корпуса — окно учётной программы) высотой в пару десятков пикселей уезжает полосой, на
 * которой глазами-то читается с трудом. Интерполяция не рисует того, чего в пикселях нет, — но
 * она даёт зрячей модели знаки того размера, на котором такие модели обучены, и это ровно тот же
 * приём, которым читается табло прибора ([meterUpscale]).
 *
 * **Целое, а не дробное** — по той же причине, что у [meterUpscale]: дробный масштаб размывает
 * штрих на полпикселя, а именно по штриху отличают 8 от 6 и «т» от «г».
 *
 * **Числа здесь — суждение, и оно названо вслух.** [READING_BAND_PX] выбрана как высота полосы, на
 * которой строка таблицы читается уверенно, а не измерена прогоном: мерить её будет следующий
 * замер корпуса (метрика таблиц, `docs/CORPUS.md`), потому что на этой дороге нет ничего, что
 * можно проверить без живого запроса к модели. Потолок [MAX_READING_UPSCALE] и бюджет
 * [READING_CROP_BUDGET_PX] — ограничители, а не цель: выше потолка интерполяция только весит,
 * а за бюджетом начинается память телефона.
 *
 * Единица — «увеличивать не надо», и это обычный случай для фотографии бумаги: полоса строки на
 * снимке 4000×3000 и так высотой в полторы сотни пикселей.
 */
fun readingCropUpscale(
    widthPx: Int,
    heightPx: Int,
    target: Int = READING_BAND_PX,
    budgetPx: Long = READING_CROP_BUDGET_PX,
): Int {
    if (widthPx <= 0 || heightPx <= 0) return 1
    var scale = 1
    while (scale < MAX_READING_UPSCALE && heightPx.toLong() * scale < target) scale++
    // Бюджет отступает последним: лучше меньше увеличить, чем уронить приложение по памяти на
    // куске, который и без увеличения был бы прочитан хоть как-то.
    while (scale > 1 && widthPx.toLong() * heightPx * scale * scale > budgetPx) scale--
    return scale
}

/**
 * Высота полосы строки, на которой зрячая модель читает её уверенно.
 *
 * Суждение, а не замер (см. [readingCropUpscale]). Ориентир — полоса строки печатной ведомости на
 * фотографии 4000×3000: там она выходит около полутора сотен пикселей и читается всеми
 * маршрутами. Строку снимка экрана в 25 px это правило поднимет до сотни, то есть в тот же
 * порядок, а не «в красивое число».
 */
const val READING_BAND_PX = 120

/** Больше растягивать бессмысленно — то же число и та же причина, что у [meterUpscale]. */
private const val MAX_READING_UPSCALE = 4

/**
 * Потолок площади увеличенного куска. Не про качество, а про память: `Bitmap` на 4 Мп — это 16 МБ,
 * и перечитов идёт до двенадцати. Полоса строки в бюджет укладывается с огромным запасом; упереться
 * в него может только кусок, который и так уже большой, — а такому увеличение и не нужно.
 */
private const val READING_CROP_BUDGET_PX = 4_000_000L

/**
 * Вырезанная улика: байты картинки и её размер в пикселях.
 *
 * Размер едет вместе с байтами, потому что писателю .docx он нужен для `wp:extent` (OOXML меряет
 * картинку в EMU), а вычитывать его обратно из JPEG-заголовка — значит завести второй парсер ради
 * того, что резак и так знает.
 */
class EvidenceImage(
    val bytes: ByteArray,
    val widthPx: Int,
    val heightPx: Int,
    /** Расширение части `word/media` — оно же решает `Default`-тип в `[Content_Types].xml`. */
    val extension: String = "jpg",
)

/**
 * Режет кусок кадра по адресу улики. Реализация — в `:data` (Android `Bitmap`), контракт здесь,
 * чтобы ядро осталось Android-free, а в тестах стоял fake.
 *
 * `null` — вырезать не удалось (файла нет, рамка выродилась, декодер не справился). Это не ошибка
 * экспорта: документ собирается без картинки, потому что улика — довесок к подсветке, а не
 * условие её существования.
 */
interface EvidenceCropper {
    suspend fun crop(evidence: CropEvidence): EvidenceImage?
}

/**
 * Сколько улик максимум приложить к одному документу.
 *
 * Предел — про размер файла и про то, как улику вообще используют. Полоса строки с ведомости
 * шириной 4000 px весит после ужатия и JPEG ~50–100 КБ; на эталонном кадре помеченными оказались
 * 387 ячеек — кроп к каждой собрал бы десятки мегабайт, которые не уходят почтой и не листаются
 * на телефоне. Двенадцать — это выборочная сверка, ради которой улику и прикладывают: дальше
 * человек всё равно открывает исходник целиком.
 */
const val MAX_EVIDENCE_CROPS = 12

/**
 * Где на странице лежит фрагмент [fragment] — область строки, чьи слова с ним совпали (#267).
 *
 * Совпадение по словам, а не по порядку блоков: текст документа пересобрала модель, и порядок её
 * абзацев с порядком строк страницы не совпадает. Приложить к фрагменту соседнюю строку — тихая
 * ложь худшего сорта: человек сверяет текст с картинкой и видит несовпадение там, где его нет.
 *
 * Поэтому адрес принимается только **однозначный**:
 * - ничья двух строк по числу совпавших слов — адреса нет, возвращается `null`;
 * - одного совпавшего слова хватает, только если оно длинное (артикул `11004` с ведомости): на
 *   рукописи движок собирает кашу, но печатный артикул в первой колонке читает, и именно он
 *   остаётся единственной ниткой к строке.
 *
 * Возвращается **вся строка** с полем в треть высоты, а не боксы совпавших слов: человек сверяет
 * строку целиком, а обрезанный по буквам кроп проверять нечем.
 *
 * Возвращённая рамка — в координатах **сырого** кадра, как и требует [CropEvidence].
 */
fun AtomLayer.locate(fragment: String): Box? = locateIn(lines(), fragment)

/**
 * [locate] по уже разложенным строкам ([AtomLayer.lines] сортирует все атомы, а спорных
 * фрагментов в ведомости сотни — строки считаются один раз на документ).
 *
 * Рамка считается в **выпрямленном** кадре и возвращается в сыром: строки уже собраны в
 * выпрямленном порядке, но боксы атомы несут сырые (ADR-0001), а на кадре боком (#262) рамка
 * строки в сыром кадре вертикальна — поле «в треть высоты», отмеренное от сырой «высоты»,
 * было бы полем от длины строки.
 */
private fun AtomLayer.locateIn(lines: List<List<Atom>>, fragment: String): Box? {
    val wanted = evidenceTokens(fragment)
    if (wanted.isEmpty()) return null
    val scored = lines
        .map { line -> line to wanted.count { token -> line.any { evidenceToken(it.text) == token } } }
    val best = scored.maxByOrNull { it.second } ?: return null
    if (best.second == 0) return null
    if (scored.count { it.second == best.second } > 1) return null // адрес неоднозначен — молчим
    if (best.second == 1) {
        val matched = wanted.firstOrNull { token -> best.first.any { evidenceToken(it.text) == token } }
        if (matched == null || matched.length < DISTINCT_TOKEN) return null
    }
    val box = best.first.map { transform?.toUpright(it.box) ?: it.box }.reduce(Box::union)
    val pad = box.height * PAD_SHARE
    val padded = Box(box.left - pad, box.top - pad, box.right + pad, box.bottom + pad)
    return transform?.toRaw(padded) ?: padded
}

/**
 * Те же блоки, но у помеченных неуверенными — адрес улики, если он есть (#267).
 *
 * Правил ровно три, и все три про честность, а не про красоту:
 * - улика только к помеченному: к прочитанному уверенно картинка не нужна, а файл она растит;
 * - не больше [limit] на документ (см. [MAX_EVIDENCE_CROPS]);
 * - **координат нет — улики нет, и это не ошибка**: текст мог прийти из PDF или из чужого файла,
 *   где за словом не стоит никаких пикселей. Возвращается тот же список.
 *
 * **Помеченное без картинки называется вслух** отдельным абзацем — и когда упёрлись в предел, и
 * когда адреса не нашлось. Причина у молчания разная, а читается оно одинаково: «здесь сомнений
 * нет», хотя означает «улики не будет». Ровно та подмена статуса красивой видимостью, от которой
 * пометка и лечит, — и на эталонной ведомости это не редкий край, а норма: помеченных ячеек 387,
 * а печатный якорь есть далеко не в каждой строке.
 */
fun List<DocBlock>.withCropEvidence(
    layer: AtomLayer?,
    imagePath: String?,
    limit: Int = MAX_EVIDENCE_CROPS,
): List<DocBlock> {
    if (layer == null || layer.atoms.isEmpty() || imagePath.isNullOrBlank()) return this
    val degrees = layer.transform?.rotationDegrees ?: 0
    // Строки страницы — один раз на документ, а не заново на каждый спорный фрагмент.
    val lines = layer.lines()
    var attached = 0
    var bare = 0
    val blocks = map { block ->
        if (!block.uncertain || block.evidence != null) return@map block
        val region = layer.locateIn(lines, block.text)
        if (region == null || attached >= limit) {
            bare++
            return@map block
        }
        attached++
        block.copy(evidence = CropEvidence(imagePath, region, degrees))
    }
    if (bare == 0) return blocks
    val note = "Улик приложено $attached из ${attached + bare} помеченных фрагментов: " +
        "у остальных не нашлось однозначного места на снимке или сработал предел на документ. " +
        "Сверяйте их с исходником."
    return blocks + DocBlock(note, DocStyle.NORMAL)
}

/** Слова фрагмента, по которым его можно узнать на странице: без маркеров неуверенности и без
 *  односимвольного мусора, в котором совпадает что угодно. */
private fun evidenceTokens(fragment: String): Set<String> =
    fragment.replace("⚠", " ").replace("~~", " ")
        .split(WHITESPACE)
        .map(::evidenceToken)
        .filter { it.length >= MIN_TOKEN }
        .toSet()

/** Одно слово в сравнимом виде: регистр и пунктуация по краям различием не считаются. */
private fun evidenceToken(raw: String): String =
    raw.lowercase().trim { !it.isLetterOrDigit() }

private val WHITESPACE = Regex("""\s+""")

/** Короче — не слово, а знак: совпадение по нему ничего не адресует. */
private const val MIN_TOKEN = 2

/** Длина слова, которого хватает в одиночку: артикул `11004`, а не предлог «на». */
private const val DISTINCT_TOKEN = 4

/** Поле вокруг строки — в долях её высоты: страница приходит в любом разрешении, и допуск в
 *  пикселях, подобранный под одно фото, соврёт на другом. */
private const val PAD_SHARE = 0.35f
