package com.point.core.flow

import com.point.core.model.CapabilityId

/**
 * Есть ли на этом устройстве чем выполнить действие — и если нет, то что мешает (#528).
 *
 * Реестр до этого среза отбирал пузырьки **только** по `accepts(state)`, то есть по одной
 * половине правды. Вторая половина живёт у [Realizer.isAvailable]: у «Скана с цветом» весь смысл
 * в цветном конвейере OpenCV, и без загруженного пака выполнять действие нечем. Человек об этом
 * узнавал ПОСЛЕ тапа — из отказа «Действие недоступно», то есть заплатив за обещание, которого
 * никто не собирался выполнять.
 *
 * **Почему отдельный контракт, а не `Resolver`.** `Resolver` выбирает реализацию и умеет её
 * запускать; отдать его реестру значило бы протащить «как» в то, что видит UI, — и заодно завести
 * цикл в графе зависимостей (`Resolver` сам спрашивает реестр). Здесь спрашивается ровно один
 * вопрос — «есть ли кому», — тем же приёмом, что `PcPairings` рядом с `PcTransport`.
 *
 * **Это не про ключи.** Отсутствие ключа лечится тапом (он ведёт на экран ключей), поэтому такое
 * действие остаётся действием и лишь договаривает цену именем ([labelNeedingKey]). Сюда попадает
 * то, чего на этом телефоне нет вовсе и тапом не появится.
 */
fun interface ActionAvailability {

    /**
     * Что мешает выполнить действие прямо здесь — короткой фразой человеку, либо `null`, если
     * выполнить есть чем.
     *
     * Фраза уходит в «Почти доступно» рядом с именем действия, поэтому она в том же роде, что и
     * остальные подсказки переговоров: «нужен пакет обработки снимков», а не код ошибки.
     */
    fun blockerFor(id: CapabilityId): String?
}
