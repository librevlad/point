package com.point.core.flow

import com.point.core.model.Feature
import com.point.core.model.Intent
import com.point.core.model.ObjectState

/**
 * Годность — часть состояния объекта, а не отдельный тип и не проверка внутри каждого
 * исполнителя (решение владельца, #684/#685). `Feature.UNUSABLE` говорит: с содержимым
 * нечего делать. Этот факт — почему, словами для человека, а не техническим кодом.
 *
 * Ставится один раз — на первом экране для пустого файла (`ObjectClassifier`) или после
 * неудачного чтения (Discovery, предпросмотр) — и виден отовсюду: экрану, Planner'у при
 * выборе дверей (`offeredWhenUnfit`), подписи действия под дверью и `Resolver`'у до похода
 * в облако. Дверь при этом не исчезает — называет причину заранее, второй строкой, которой
 * у действия обычно нет вовсе (#582). Исключение одно и названо решением владельца: читать
 * себя негодный объект не предлагает (#994).
 *
 * Класть сюда можно только свои слова — названную константу или [readerFailure] (#1101). По
 * этой фразе потом решают, дело в самом файле или в сорвавшейся попытке ([saidFailureIsFatal]),
 * и незнакомая фраза считается сказанной о содержимом: чужие слова молча отняли бы объекту
 * все двери чтения. Правило держит `UnfitReasonIsOurOwnWordsTest` в `:checks`.
 */
const val META_UNUSABLE_REASON = "unusable.reason"

/**
 * Негодному объекту не предлагают прочитать себя (#994, #1101; решение владельца 21.08.2026).
 *
 * Негодность была видна подписью под каждой дверью, а двери оставались все: битому снимку
 * предлагали «Понять — найдёт суть, суммы, даты и контакты», «Распознать текст», «Прочитать
 * сильнее» и «AI» — четыре способа прочитать то, что прочитать нельзя, первым и подсвеченным.
 * Знание «с содержимым нечего делать» закрывает не только путь наружу (`staysHomeWhenUnfit`),
 * но и сам вопрос чтения.
 *
 * Уходят ровно двери чтения, и каждая объявляет себя сама — намерением «понять», а не
 * догадкой планировщика по форме результата. Решение владельца сказано про чтения: открыть,
 * поделиться, сохранить, превратить остаются на месте и по-прежнему называют причину
 * подписью там, где второй строки обычно нет (#582).
 *
 * Метку негодности ставит и сорвавшаяся операция — не отрисовался эскиз, не декодировался
 * снимок, не открылся архив. Состояние операции знанием не является (Конституция §13,
 * ADR-0001 §9), и здесь это стоит дороже, чем подпись: последнюю дверь чтения убирают
 * совсем. Поэтому дверь снимает не голая метка, а сказанное о содержимом — и уже полученное
 * знание старше и того, и другого:
 *
 * - метка молчит (слов о негодности нет) — двери чтения остаются: молчание ничего не
 *   сказало, а «не исследовано» не равно «не найдено»;
 * - слова говорят о попытке («Прочитать сейчас не вышло», «заняло слишком долго», «снимок
 *   слишком большой») — двери чтения остаются: экран зовёт попробовать ещё раз, и пробовать
 *   должно быть чем. Ровно так предпросмотр отвечает на PDF под паролем — и на битый PDF,
 *   живой объект #994: `PdfRenderer` бросает на нём `IOException` без слов словаря, и слова
 *   человеку выходят про попытку. Чтения ему поэтому пока предлагаются — героем не
 *   становятся (`promisesExtraction`), а уйдут, когда #1271 приведёт сигналы предпросмотра
 *   к словарю ридера и битый PDF назовут повреждённым (#1271: метку предпросмотр ставит без
 *   гарда `readerFailureIsFatal`, и лечится это там же, у самой метки);
 * - слова говорят о содержимом (пустой файл, обломок архива, «он повреждён», «нет ни одной
 *   страницы») — читать нечего, и чтения не предлагаются;
 * - из содержимого уже что-то прочитано — двери чтения возвращаются все, чем бы метка ни
 *   была: иначе у снимка, чей QR прочитан, пропадала бы дверь «Прочитать QR», знание есть,
 *   а войти в него нечем.
 *
 * Правило живёт здесь и одно на оба устройства — как ранжирование после #840.
 */
fun <T : Capability> offeredWhenUnfit(
    state: ObjectState,
    facts: Map<String, String>,
    candidates: List<T>,
): List<T> =
    if (contentIsUnfit(state, facts) && !knowsFromContent(facts)) {
        candidates.filterNot { Intent.UNDERSTAND in it.intents(state) }
    } else {
        candidates
    }

/**
 * Негодность сказана о содержимом, а не о сорвавшейся попытке (#1101).
 *
 * Вопрос «дело в самом объекте?» уже решён один раз — [saidFailureIsFatal] отвечает на него
 * по тем же словам, которые объект показывает человеку. Второго разбора негодности здесь не
 * заводится: разойдись они, экран говорил бы «попробуйте ещё раз» там, где пробовать уже
 * нечем.
 */
private fun contentIsUnfit(state: ObjectState, facts: Map<String, String>): Boolean =
    state.has(Feature.UNUSABLE) && saidFailureIsFatal(facts[META_UNUSABLE_REASON])

/**
 * Из содержимого объекта уже что-то узнано (#1101).
 *
 * Отвеченный вопрос, найденная сущность, прочитанный текст — такое знание могло взяться
 * только из самого содержимого. Имя файла, его размер и вид — нулевые сигналы первого
 * экрана: ими объект о себе не рассказывал, и «с содержимым нечего делать» они не спорят.
 */
fun knowsFromContent(facts: Map<String, String>): Boolean =
    facts.any { (key, value) -> value.isNotBlank() && tellsAboutContent(key, value) }

private fun tellsAboutContent(key: String, value: String): Boolean = when {
    isStateKey(key) -> value == InvestigationState.FOUND.wire
    isAnnotationKey(key) -> false
    isKnowledgeKey(key) -> true
    else -> key in READINGS
}

/** Прочитанное из объекта: сам текст или его слой (#811, #426) — знание, а не след работы. */
private val READINGS = setOf(META_READ_TEXT, META_OCR_TEXT_REF, META_OCR_ATOMS_REF)

/** Файл без единого байта — нулевой сигнал первого экрана, пустота видна до всякого чтения. */
const val EMPTY_FILE_REASON = "Файл пустой — в нём нечего читать"

/**
 * Архив, чей каталог не читается: обломок вместо архива (#570). Видно при первом же заходе
 * внутрь, и это про сам объект — как пустой файл, а не как сорвавшаяся попытка.
 */
const val BROKEN_ARCHIVE_REASON = "Архив не открылся — он повреждён или обрезан"

/**
 * Когда причина не сказана, а негодность известна. Одна на оба устройства (#855): телефон
 * говорил это из `UnusableRealizer`, компьютер — «действие для такого объекта не
 * выполняется», то есть про действие вместо объекта.
 */
const val UNFIT_DEFAULT_REASON = "С этим файлом нечего делать"

/** Причина, только когда она действительно сказана — пустая строка не считается знанием. */
fun unusableReasonOf(metadata: Map<String, String>): String? =
    metadata[META_UNUSABLE_REASON]?.takeIf { it.isNotBlank() }

/**
 * Причина по всему состоянию, а не только по факту: `META_UNUSABLE_REASON` без выставленного
 * `Feature.UNUSABLE` — залежавшийся или чужой ключ, не знание о годности этого объекта.
 */
fun GraphState.unusableReason(): String? =
    if (state.has(Feature.UNUSABLE)) fact(META_UNUSABLE_REASON) else null

/**
 * Причина, общая для всех действий сразу (#874).
 *
 * Когда с объектом нечего делать, причина одна на всё: «Файл пустой — в нём нечего читать».
 * Она уже сказана подписью объекта, а `yieldLabel` подставлял её ещё и второй строкой у
 * каждого действия — на экране получалось шесть одинаковых фраз подряд, а под прокруткой
 * больше. Экран кричал одно вместо того, чтобы сказать это один раз.
 *
 * Правило то же, что у групп на экране ключей (#887): общее говорится один раз, а в строке
 * остаётся то, что её отличает. Причина у действия остаётся, когда она СВОЯ, — например
 * «нет интернета» у сетевого действия рядом с местным.
 */
fun sharedUnusableReason(reasons: List<String?>): String? {
    val first = reasons.firstOrNull()?.takeIf { it.isNotBlank() } ?: return null
    if (reasons.size < 2) return null
    return first.takeIf { reasons.all { reason -> reason == first } }
}
