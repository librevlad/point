package com.point.core.flow

import com.point.core.model.Feature

/**
 * Годность — часть состояния объекта, а не отдельный тип и не проверка внутри каждого
 * исполнителя (решение владельца, #684/#685). `Feature.UNUSABLE` говорит: с содержимым
 * нечего делать. Этот факт — почему, словами для человека, а не техническим кодом.
 *
 * Ставится один раз — на первом экране для пустого файла (`ObjectClassifier`) или после
 * неудачного чтения (Discovery, предпросмотр) — и виден отовсюду: экрану, подписи действия
 * под дверью и `Resolver`'у до похода в облако. Дверь при этом не исчезает — называет
 * причину заранее, второй строкой, которой у действия обычно нет вовсе (#582).
 */
const val META_UNUSABLE_REASON = "unusable.reason"

/** Файл без единого байта — нулевой сигнал первого экрана, пустота видна до всякого чтения. */
const val EMPTY_FILE_REASON = "Файл пустой — в нём нечего читать"

/**
 * Архив, чей каталог не читается: обломок вместо архива (#570). Видно при первом же заходе
 * внутрь, и это про сам объект — как пустой файл, а не как сорвавшаяся попытка.
 */
const val BROKEN_ARCHIVE_REASON = "Архив не открылся — он повреждён или обрезан"

/**
 * Когда причина не сказана, а негодность известна. Одна на оба устройства (#855): телефон
 * говорил это из `UnusableRealizer`, компьютер — «действие для такого объекта не
 * выполняется», то есть про действие вместо объекта.
 */
const val UNFIT_DEFAULT_REASON = "С этим файлом нечего делать"

/** Причина, только когда она действительно сказана — пустая строка не считается знанием. */
fun unusableReasonOf(metadata: Map<String, String>): String? =
    metadata[META_UNUSABLE_REASON]?.takeIf { it.isNotBlank() }

/**
 * Причина по всему состоянию, а не только по факту: `META_UNUSABLE_REASON` без выставленного
 * `Feature.UNUSABLE` — залежавшийся или чужой ключ, не знание о годности этого объекта.
 */
fun GraphState.unusableReason(): String? =
    if (state.has(Feature.UNUSABLE)) fact(META_UNUSABLE_REASON) else null

/**
 * Читать нечего (#994).
 *
 * Про объект уже известно, что содержимое не открылось, и знания из него не добыто ни одного.
 * Тогда действия чтения — «Понять», «Распознать текст», «Прочитать сильнее» — не могут быть
 * лучшим следующим шагом: очевидное на битом файле не «найти суммы», а взять целый файл.
 *
 * Знание важнее пометки: у снимка, чей предпросмотр не отрисовался, слова со страницы могли
 * прочитаться — и тогда читать есть что, что бы ни говорила пометка о годности.
 */
fun nothingToRead(state: com.point.core.model.ObjectState, facts: Map<String, String>): Boolean =
    state.has(Feature.UNUSABLE) &&
        !state.has(Feature.HAS_TEXT) &&
        !state.has(Feature.HAS_WORD_LAYER) &&
        facts.keys.none { it.startsWith(META_ENTITY_PREFIX) }

/**
 * Причина, общая для всех действий сразу (#874).
 *
 * Когда с объектом нечего делать, причина одна на всё: «Файл пустой — в нём нечего читать».
 * Она уже сказана подписью объекта, а `yieldLabel` подставлял её ещё и второй строкой у
 * каждого действия — на экране получалось шесть одинаковых фраз подряд, а под прокруткой
 * больше. Экран кричал одно вместо того, чтобы сказать это один раз.
 *
 * Правило то же, что у групп на экране ключей (#887): общее говорится один раз, а в строке
 * остаётся то, что её отличает. Причина у действия остаётся, когда она СВОЯ, — например
 * «нет интернета» у сетевого действия рядом с местным.
 */
fun sharedUnusableReason(reasons: List<String?>): String? {
    val first = reasons.firstOrNull()?.takeIf { it.isNotBlank() } ?: return null
    if (reasons.size < 2) return null
    return first.takeIf { reasons.all { reason -> reason == first } }
}
