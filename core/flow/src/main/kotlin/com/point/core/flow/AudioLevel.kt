package com.point.core.flow

import com.point.core.model.PointObject

/**
 * Уровень звука записи, измеренный на самом устройстве (#1053).
 *
 * Пустая запись не молчит в облаке: двадцать секунд цифровой тишины возвращались из Whisper
 * фразой «Thank you.», и выдумка ложилась знанием об объекте — по ней предлагали «Понять» и
 * «Перевести». Спрашивать сервис, есть ли в записи звук, незачем: у записи, в которой нечего
 * слушать, самый громкий сэмпл лежит у нуля, и это видно здесь, до отправки.
 *
 * Само измерение — side effect (декодер), поэтому живёт за интерфейсом; правило ниже — чистое.
 */
fun interface AudioLevel {

    /**
     * Самый громкий сэмпл записи, 0..1.
     *
     * `null` — измерить не вышло: формат не открылся, декодер отказал, времени не хватило.
     * Это не «тихо»: не измерили — значит, запись идёт дальше обычным путём.
     */
    suspend fun peak(obj: PointObject): Double?
}

/**
 * Тише этого пика в записи нет звука вовсе.
 *
 * 0,5 % от полной шкалы (около −46 dBFS) — это цифровые нули и шум кодека вокруг них, а не
 * тихий голос: даже далёкая от микрофона речь даёт пик на порядок выше. Порог намеренно
 * низкий: не расслышать настоящую речь дороже, чем впустую сходить в сервис.
 */
const val AUDIBLE_PEAK = 0.005

/** В записи нечего слушать — отправлять её некуда (#1053). */
fun nothingToHear(peak: Double?): Boolean = peak != null && peak < AUDIBLE_PEAK
