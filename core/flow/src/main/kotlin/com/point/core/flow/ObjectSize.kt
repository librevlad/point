package com.point.core.flow

import kotlin.math.roundToInt

/**
 * Вес объекта в байтах, каким его увидел приёмник (#459).
 *
 * **Почему метаданное, а не чтение по требованию.** Размер — нулевой сигнал: он уже известен
 * тому, кто скопировал объект в scratch, ровно в тот момент, когда копировал. Первый экран
 * (≤ 300 мс, без I/O) вправе им пользоваться только если размер приехал вместе с объектом;
 * стоило бы экрану спросить его у файловой системы самому — и правило «без I/O» держалось бы
 * на честном слове каждого нового вызова.
 *
 * Кладут его хранилища объектов (`ScratchObjectStore`, `FileHistoryStore`), а не действия:
 * они единственные знают файл. Метаданные журналируются целиком, поэтому вес переживает
 * смерть процесса и возвращается вместе с флоу.
 */
const val META_SIZE = "size"

/**
 * Вес словами — «540 КБ», «5,2 МБ» — или null, когда веса нет вовсе.
 *
 * Разряд один: «5,2 МБ» человек читает как размер, «5 242 880 байт» — как число. Дробная часть
 * появляется только там, где она что-то меняет: «2 МБ», а не «2,0 МБ».
 */
fun humanWeight(bytes: Long): String? {
    if (bytes <= 0L) return null
    val kb = bytes / 1024.0
    if (kb < 1.0) return "$bytes Б"
    if (kb < 1024.0) return "${kb.roundToInt()} КБ"
    val mb = kb / 1024.0
    if (mb < 1024.0) return "${oneDecimal(mb)} МБ"
    return "${oneDecimal(mb / 1024.0)} ГБ"
}

/** Число с одним знаком после запятой, без Locale-зависимого форматирования: запятая здесь
 *  часть языка экрана, а не настройка системы. */
private fun oneDecimal(value: Double): String {
    val tenths = (value * 10).roundToInt()
    val whole = tenths / 10
    val rest = tenths % 10
    return if (rest == 0) "$whole" else "$whole,$rest"
}
