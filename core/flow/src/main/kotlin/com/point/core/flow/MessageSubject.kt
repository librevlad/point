package com.point.core.flow

/**
 * Тема письма — **признак того, что документ вообще про переписку** (#262).
 *
 * Зачем отдельный факт. Два кадра корпуса — входящее сообщение клиента в поддержку и фото
 * монитора с открытым почтовым клиентом — человек открыл, чтобы **ответить**. Готовность такого
 * действия считается адресом («кому отвечать»), но адрес почты карточку звать не имеет права: он
 * стоит в подписи счёта, на визитке и в шапке накладной, и якорь на нём повторил бы ошибку,
 * которую чинил #260 на дате и #262 на адресе — «в документе упомянуто» вместо «документ ПРО
 * это». Тема бывает только у письма или сообщения, поэтому якорем стоит она.
 *
 * **Формы у темы нет, и правило сюда не пишет никогда** — тот же случай, что у места назначения
 * ([META_ENTITY_PLACE]): «Refund for service — It won't be needed» отличается от любой другой
 * строки документа не написанием, а тем, где она стоит на экране. Значение приходит только от
 * модели (контрактный ключ `SUBJECT`) и получает происхождение «прочитано моделью»; гадать по
 * первой жирной строке правило не будет — это вёрстка, а не чтение.
 *
 * **Названная цена.** Письмо без темы («(no subject)» на кадре 05) карточку «Ответить» не покажет,
 * пока модель не назовёт тему, — но **измеримости это не касается**: [scoreCorpus] считает
 * готовность через [ActionSchema.readiness], где якоря нет, и там всё решает адрес. Ровно та же
 * цена и то же разделение, что у адреса в «Построить маршрут».
 */
const val META_ENTITY_SUBJECT = META_ENTITY_PREFIX + "subject"
