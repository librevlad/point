package com.point.core.flow

/**
 * Настройки едут за человеком через сервер (#610, решение владельца 10.08.2026) — за
 * аккаунтом, а не за кругом устройств (владелец 26.11.2026: «оно должно зависеть только от
 * аккаунта, не от круга»).
 *
 * До этого настройки ездили запечатанными под устройства круга, и новое устройство открыть
 * их не могло, пока кто-то из старых не перепечатает: телефон, вошедший после компьютера,
 * видел один ключ из двенадцати. Теперь их хранит сервер, и отдаёт любому вошедшему.
 *
 * Один свод на обе стороны: телефон и компьютер сводят своё с тем, что лежит на сервере,
 * одним и тем же кодом. Порознь у них разъехались бы правила слияния — молча и незаметно,
 * потому что каждая сторона считала бы себя правой.
 */
class AccountSettingsSync(
    private val client: AccountClient,
    private val clock: () -> Long = System::currentTimeMillis,
) {

    /**
     * Свести своё с общим и вернуть итог.
     *
     * `null` — свести не вышло (сеть, отзыв пропуска, на сервере успели положить новее):
     * своё при этом остаётся как было. Молчаливая потеря настроек хуже несостоявшегося обмена.
     */
    suspend fun sync(account: PointAccount, mine: AccountSettings): AccountSettings? {
        // Не спросили — не пишем: «не знаю, что там» не то же, что «там пусто».
        val theirs = client.settings(account) ?: return null

        val merged = theirs.mergedWith(mine)
        if (merged == theirs) return merged

        // Своё новее общего — значит, у общего появилась новая отметка времени: иначе
        // сервер отказал бы, а правка человека потерялась бы молча.
        val stamped = merged.copy(at = maxOf(merged.at, clock()))
        return if (client.saveSettings(account, stamped)) stamped else null
    }
}
