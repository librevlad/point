package com.point.core.flow

import com.point.core.model.Provenance
import java.math.BigDecimal
import java.math.RoundingMode

/**
 * Сумма денег — факт, которого у объекта не было вовсе (#262).
 *
 * Прецедент — показание счётчика ([meterFacts]): в корпусе владельца два кадра из двадцати трёх,
 * где человек пришёл **перевести деньги** (реквизиты карты в переписке и сумма к возврату; фото
 * приборов учёта с расчётом суммы к оплате), и измерить их было нечем — не потому, что действие
 * сложное, а потому, что самого факта никто не писал. Схема без факта лжёт в обе стороны, поэтому
 * факт заводится вместе со схемой «Перевести по реквизитам».
 *
 * **Форма — число рядом с валютой.** Ровно та же порода правила, что «число рядом с единицей
 * учёта»: дешёвая, офлайновая, ошибающаяся. Поэтому она **размечает, а не решает** (#232, #258):
 * улика ровно одна — [EvidenceClass.SEMANTIC], — и человек видит «возможно», пока второй
 * независимый класс не принесёт тот, кто смотрел на слой страницы ([fieldEvidence]: подпись
 * «Сума» рядом со значением — это уже другой класс).
 *
 * **Значение — только цифры**, валюта живёт своим ключом ([META_ENTITY_AMOUNT_CURRENCY]). Тот же
 * довод, что у показания: OCR читает «300грн», модель пишет «300 грн», [normConsensus] складывает
 * пробелы, но не буквы, — и число, прочитанное обоими одинаково, получило бы ложный спор.
 *
 * **Второе чтение — итог сошедшегося расчёта** ([arithmeticTotals], #262, кадр 03). Валюта на
 * странице бывает не всегда: в переписке человек считает вслух — «127*4.32=548,64», «500+548,64=
 * 1048,64», — и ни одного знака гривны рядом нет. Число при этом стоит на странице **дословно**, и
 * не прочесть его значит объявить непрочитанным то, что напечатано. Читается оно другой уликой —
 * [EvidenceClass.ARITHMETIC]: расчёт сошёлся сам с собой, и это проверяемое утверждение страницы,
 * а не наша догадка.
 *
 * **Названная граница: цену от суммы к переводу правило не отличает вовсе.** На кадре 02 корпуса
 * стоят обе — цена товара и сумма, которую просят перевести, — и формой они не различаются ничем.
 * Правило пишет первую, вторая честно видна в `.more` («или: …»), и человек выбирает сам. Это та
 * же граница, что у показания счётчика рядом с объёмом потребления, и лечится она не хитростью
 * формы, а вторым читателем — моделью (контрактный ключ `AMOUNT`).
 *
 * **Извлекатель сущностей этот ключ намеренно НЕ пишет.** У ML Kit есть тип `MONEY`, но его
 * значение несёт валюту внутри («300 грн»), а [mergeFacts] сравнивает значения: два писателя
 * одного ключа с разной записью объявили бы ложный спор о числе, которое оба прочли одинаково.
 * Писателей у факта поэтому двое — это правило и модель, — и оба пишут цифры.
 */
data class MoneyAmount(
    /** Цифры суммы, дословно со страницы: `300`, `4 020.10`, `1048,64`. */
    val value: String,
    /** Валюта, дословно: `грн`, `₴`, `$`. Она и есть причина считать это число деньгами. */
    val currency: String,
)

/**
 * Сумма как факт объекта: тот же ключ читают схемы «Перевести по реквизитам» и «Переслать
 * квитанцию» ([ACTION_SCHEMAS]) и пишет «Понять» (контрактный ключ `AMOUNT`). Два независимых
 * источника одного факта встречаются в [mergeFacts]: цифры неприкосновенны, спор виден.
 */
const val META_ENTITY_AMOUNT = META_ENTITY_PREFIX + "amount"

/**
 * Валюта суммы — **факт, а не аннотация** (`.currency` не входит в [isAnnotationKey]), ровно как
 * единица учёта у показания. Она отвечает на «в чём переводить», то есть меняет само действие, а
 * не оформление числа.
 */
const val META_ENTITY_AMOUNT_CURRENCY = META_ENTITY_AMOUNT + ".currency"

/** Больше цифр в целой части не бывает у денег, зато бывает у номера карты (16) и IBAN (27):
 *  граница отсекает не «слишком дорого», а чужое число, к которому прилипла валюта. */
private const val AMOUNT_MAX_DIGITS = 12

/**
 * Столько ли цифр в целой части, сколько бывает у суммы.
 *
 * **Одна реализация границы на обоих судей** — правило ([moneyAmounts]) и валидатор чтения модели
 * ([semanticFits]). Два счётчика формы разъехались бы на первой правке, и «модель прочитала то,
 * чего правило не приняло бы» стало бы невидимым (тот же урок, что у [meterDigitsFit]).
 */
internal fun amountDigitsFit(value: String): Boolean =
    value.substringBefore(',').substringBefore('.').count(Char::isDigit) in 1..AMOUNT_MAX_DIGITS

/**
 * Суммы в [text] в порядке появления, без повторов (одно и то же число с той же валютой в шапке и
 * в итоге — одна сумма).
 *
 * Границы числа стерегутся с обеих сторон: номер карты, к которому прилип знак валюты, обрезком
 * суммы не становится (тот же урок, что у [waybillNumbers] и [meterReadings]). Разрядный пробел —
 * часть числа: «4 020.10 ₴» обязано читаться целиком, иначе правило напишет `020.10` и пометит
 * его `src=ocr`, то есть выдаст выдуманное значение за прочитанное дословно (ревью #262).
 */
fun moneyAmounts(text: String): List<MoneyAmount> =
    AMOUNT_SHAPED.findAll(text)
        .map { m ->
            // Ветка «валюта перед числом» — первые две группы, «число перед валютой» — вторые.
            val value = m.groupValues[2].ifEmpty { m.groupValues[3] }
            val currency = m.groupValues[1].ifEmpty { m.groupValues[4] }
            MoneyAmount(value.trim(), currency.trim())
        }
        .filter { amountDigitsFit(it.value) }
        .distinctBy { it.value.filter { c -> c.isDigit() || c == ',' || c == '.' } + "|" + it.currency.lowercase() }
        .toList()

/**
 * Сумма как факты объекта: значение, валюта, происхождение и улика формы. Несколько сумм на
 * странице (цена и сумма к возврату, сумма и комиссия) — все в `entity.amount.more`: подтверждение
 * первой моделью не имеет права стереть запись о второй (конвенция `.more`, #260).
 *
 * **Названная граница:** `.more` несёт числа без валют — валюта записана у первой суммы. Второе
 * число не теряется, теряется его подпись; чинить это стоит тогда, когда появится действие,
 * переводящее две суммы разом.
 */
fun amountFacts(text: String): Map<String, String> {
    val amounts = moneyAmounts(text)
    // Валюта — сильнейшее чтение: она и есть причина считать число деньгами. Расчёт спрашивают
    // только там, где валюты на странице нет вовсе: иначе слабое чтение шумело бы в `.more`
    // страницы, которая про свои деньги всё сказала сама.
    val first = amounts.firstOrNull() ?: return totalFacts(arithmeticTotals(text))
    val values = amounts.map { it.value }.distinct()
    return buildMap {
        put(META_ENTITY_AMOUNT, first.value)
        put(META_ENTITY_AMOUNT_CURRENCY, first.currency)
        // ПРОЧИТАНО: правило нашло эти цифры дословно в распознанном тексте, а не вывело их (#264).
        put(META_ENTITY_AMOUNT + META_SOURCE_SUFFIX, Provenance.OCR.wire)
        // Улика ровно одна — форма. «Не судили» и «улик мало» обязаны выглядеть по-разному (#264).
        put(META_ENTITY_AMOUNT + META_EVIDENCE_SUFFIX, EvidenceClass.SEMANTIC.name.lowercase())
        if (values.size > 1) put(META_ENTITY_AMOUNT + META_MORE_SUFFIX, altValue(values))
    }
}

/**
 * Итог расчёта как факты объекта — второе чтение той же суммы, когда валюты на странице нет.
 *
 * **Валюта не пишется вовсе.** Её на странице не было, а выдумать «грн» значило бы решить за
 * человека, в чём переводить, — то есть подменить факт догадкой в единственном месте, где она
 * стоит денег. Схема «Перевести по реквизитам» валюту читает побочным полем и без неё работает.
 *
 * **Улика ровно одна — [EvidenceClass.ARITHMETIC]**, и человек видит «возможно». Соблазн выдать
 * вторую (форма числа подходит под сумму) назвал бы значение подтверждённым: расчёт доказывает,
 * что число — **итог**, и ничего не говорит о том, что итог этот в деньгах. Валютное чтение стоит
 * ровно одной улики ([EvidenceClass.SEMANTIC]) — расчётное не имеет права выглядеть увереннее.
 */
private fun totalFacts(totals: List<String>): Map<String, String> {
    val first = totals.firstOrNull() ?: return emptyMap()
    return buildMap {
        put(META_ENTITY_AMOUNT, first)
        // ПРОЧИТАНО: итог напечатан на странице дословно — правило его не вычисляло, а сверило.
        put(META_ENTITY_AMOUNT + META_SOURCE_SUFFIX, Provenance.OCR.wire)
        put(META_ENTITY_AMOUNT + META_EVIDENCE_SUFFIX, EvidenceClass.ARITHMETIC.name.lowercase())
        // Промежуточные итоги не исчезают: человек видит их строкой «или: …» и выбирает сам.
        if (totals.size > 1) put(META_ENTITY_AMOUNT + META_MORE_SUFFIX, altValue(totals))
    }
}

/**
 * Итоги расчётов, **сошедшихся самих с собой**: `500+548,64=1048,64` (#262, кадр 03).
 *
 * Порядок — итоговые впереди промежуточных, внутри каждой группы по появлению. Промежуточный —
 * тот, чей результат ниже по странице сам стал слагаемым: человек считает по шагам, и число,
 * которое он тут же складывает дальше, ответом не является. На кадре корпуса это ровно те две
 * строки — `127*4.32=548,64`, а следом `500+548,64=1048,64`, — и без этого правила первым
 * (то есть значением поля) встал бы промежуточный `548,64`, а человеку пришлось бы править сумму
 * перевода. Метрика #262 считает действие выполненным «без правок», поэтому такая победа была бы
 * зелёной по числу и ложной по смыслу.
 *
 * **Что здесь свидетельствует.** Не форма числа — под неё подходит любое число, — а то, что три
 * числа строки согласованы между собой. Это ровно [EvidenceClass.ARITHMETIC] по определению
 * класса, и второй такой улики у нас до сих пор не было (первая — контрольная цифра S10).
 * Проверка обязательна: не сошлось — правило молчит. Расчёт, который не сходится, — это либо
 * не расчёт вовсе, либо строка, которую движок прочитал неверно, и выдавать её итог за сумму
 * значило бы пометить `src=ocr` число, ничем на странице не подтверждённое.
 *
 * **Названная цена: правило не знает, что расчёт про деньги.** «2*3=6» в заметке о раскладке
 * плитки станет `entity.amount = 6`. Цена принята сознательно и мала: сумма не якорь ни в одной
 * схеме ([ACTION_SCHEMAS]) — «Перевести по реквизитам» зовёт карта, — поэтому лишний итог никого
 * никуда не зовёт, а рядом со значением стоит «возможно». Сузить правило до «расчёта про деньги»
 * нечем: на кадре корпуса про деньги не сказано ни слова, только числа.
 */
fun arithmeticTotals(text: String): List<String> {
    val sums = ARITHMETIC_SHAPED.findAll(text).mapNotNull(::checkedSum).toList()
    // Промежуточный — тот, чей итог ниже по странице стал слагаемым другого сошедшегося расчёта.
    val (finals, intermediates) = sums.withIndex().partition { (i, sum) ->
        sums.drop(i + 1).none { later -> later.operands.any { sameNumber(it, sum.total) } }
    }
    return (finals + intermediates).map { it.value.total }.distinctBy(::numericKey)
}

/** Сошедшийся расчёт: слагаемые и напечатанный итог, дословно со страницы. */
private class CheckedSum(val operands: List<String>, val total: String)

/** Расчёт из совпадения — или `null`, если он не сходится (единственный законный повод молчать). */
private fun checkedSum(m: MatchResult): CheckedSum? {
    val left = decimalOrNull(m.groupValues[1]) ?: return null
    val right = decimalOrNull(m.groupValues[3]) ?: return null
    val printed = decimalOrNull(m.groupValues[4]) ?: return null
    val computed = apply(left, m.groupValues[2], right) ?: return null
    // Сверяется столько знаков, сколько напечатано: «127*4.32» даёт 548,6400, а страница
    // говорит «548,64» — это то же число, записанное так, как записывают деньги.
    if (computed.setScale(printed.scale(), RoundingMode.HALF_UP).compareTo(printed) != 0) return null
    return CheckedSum(listOf(m.groupValues[1], m.groupValues[3]), m.groupValues[4].trim())
}

private fun apply(a: BigDecimal, op: String, b: BigDecimal): BigDecimal? = when (op) {
    "+" -> a + b
    "-", "−", "–" -> a - b
    // Латинская и кириллическая «икс» — то же умножение: человек пишет её той раскладкой, что
    // включена, а не той, что правильнее.
    "*", "×", "x", "X", "х", "Х" -> a * b
    // Деление точное невозможно (1/3), поэтому считается с запасом знаков и округляется по
    // напечатанному итогу — тем же порядком, что умножение с копейками.
    "/", ":", "÷" -> if (b.signum() == 0) null else a.divide(b, DIVISION_SCALE, RoundingMode.HALF_UP)
    else -> null
}

/** Знаков после запятой при делении — с запасом: итог всё равно сверяется по напечатанному. */
private const val DIVISION_SCALE = 6

/** Число страницы как число: разрядный пробел — оформление (и ровно тот же, что знает форма
 *  числа), запятая и точка — одна и та же десятичная черта: OCR и человек пишут их вперемешку
 *  в одной строке («127*4.32=548,64»). */
private fun decimalOrNull(raw: String): BigDecimal? =
    raw.replace(SPACE_IN_NUMBER, "").replace(',', '.').toBigDecimalOrNull()

private val SPACE_IN_NUMBER = Regex(H_SPACE)

/** Число без записи: `1 048,64` и `1048.64` — одно и то же число, и повтором они считаются
 *  вместе. Дословное значение при этом не трогается нигде — ключ живёт только в сравнении. */
private fun numericKey(value: String): String =
    value.filter { it.isDigit() || it == ',' || it == '.' }.replace(',', '.')

private fun sameNumber(a: String, b: String): Boolean = numericKey(a) == numericKey(b)

/**
 * Расчёт: два числа, знак и напечатанный итог за знаком равенства.
 *
 * Числа — те же, какими пишут деньги ([AMOUNT_NUMBER]): одна форма на оба чтения суммы, иначе
 * «правило приняло бы это число слагаемым, но не приняло бы суммой» стало бы невидимым.
 *
 * Справа от итога запрещены только цифра и ещё одна дробная часть. Запрет «цифра через пробел»,
 * которым [AMOUNT_RIGHT] бережёт сумму от обрезка карты, здесь **вреден**: в переписке за итогом
 * стоит таймстемп, и движок отдал его как `1048,64 4...` — с тем запретом правило молчало бы
 * ровно на живом кадре. Обрезком чужого числа итог быть не может: слева его держит знак равенства.
 */
private val ARITHMETIC_SHAPED = Regex(
    "(?<![\\d.,])($AMOUNT_NUMBER)$H_SPACE*([-+*/:−–×÷xXхХ])$H_SPACE*" +
        "($AMOUNT_NUMBER)$H_SPACE*=$H_SPACE*($AMOUNT_NUMBER)(?![\\d])(?![.,]\\d)",
)

/**
 * Валюты, которыми здесь пишут суммы. Список сознательно короткий и дословный: каждая новая
 * строка — новый способ ошибиться, и добавлять её стоит с живым кадром в руках (тот же порядок,
 * что у единиц учёта в [meterReadings]).
 *
 * Слова «гривень», «долларов» в списке нет намеренно: «п'ятсот гривень 00 копійок» — сумма
 * прописью с банковской квитанции, и правило прочло бы её как «00 гривень», то есть выдало бы
 * ноль за сумму платежа.
 */
private val CURRENCIES = listOf(
    "₴", "грн.", "грн", "UAH",
    "$", "USD", "€", "EUR", "£", "GBP",
    "₽", "руб.", "руб", "RUB",
    "zł", "PLN",
)

private val CURRENCY_ALT =
    CURRENCIES.sortedByDescending { it.length }.joinToString("|") { Regex.escape(it) }

/**
 * Пробел **внутри одного числа** — только горизонтальный: обычный, табуляция, неразрывный.
 *
 * Перенос строки им не бывает (ревью #262). `\s` в Java включает `\n`, и с ним разрядной группой
 * оказывался кусок соседней строки: в переписке таймстемп стоит своей строкой, сумма — следующей,
 * и «10:03 ⏎ 300 грн» правило читало как одно число `03⏎300`. Хуже места для такой ошибки нет:
 * значение помечено `src=ocr` — «прочитано со страницы дословно», — а такого числа на странице
 * нет вовсе. Ровно та болезнь, от которой разрядный пробел и был введён («4 020.10» вместо
 * `020.10`), только с обратным знаком: там число рвали, здесь склеивают чужое.
 *
 * Обратная сторона того же переноса — молчаливая потеря: граница «слева не стоит цифра с
 * пробелом» защищает от обрезка карты, но с `\n` она глотала настоящую сумму всякий раз, когда
 * предыдущая строка кончалась цифрой («Код банку 322001 ⏎ 500 грн» → не найдено ничего).
 *
 * Между числом и валютой перенос по-прежнему законен (`320 ⏎ грн` — живая вёрстка пузыря кадра
 * 02): там он разделяет число и подпись, а не разрывает число.
 */
private const val H_SPACE = "[ \\t\\u00A0]"

/**
 * Число, каким его пишут в деньгах: разрядные группы ровно по три либо сплошные цифры, дробная
 * часть — не больше двух знаков. Сколько цифр законно, решает не регекс, а [amountDigitsFit] —
 * граница живёт в одном месте.
 */
private const val AMOUNT_NUMBER =
    "(?:\\d{1,3}(?:$H_SPACE\\d{3})+|\\d{1,$AMOUNT_MAX_DIGITS})(?:[.,]\\d{1,2})?"

/**
 * Число не должно оказаться **куском** чужого числа подлиннее — карты, счёта, IBAN. Слева от
 * суммы не стоит цифра (и цифра с пробелом: `4111 1111 1111 1111` — четвёрки, а не разрядные
 * группы, и «2632 грн» было бы обрезком карты), справа за суммой не начинается ещё одна группа
 * цифр. Тот же урок, что у [waybillNumbers] с «рахунок 202045149154939512».
 *
 * Пробел здесь тоже только горизонтальный ([H_SPACE]): цифра в конце **предыдущей строки** ничего
 * о сумме не говорит, а с `\n` она эту сумму отменяла молча.
 *
 * **И справа за суммой не начинается ещё одна группа через точку, запятую или двоеточие**
 * (ревью #262). Куском чужого числа сумма бывает не только через пробел: подпись колонки на
 * квитанции стоит отдельной строкой, а под ней — не всегда число, и «Сума (грн) ⏎ 26.04.2026»
 * правило читало как «26.04 грн», а «Ціна, грн ⏎ 10:03» — как «10 грн». Дата и время выглядели
 * бы на карточке «Перевести по реквизитам» настоящей суммой, помеченной `src=ocr`. Настоящую
 * сумму запрет не трогает: у денег дробная часть одна и последняя («500.00 », «1048,64 грн»).
 */
private const val AMOUNT_LEFT = "(?<![\\d.,])(?<![\\d.,]$H_SPACE)"
private const val AMOUNT_RIGHT = "(?![\\d])(?![.,:]\\d)(?!$H_SPACE\\d)"

/**
 * Сумма — число и валюта вплотную, в любом порядке.
 *
 * Валюта **перед** числом бывает не только в `$100`: на банковской квитанции подпись колонки
 * несёт её в скобках — «Сума (грн) 500.00», — а колоночную вёрстку OCR отдаёт то одной строкой с
 * широким пробелом, то переносом. Поэтому между валютой и числом допущены закрывающая скобка,
 * пробелы и **один** перенос строки: требовать от вёрстки ровно пробела значит требовать того,
 * чего она не обещала (тот же довод, что у окна соседства в [markerNear]), а пустая строка уже
 * означает другой абзац.
 *
 * `(?iu)` — регистронезависимость **с юникодом**: без `u` флаг Java складывает только ASCII, и
 * «ГРН» прошло бы мимо.
 */
private val AMOUNT_SHAPED = Regex(
    "(?iu)(?:" +
        "(?<![\\p{L}])($CURRENCY_ALT)\\)?[ \\t\\u00A0]*\\n?[ \\t\\u00A0]*" +
        AMOUNT_LEFT + "($AMOUNT_NUMBER)" + AMOUNT_RIGHT +
        "|" +
        AMOUNT_LEFT + "($AMOUNT_NUMBER)" + AMOUNT_RIGHT +
        "[\\s\\u00A0]{0,2}($CURRENCY_ALT)(?![\\p{L}])" +
        ")",
)
