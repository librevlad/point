package com.point.core.flow

/**
 * Временные копии расшаренного текста — и их уборка.
 *
 * Текст из «Поделиться», из выделения в чужом приложении и из буфера попадает во флоу так же, как
 * любой другой объект: он сначала становится файлом. Файл этот ложился в кэш приложения, а
 * обязательная уборка в конце флоу чистила только рабочую копию (`ObjectStore.clear`) — и текст
 * оставался на диске навсегда. На эмуляторе после нескольких сеансов лежало полтора десятка таких
 * файлов; через эту дверь идут пароли, переписка и реквизиты.
 *
 * Отдельный контракт, а не «дописать в ObjectStore»: рабочую копию заводит хранилище, а эти файлы
 * заводит `:app` на границе с системой, и убирать их должен тот, кто их создаёт.
 */
interface SharedTexts {

    /** Файл под новый расшаренный текст. Путь возвращается строкой — `:core:flow` Android-free. */
    fun create(text: String): String

    /** Всё, что натекло за флоу, уходит с диска. Вызывается там же, где `ObjectStore.clear`. */
    fun clear()
}
