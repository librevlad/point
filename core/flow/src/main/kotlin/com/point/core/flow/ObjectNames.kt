package com.point.core.flow

/**
 * Как объект называется, когда имени ему никто не давал (#533).
 *
 * Три источника из пяти Point называет сам, и до сих пор называл машинно: расшаренный текст
 * становился `shared-5631909340713910696.txt`, запись — `record-1754325912345.m4a`, снимок —
 * `shot-1754325912345.jpg`. В «Недавнем» это видно в лицо: живой прогон 04.08.2026 дал две строки
 * `receipt.png` подряд, различимые ТОЛЬКО относительным временем под ними. Имя, по которому нельзя
 * узнать объект, — не имя, а идентификатор в чужой одежде.
 *
 * Правило простое: **имя берётся из содержимого**, а когда содержимое ещё не прочитано (звук,
 * кадр) — из того, чем объект является и когда он появился. Обе функции чистые и потому судятся
 * тестом, а не глазами на телефоне.
 *
 * Имя — не имя файла. Файл в кэше как назывался, так и называется; расширение остаётся его
 * свойством, а фраза из содержимого — свойством объекта (см. `FileHistoryStore.extensionFor`).
 */

/** Длина имени в знаках: строка «Недавнего» всё равно обрежет длиннее, а хвост «…» честнее многоточия системы. */
private const val NAME_LIMIT = 40

/** Имя тексту, у которого нечего спросить, кроме самого текста. */
private const val UNNAMED_TEXT = "Текст"

/**
 * Первые слова текста — его имя.
 *
 * Режется по границе слова: обрубок посреди слова читается как поломка, а не как сокращение.
 * Переводы строк и знаки, запрещённые в именах файлов, схлопываются в пробел — имя доезжает до
 * `MediaStore` при сохранении в «Загрузки», и оставлять там `/` значит подарить человеку отказ
 * записи вместо файла.
 */
fun textObjectName(text: String, limit: Int = NAME_LIMIT): String {
    // Читаем начало, а не файл целиком: имени хватит первых строк, и на мегабайтном тексте это
    // разница между «мгновенно» и «подумав».
    val head = text.take(limit * 4).replace(UNSAFE, " ").replace(SPACES, " ").trim()
    if (head.isEmpty()) return UNNAMED_TEXT
    if (head.length <= limit) return head.trimEnd(*TRAILING).ifBlank { UNNAMED_TEXT }
    val cut = head.take(limit + 1)
    val lastSpace = cut.lastIndexOf(' ')
    val words = (if (lastSpace > limit / 2) cut.take(lastSpace) else head.take(limit)).trimEnd(*TRAILING)
    return if (words.isBlank()) UNNAMED_TEXT else "$words…"
}

/**
 * Имя тому, что Point только что произвёл сам: «Запись, 4 авг 19:25», «Снимок, 4 авг 19:25».
 *
 * Содержимое здесь ещё никто не читал — звук не расшифрован, кадр не распознан, — поэтому имя
 * говорит единственную известную правду: что это и когда появилось. Время абсолютное: имя даётся
 * один раз и остаётся с объектом навсегда (см. [stampLabel]).
 */
fun stampedObjectName(
    what: String,
    epochMillis: Long,
    zone: java.time.ZoneId = java.time.ZoneId.systemDefault(),
): String = "$what, ${stampLabel(epochMillis, zone)}"

/** Управляющие знаки и то, что ломает имя файла. Двоеточие среди них: имя уезжает в «Загрузки». */
private val UNSAFE = Regex("""[\p{Cntrl}/\\:*?"<>|]""")

private val SPACES = Regex("""\s+""")

/** Хвостовая пунктуация: «Пришлите договор,» — не имя, а обрывок фразы. */
private val TRAILING = charArrayOf(' ', ',', '.', ';', '!', '?', '-', '–', '—', '…')
