package com.point.core.flow

fun interface DropLink {

    suspend fun give(path: String, fileName: String, mime: String): DropOutcome
}

/**
 * Чем кончилась попытка выдать ссылку (#1284).
 *
 * Прежде здесь был `String?`, и пять разных причин — нет сети, нет аккаунта, файла нет на
 * диске, файл больше предела, сервер ответил отказом — приходили одним и тем же `null`.
 * Настоящая причина терялась на границе, и человек читал перечисление догадок: «нет связи с
 * сервером или файл слишком большой» — при живом интернете, живом аккаунте и файле в 880 раз
 * меньше предела.
 *
 * Отказ рождается там, где известна правда: тот же приём, что в #1311 у сетевого отказа.
 */
sealed interface DropOutcome {

    /** Ссылка выдана. */
    data class Given(val link: String) : DropOutcome

    /**
     * Ссылки не будет, и вот почему — ровно одна названная причина, а не список.
     *
     * Слова человеку, а не код: их читает он, и он же по ним решает, что делать дальше.
     */
    data class Refused(val why: String) : DropOutcome
}

/** Сколько весит файл — словами человека, для отказа и для обещания. */
fun megabytes(bytes: Long): String = "${(bytes + 1024 * 1024 - 1) / (1024 * 1024)} МБ"

/**
 * Файл тяжелее предела — предел назван числом (#1284).
 *
 * Число называется и до отправки: человек видит его в обещании действия, а не узнаёт после
 * того, как пятьдесят пять мегабайт уже уехали на сервер.
 */
fun tooHeavyForLink(bytes: Long): String =
    "Файл ${megabytes(bytes)} — ссылкой отдаётся до ${megabytes(MAX_DROP_BYTES)}"

/** Сервер Point не принял файл и сказал, почему. */
fun serverRefusedDrop(reason: String): String =
    if (reason.isBlank()) "Сервер Point не принял файл" else "Сервер Point не принял файл: $reason"

/** Файла, за которым пришли, на устройстве больше нет. */
const val NO_FILE_FOR_LINK = "Файла больше нет на этом устройстве"
