package com.point.core.flow

fun interface DropLink {

    suspend fun give(path: String, fileName: String, mime: String): String?

    /**
     * Может ли это устройство выдавать ссылки вообще (#1022).
     *
     * Телефон без аккаунта предлагал «Дать ссылку», спрашивал согласие выложить файл в
     * интернет, получал «Выложить» — и отвечал «нет связи с сервером или файл слишком
     * большой». Обе догадки были неверны: связь была, файл — в 880 раз меньше предела.
     *
     * Согласие на выход объекта наружу спрашивают только там, где выход возможен. Компьютер
     * это уже делал правильно: у него действие сразу помечено недоступным с настоящей
     * причиной.
     */
    fun canGive(): Boolean = true
}

/** Почему выдать ссылку нельзя — одними словами на оба устройства (#1022). */
const val NOT_SIGNED_IN_TO_GIVE_LINKS = "это устройство не вошло в аккаунт"
