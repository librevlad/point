package com.point.core.flow

/**
 * Отдать файл ссылкой (#388, минимальный вид).
 *
 * Самая маленькая форма того, ради чего задумывался Drop: человеку, у которого Point не стоит,
 * достаётся ссылка — он открывает её и получает файл. Ни аккаунтов, ни страниц, ни своего
 * сервера: релей уже умеет хранить байты и удалять их по времени.
 *
 * **Цена названа вслух.** Всё остальное, что возит релей (объекты между устройствами, буфер),
 * запечатано ключом пары устройств. У ссылки для чужого человека такого ключа нет, поэтому файл
 * лежит на сервере открытым — ровно сутки, пока не истечёт. Кто нажимает «Дать ссылку», тот это
 * принимает; поэтому действие называется прямо, а не «поделиться».
 */
fun interface DropLink {
    /**
     * Положить файл и вернуть ссылку на него; `null` — не получилось (нет релея, нет сети).
     *
     * Молчание здесь не отличается от отказа намеренно: человеку в обоих случаях нужно одно и то
     * же — узнать, что ссылки не будет.
     */
    suspend fun give(path: String, fileName: String, mime: String): String?
}
