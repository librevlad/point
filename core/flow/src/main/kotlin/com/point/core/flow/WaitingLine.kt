package com.point.core.flow

/**
 * Сколько идёт работа — одними словами на телефоне и компьютере (#901).
 *
 * Телефон говорил «Идёт 12 с», а после тридцати секунд честно добавлял «долгое ожидание,
 * можно отменить». Компьютер в том же месте говорил «12 секунд» и про затянувшееся ожидание
 * молчал вовсе: человек не знал, ждать ему или отменять.
 *
 * Про то, ЧЕМ занят Point, говорит стадия — она приходит от самого действия. Эта строка
 * знает только, сетевая ли работа, и выводить из этого «модель читает документ» нельзя
 * (#810): так однажды объяснялась отправка файла на собственный компьютер, где никакой
 * модели нет.
 */
fun waitingLine(elapsed: Int, network: Boolean, cancelable: Boolean = true): String = when {
    !network -> if (elapsed < 3) "Обрабатываю…" else "Идёт $elapsed с"
    elapsed < LONG_WAIT_S -> "Идёт $elapsed с"
    cancelable -> "Идёт $elapsed с · долгое ожидание, можно отменить"
    else -> "Идёт $elapsed с · долгое ожидание"
}

/** С какой секунды ожидание считается долгим и об этом говорят вслух. */
const val LONG_WAIT_S = 30

/**
 * Сколько работа имеет право молчать, прежде чем покажет себя человеку (#1128).
 *
 * Тяжесть — свойство прогона, а не имени действия. «Скан» и «Сжать» объявлены быстрыми и на
 * снимке с телефона идут доли секунды, но на большом снимке или на занятом устройстве — минуты;
 * «Убрать фон» на живом телефоне отвечает за секунды, а там, где модель сегментации
 * разворачивается минутами, ожидание тянулось без счёта секунд и без «Отменить». Поэтому список
 * тяжёлых способностей всегда неполон: право на тишину даётся всякой местной работе одинаково и
 * кончается по времени — дальше работа говорит, сколько уже идёт, и даёт себя отменить, тем же
 * экраном ожидания, что у облачных (решение владельца 20.08.2026).
 *
 * Срок отмерян тем, сколько человек согласен смотреть на неподвижное. В сборке, на которой
 * написана карточка, два знака тихой работы в коде уже были заведены: список действий гас
 * вполовину и переставал нажиматься, а назвавшая себя работа писала строку стадии. В живом
 * прогоне на медленном устройстве до человека не дошёл ни один — запись прогона (AND-068 в
 * `docs/audits/live-review-967-coverage.md`, та же сборка и тот же эмулятор) говорит, что тап
 * не дал ни строки состояния, ни счётчика, ни отмены, и через две, четыре и пять минут экран
 * был тот же. Почему знаки не дошли — не выяснено. Поэтому раздвигать срок доводом «объект и
 * так показывает занятость» нельзя: в живом прогоне этого не видели. Стережёт это не само
 * число, а проверка живой секундой (`FlowViewModelTest`).
 */
const val QUIET_GRACE_S = 2
