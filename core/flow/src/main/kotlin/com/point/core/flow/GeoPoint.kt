package com.point.core.flow

import com.point.core.model.Provenance

/**
 * Координаты точки — второе чтение поля «куда ехать» (#262).
 *
 * Маршрут строится не только по адресу: в корпусе владельца кадр «точка по координатам» — это
 * пара чисел и больше ничего, адреса у неё нет и не будет. Писать такую пару в `entity.address`
 * нельзя: адрес и координаты — не два чтения одного значения, а два разных значения, и
 * [mergeFacts] объявил бы между ними ложный спор на первом же скриншоте карты, где есть и то и
 * другое. Поэтому у координат свой ключ, а схема «Построить маршрут» читает **требование**
 * «куда», закрываемое любым из двух ([FieldSpec.insteadOf]).
 *
 * **Форма — десятичные градусы с точкой.** Пара чисел с [MIN_FRACTION]+ знаками после точки в
 * границах глобуса. Запятая как десятичный разделитель сознательно не поддержана: «50,4501,
 * 30,5234» неразличимо с парой «50,4501» и «30,5234» — правило, которое гадает, врёт дважды.
 * Градусы-минуты-секунды (`50°27'0"N`) тоже не здесь: OCR ломает знак градуса непредсказуемо,
 * а у модели («Понять», контрактный ключ `GEO`) с этой формой проблем нет — ровно тот же довод,
 * которым #260 отдал модели номера отправлений.
 *
 * Правило **размечает, а не решает**: улика ровно одна ([EvidenceClass.SEMANTIC]), и пока второй
 * независимый класс не найден, значение видно как предположение.
 *
 * Ключ читает схема «Построить маршрут» ([ACTION_SCHEMAS]) и пишет «Понять» (контрактный ключ
 * `GEO`). Координаты — единственное **якорное** поле маршрута: пара чисел на странице ничем,
 * кроме точки, куда едут, не бывает, тогда как адрес есть и на чеке, и в подписи письма (#262).
 *
 * Действия по этому факту сегодня нет: `MapCapability` («Открыть на карте») зажигается по
 * `Feature.HAS_ADDRESS` и ведёт `geo:0,0?q=<адрес>`. Факт заводится раньше пузырька сознательно —
 * метрика #262 меряет **прочитанное**, и «координаты со страницы сняты» обязано быть измеримо
 * до того, как появится тот, кто по ним поедет.
 */
const val META_ENTITY_GEO = META_ENTITY_PREFIX + "geo"

/** Меньше — это цена или количество: «12.500 45.300» в накладной от точки на карте по форме
 *  неотличимо, а карты пишут 4–7 знаков. Точность здесь дороже полноты: правило пишет ФАКТ. */
private const val MIN_FRACTION = 4

/**
 * Пары координат в [text] в порядке появления, без повторов. Значение — `широта, долгота`:
 * цифры дословно со страницы, канонизирован только разделитель (он формат, а не суть, — тот же
 * приём, что склейка пробелов у [waybillNumbers]).
 */
fun geoPoints(text: String): List<String> =
    GEO_SHAPED.findAll(text)
        .mapNotNull { m ->
            val lat = m.groupValues[1].toDoubleOrNull() ?: return@mapNotNull null
            val lon = m.groupValues[2].toDoubleOrNull() ?: return@mapNotNull null
            // За пределами глобуса чисел не бывает: пара, вылезшая за широту/долготу, —
            // просто два числа, стоявшие рядом.
            if (kotlin.math.abs(lat) > MAX_LAT || kotlin.math.abs(lon) > MAX_LON) return@mapNotNull null
            "${m.groupValues[1]}, ${m.groupValues[2]}"
        }
        .distinct()
        .toList()

/** Координаты как факты объекта: значение, происхождение и улика формы; несколько точек на
 *  странице — все в `entity.geo.more` (конвенция `.more`: вторая точка не исчезает, #260). */
fun geoFacts(text: String): Map<String, String> {
    val points = geoPoints(text)
    val first = points.firstOrNull() ?: return emptyMap()
    return buildMap {
        put(META_ENTITY_GEO, first)
        put(META_ENTITY_GEO + META_SOURCE_SUFFIX, Provenance.OCR.wire)
        put(META_ENTITY_GEO + META_EVIDENCE_SUFFIX, EvidenceClass.SEMANTIC.name.lowercase())
        if (points.size > 1) put(META_ENTITY_GEO + META_MORE_SUFFIX, altValue(points))
    }
}

private const val MAX_LAT = 90.0
private const val MAX_LON = 180.0

/**
 * Широта (до двух целых) и долгота (до трёх), разделённые запятой, точкой с запятой или
 * пробелом; с обеих сторон пары — не цифра и не точка, иначе это кусок числа подлиннее.
 *
 * Разделитель **обязателен**: без него длинное «50.450130.5234» разваливалось бы регексом на
 * законную с виду пару — форма, которой на странице не было.
 */
private val GEO_SHAPED = Regex(
    """(?<![\d.,])([-+]?\d{1,2}\.\d{$MIN_FRACTION,8})(?:\s*[,;]\s*|\s+)([-+]?\d{1,3}\.\d{$MIN_FRACTION,8})(?![\d.])""",
)

/**
 * Место назначения — **то, куда человек едет, когда адреса на экране нет** (#262).
 *
 * Замер корпуса: на скрине карты Новой Почты в прочитанном есть «Нова Пошта» и «ддлення N21»,
 * на скрине маршрута — «Новониколаевка, Запорожская о…». Адресом извлекатель это не считает и
 * прав: улицы с домом там нет. Но «куда» — есть, и человек именно за этим и пришёл.
 *
 * Формы у места назначения нет, как нет её у идентификатора (design v3 §5), поэтому правило
 * сюда не пишет **никогда**: значение приходит только от модели, ключом PLACE, и получает
 * происхождение «прочитано моделью». Гадать по словарю топонимов мы не будем — словарь врёт
 * ровно там, где название нестандартное.
 */
const val META_ENTITY_PLACE = META_ENTITY_PREFIX + "place"
