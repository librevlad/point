package com.point.core.flow

/**
 * Годится ли значение этому виду знания — по форме, а не по источнику.
 *
 * Одно место на все входы: и на то, что модель нашла впервые, и на то, что она же потом
 * исправила (#666). Правило, живущее в двух копиях, расходится на первой же правке.
 *
 * Правила намеренно бедные и односторонние: они умеют сказать «это точно не оно» и молчат
 * там, где жизнь богаче правила (координаты, показания счётчика). Молчание — «пропустить».
 *
 * Мерка о двух половинах (#1032). Форма самого значения ([factFormFits]) — её видно по
 * значению и больше ни по чему. Заземление ([groundsOnPage]) — то, что видно только по
 * прочитанной странице: у накладной это слово-подпись рядом с числом. [readText] — всё, что
 * Point прочитал сам; пусто — сверять не с чем, и накладной остаётся только форма перевозчика.
 * Половины разделены не ради красоты: находка спрашивает обе, а правка уже заведённого знания
 * может спросить не всякую (см. [fixFits]).
 */
fun factFits(key: String, value: String, readText: String = ""): Boolean =
    factFormFits(key, value) && groundsOnPage(key, value.trim(), readText)

/**
 * Годится ли исправленное прочтение уже заведённого знания (#666, #1032).
 *
 * Мерка та же. Разница в том, что правка не заводит знание, а меняет прочтение заведённого:
 * заземлять исправленное число нечем — его на странице нет и быть не может, в этом весь смысл
 * пути. Заземление наследуется от прочтения, которое правка заменяет: если страница держит
 * прежнее прочтение этого же знания со всем, что делает его накладной, — исправленное встаёт
 * на его место, и остаётся спросить форму. [readings] — прежние прочтения: текущее значение и
 * след «или», куда прошлая правка положила то, что было (`applyFixes`).
 *
 * Иначе гасло молча: отброшенная правка не просто не ложилась — человеку отвечали «Ошибок не
 * нашлось», приговором знанию, которое как раз чинили. Живой путь: фото накладной Укрпошты, OCR
 * прочёл «Експрес-накладна № 8806923102858», человек жмёт «Исправить ошибки» — правка …859
 * ложится, но сидекар остаётся прежним. Обе двери на экране, он жмёт «Исправить сильнее», где
 * модель видит сам снимок и возвращает верное …851, — гейт искал …851 на странице с …858, не
 * находил и выбрасывал правку, а «Отследить отправление» продолжало уходить по неверному
 * номеру. То же и там, где число стоит на странице не теми пробелами, что в значении:
 * заземление ищется по странице целиком, а не дословным совпадением. Правку, которую гейт
 * всё-таки отверг, [parseFixes] больше не съедает молча: она уходит в [FixedFacts.missed].
 *
 * Наследуется ровно то, что страница дала **месту**: слово-подпись рядом с числом верно для
 * любого его прочтения. Форма перевозчика месту не принадлежит — она свойство самого числа,
 * и другому числу не передаётся: 14 цифр, стоящие на странице без слова рядом, не делают
 * накладной исправленные 13, как не сделали бы находкой. А там, где слово рядом стоит, чинится
 * и само число: OCR склеивает лишнюю цифру на длинном прогоне, 13-значная накладная Укрпошты
 * читается как 14-значная — и «Исправить сильнее» обязана вернуть верные 13.
 */
fun fixFits(key: String, readings: List<String>, fixed: String, readText: String): Boolean =
    factFits(key, fixed, readText) || (factFormFits(key, fixed) && pageGrounds(key, readings, readText))

/**
 * Форма значения — половина мерки, которую видно по нему одному.
 *
 * Отказ-фразы, огрехи чтения, чужие виды: 13 цифр не станут суммой, IBAN — накладной, слово со
 * смешанными алфавитами — организацией. Этой половиной судится и находка, и правка.
 */
private fun factFormFits(key: String, value: String): Boolean {
    val text = value.trim()
    if (text.isEmpty()) return false

    // Отказ-фраза — не значение ни для какого поля (#656).
    if (startsWithRefusal(text)) return false

    // Слово со смешанными алфавитами — огрех чтения, не значение (#1032).
    if (garbledWord(key, text)) return false

    // Форму спрашивают у всех видов знания одинаково (#657, решение владельца): гейт один,
    // а не по списку избранных полей. Прогон 2026-08-09: номер карты вставал телефоном,
    // «квитанцію» — трек-номером, товарная строка — адресом; правило существовало, но не
    // для всех.
    //
    // `semanticFits` отвечает `null` там, где жизнь богаче правила, и это по-прежнему значит
    // «пропустить»: гейт отсекает только явно чужое, а не всё незнакомое.
    if (semanticFits(key, text) == false) return false

    return when (key.removePrefix(META_ENTITY_PREFIX)) {

        // Относительное слово и голое время — не дата (#659, #651); дата без цифр — тоже.
        "date" -> !relativeDayWord(text) && !bareClock(text)

        // Форма IBAN — не трек: «UA79…» с квитанции становился готовым отслеживанием.
        // Слово — тем более: «квитанцію» и «№ 7 36ір» с кадров прогона вставали трек-номерами
        // и получали готовое «отследить» на пустом месте (#657).
        "track" -> !looksLikeIban(text)

        "address" -> plausibleAddress(text)

        else -> true
    }
}

/**
 * Заземление — половина мерки, которую видно только по прочитанной странице.
 *
 * Накладная — по форме перевозчика или по слову рядом, одной меркой с правилом-читателем
 * (#1032, решение владельца): 13 цифр без того и другого — номер без роли, а не трек.
 */
private fun groundsOnPage(key: String, text: String, readText: String): Boolean =
    when (key.removePrefix(META_ENTITY_PREFIX)) {
        "track" -> looksLikeTrack(text, readText)
        else -> true
    }

/**
 * Дала ли страница заземление хоть одному из прежних прочтений — тому, что правка заменяет.
 *
 * Наследуется ровно то, что страница даёт **месту**: слово-подпись рядом с числом верно для
 * любого прочтения этого места, и исправленное встаёт на него. Форма перевозчика месту не
 * принадлежит — она свойство самого числа, и поделиться ею с другим числом нельзя: 14 цифр,
 * стоящие на странице без слова рядом, накладной исправленные 13 не делают, как не сделали
 * бы находкой.
 */
private fun pageGrounds(key: String, readings: List<String>, readText: String): Boolean =
    when (key.removePrefix(META_ENTITY_PREFIX)) {
        "track" -> readings.any { it.isNotBlank() && markedTrackOnPage(it, readText) }
        else -> false
    }

/**
 * Слово, в котором смешаны алфавиты, — огрех чтения, а не значение (#1032, решение владельца:
 * правило общее для всех словесных значений, не только для ролей).
 *
 * Роль, имя и адрес судились им по отдельности, а место и тема — нет: «РÉPUBLIOUEFRANCAISE»
 * с кириллическими Р и О внутри латинского слова проходило у одних и гасло у других.
 * Ссылка и почта — не слова: в них алфавиты смешиваются по праву (кириллический путь,
 * интернациональный домен), и это не огрех чтения.
 */
fun garbledWord(key: String, value: String): Boolean =
    key.removePrefix(META_ENTITY_PREFIX) !in MIXED_SCRIPT_LAWFUL && hasMixedScriptWord(value)

private val MIXED_SCRIPT_LAWFUL = setOf("url", "email")
