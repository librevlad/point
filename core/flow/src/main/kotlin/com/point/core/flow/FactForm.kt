package com.point.core.flow

/**
 * Годится ли значение этому виду знания — по форме, а не по источнику.
 *
 * Одно место на все входы: и на то, что модель нашла впервые, и на то, что она же потом
 * исправила (#666). Правило, живущее в двух копиях, расходится на первой же правке.
 *
 * Правила намеренно бедные и односторонние: они умеют сказать «это точно не оно» и молчат
 * там, где жизнь богаче правила (координаты, показания счётчика). Молчание — «пропустить».
 *
 * [readText] — всё, что Point прочитал сам (#1032): по нему видно, стоит ли у числа
 * слово-подпись накладной. Пусто — сверять не с чем, и накладной остаётся только форма
 * перевозчика.
 */
fun factFits(key: String, value: String, readText: String = ""): Boolean {
    val text = value.trim()
    if (text.isEmpty()) return false

    // Отказ-фраза — не значение ни для какого поля (#656).
    if (startsWithRefusal(text)) return false

    // Слово со смешанными алфавитами — огрех чтения, не значение (#1032).
    if (garbledWord(key, text)) return false

    // Форму спрашивают у всех видов знания одинаково (#657, решение владельца): гейт один,
    // а не по списку избранных полей. Прогон 2026-08-09: номер карты вставал телефоном,
    // «квитанцію» — трек-номером, товарная строка — адресом; правило существовало, но не
    // для всех.
    //
    // `semanticFits` отвечает `null` там, где жизнь богаче правила, и это по-прежнему значит
    // «пропустить»: гейт отсекает только явно чужое, а не всё незнакомое.
    if (semanticFits(key, text) == false) return false

    return when (key.removePrefix(META_ENTITY_PREFIX)) {

        // Относительное слово и голое время — не дата (#659, #651); дата без цифр — тоже.
        "date" -> !relativeDayWord(text) && !bareClock(text)

        // Форма IBAN — не трек: «UA79…» с квитанции становился готовым отслеживанием.
        // Слово — тем более: «квитанцію» и «№ 7 36ір» с кадров прогона вставали трек-номерами
        // и получали готовое «отследить» на пустом месте (#657). Накладная — по форме
        // перевозчика или по слову рядом, одной меркой с правилом-читателем (#1032): 13 цифр
        // без того и другого — номер без роли, а не трек.
        "track" -> !looksLikeIban(text) && looksLikeTrack(text, readText)

        "address" -> plausibleAddress(text)

        else -> true
    }
}

/**
 * Слово, в котором смешаны алфавиты, — огрех чтения, а не значение (#1032, решение владельца:
 * правило общее для всех словесных значений, не только для ролей).
 *
 * Роль, имя и адрес судились им по отдельности, а место и тема — нет: «РÉPUBLIOUEFRANCAISE»
 * с кириллическими Р и О внутри латинского слова проходило у одних и гасло у других.
 * Ссылка и почта — не слова: в них алфавиты смешиваются по праву (кириллический путь,
 * интернациональный домен), и это не огрех чтения.
 */
fun garbledWord(key: String, value: String): Boolean =
    key.removePrefix(META_ENTITY_PREFIX) !in MIXED_SCRIPT_LAWFUL && hasMixedScriptWord(value)

private val MIXED_SCRIPT_LAWFUL = setOf("url", "email")
