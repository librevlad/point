package com.point.core.flow

import com.point.core.model.ObjectState

/**
 * Чем и где выполнить намерение — решение момента запуска (ADR-0001, «ExecutionPolicy»).
 *
 * ADR назвал этот шов и оставил его нулём:
 *
 * > цена — свойство запуска… и живёт она там, где делается выбор исполнителя, то есть у `Resolver`.
 *
 * Довод ADR был про деньги: один и тот же OCR бывает офлайновым на одном устройстве и облачным на
 * другом, поэтому цену объявляет не реализация, а её запуск. Контракт от 06.08.2026
 * (`docs/DESKTOP-CONTRACT.md`, И3) добавил к тому же шву вторую работу — **выбор исполнителя**,
 * и это тот же вопрос: «чем именно выполнить вот это вот здесь и сейчас».
 *
 * **Глобального закона нет.** Никакого архитектурного `LOCAL > CLOUD > REMOTE`: порядок задают
 * сами реализации через [RealizerMeta.priority], а `kind` остаётся признаком, а не приговором.
 * Прежде порядок был зашит вторым ключом сортировки — то есть философией, объявленной от имени
 * всех будущих реализаций сразу. Эвристики допустимы; законом они не становятся.
 *
 * Отбор — две половины одного вопроса «есть ли чем выполнить»: [Realizer.isAvailable] про
 * устройство (пак, ключ, сеть), [Realizer.accepts] про сам объект.
 */
fun interface ExecutionPolicy {

    /**
     * Кандидаты в порядке предпочтения; пустой список — выполнить нечем.
     *
     * Список, а не один: несколько подходящих складываются в цепочку с запасным путём
     * (`FallbackRealizer`), и это то же самое решение — «чем выполнить», просто с продолжением.
     */
    fun choose(state: ObjectState, candidates: List<Realizer>): List<Realizer>
}

/**
 * Умолчание: берём то, что может и берётся, в объявленном самими реализациями порядке.
 *
 * Ровно то, что делал `Resolver` до появления шва, **минус** зашитый закон про `kind`. Отдельным
 * классом, а не лямбдой в резолвере, потому что правило одно на обе поверхности: телефон и
 * компьютер обязаны выбирать одинаково, иначе одно и то же намерение поведёт себя по-разному, и
 * виноватым окажется человек.
 */
class DefaultExecutionPolicy : ExecutionPolicy {
    override fun choose(state: ObjectState, candidates: List<Realizer>): List<Realizer> =
        candidates
            .filter { it.isAvailable() && it.accepts(state) }
            // При равных приоритетах порядок всё равно обязан быть определённым: реализации
            // приходят множеством, и его обход ничем не закреплён — цепочка чтения строилась бы
            // сегодня так, а завтра иначе, и поймать это было бы нечем. Вторым ключом — имя
            // класса: оно ни о чём не говорит и потому ничего не утверждает. Прежде здесь стоял
            // `kind`, и это была философия («локальный раньше облачного»), объявленная от имени
            // всех будущих реализаций сразу; равенство приоритетов — повод их развести числом,
            // а не повод решать за них.
            .sortedWith(compareBy({ it.meta.priority }, { it::class.java.name }))
}
