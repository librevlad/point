package com.point.core.flow

/**
 * Запрос-ответ поверх ящиков сервера (#161): общий язык для телефона и компьютера.
 *
 * Ящик умеет только «положить», «забрать» и «подтвердить». Поэтому вопрос и ответ — два письма в
 * ящики двух устройств, а не одно соединение.
 *
 * Ящик у устройства **один** (`/mbx/{device_id}`), и разделять каналы адресом больше нечем: вид
 * письма едет в его мете ([KIND]), и тот, кто разбирает почту, по нему решает, кому письмо отдать.
 * Раньше каналов было три и они держались врозь тремя выдуманными адресами; с переходом на ящики
 * аккаунта адрес стал именем устройства, а не именем канала (#475).
 *
 * Живёт в `:core:flow`, потому что обе стороны обязаны понимать протокол одинаково — иначе
 * телефон и ПК разойдутся в мелочах и канал будет «работать через раз».
 */
object RelayRpc {

    /** Вид запроса — едет в мете кадра. */
    const val KIND = "rpc.kind"

    /** Идентификатор запроса: по нему свой ответ отличается от чужого. */
    const val ID = "rpc.id"

    /** Ответ на запрос (в мете ответа стоит тот же [ID]). */
    const val REPLY = "rpc.reply"

    /**
     * Сам объект: байты и понимание о нём.
     *
     * Объект едет тем же запросом-ответом, что и всё остальное, — и это не единообразие ради
     * красоты. Пока отправка была письмом без ответа, «положил в ящик» выдавалось за «доехало»:
     * выключенный компьютер и работающий выглядели для человека одинаково (#524). Ответ и есть
     * разница между «он не запущен» и «сделано».
     */
    const val OBJECT = "object"

    /** Положить в буфер компьютера то, что скопировано на телефоне. */
    const val CLIP_PUSH = "clip-push"

    /** Спросить, что сейчас в буфере компьютера. */
    const val CLIP_PULL = "clip-pull"

    /** Что умеет компьютер: печать, сборка PDF, открыть, копировать. */
    const val CAPS = "caps"

    /** Что компьютер приготовил телефону (очередь «на телефон»). */
    const val OUTBOX = "outbox"

    /** Забрать один объект из очереди. */
    const val FETCH = "fetch"

    /** Подтвердить, что объект забран. */
    const val ACK = "ack"

    /** Телефон рассказывает компьютеру, что умеет сам. */
    const val PHONE_CAPS = "phone-caps"
}

/**
 * Наш ли это ответ.
 *
 * Три случая, и каждый выбран не на вкус:
 * - **свой** `reqId` — ответ принимается;
 * - **чужой** — протухший ответ другому запросу, пропускается (иначе канал начнёт врать: урок
 *   #272, где любой первый блоб принимался за ответ);
 * - **отсутствующий** — компьютер старой сборки, который про `reqId` ещё не знает. Принимается
 *   намеренно: иначе «новый телефон + старый ПК» брикует связь навсегда, а гарантия от протухших
 *   деградирует до дренажа — как было раньше, не хуже.
 */
fun isOurReply(replyMeta: Map<String, String>, requestId: String): Boolean {
    if (replyMeta[RelayRpc.KIND] != RelayRpc.REPLY) return false
    val answered = replyMeta[RelayRpc.ID] ?: return true
    return answered == requestId
}
