package com.point.core.flow

import com.point.core.model.Bubble
import com.point.core.model.CapabilityId

/**
 * Схема принадлежит **действию**, а не типу документа (#260, design v3 §5–6).
 *
 * Тип документа как корневой роутер — ошибка, названная тремя архитекторами консилиума
 * независимо: входы гибридные (фото посылки с чеком, скрин переписки со вложенным треком),
 * одна метка заставляет систему саму отрезать половину информации, а «заполнено 6 из 9»
 * становится красивой ложью — документ не понят, его насильно засунули в чужой контракт.
 *
 * Поэтому здесь нет «схемы накладной». Есть схема действия «Отследить отправление», и полнота
 * считается по нему: у действия есть **критические** поля, без которых оно не работает, и
 * побочные, которые весят почти ноль («имя отправителя» для отслеживания). Готовность бинарна —
 * действие готово или нет; число заполненных полей не сообщается вовсе, потому что это метрика,
 * которую легко накрутить и невозможно честно истолковать.
 *
 * Схема **не запускает** ничего сама: первый экран (≤300 мс) показывает возможные действия,
 * заполнение начинается после явного тапа (`Object → Intent → Capability`), а эта модель лишь
 * говорит, чего не хватает, — строкой «не хватает только X», а не формой из девяти полей.
 */
data class ActionSchema(
    /** Устойчивый идентификатор схемы — для тестов, журнала и будущего маппинга на capability. */
    val id: String,
    /** Название действия человеку: «Отследить отправление». */
    val label: String,
    val fields: List<FieldSpec>,
    /**
     * Возможность, которой готовая строка запускается тапом (#464), — или `null`, если запускать
     * пока нечем.
     *
     * Решение владельца 04.08.2026: **строка = действие**. До него карточка называла глагол
     * («Отследить отправление»), ставила галочку, показывала найденное значение — и не давала
     * тапнуть; кликабельным было только НЕготовое (раскрыть, чего не хватает). Обратная связь
     * была ровно противоположна ожиданию.
     *
     * Здесь стоит **декларация**, а не реализация: схема называет `CapabilityId`, поведение
     * живёт в своём `Realizer` за `Resolver`'ом, а UI получает колбэк ([runner]) — инвариант
     * «Capability ≠ Realizer» держится. Идентификатор написан строкой сознательно: `:core:flow`
     * не знает `:executors` (стрелка идёт вниз, не вверх), а от опечатки и от переименования
     * защищает тест в `:executors`, где видно обе стороны.
     *
     * `null` — честнее выдуманного действия: строка остаётся справкой о готовности, и это
     * названо в PR/`DECISIONS.md` хвостом со своим issue, а не замазано похожей возможностью.
     */
    val runs: CapabilityId? = null,
)

/**
 * Поле схемы: какой факт объекта действие читает и обязано ли оно им обладать.
 *
 * [key] — ключ метаданных объекта (`entity.track`, `graph.role.carrier`): схема читает те же
 * факты, что пишут энричеры и «Понять», а не заводит собственный мир значений.
 */
data class FieldSpec(
    val key: String,
    /** Название поля человеку, именительный падеж: «трек-номер». */
    val label: String,
    /** Критическое: без него действие не работает. Некритическое отсутствие готовности не рушит. */
    val critical: Boolean = false,
    /**
     * Якорное: наличие этого поля означает, что документ **про это действие**. Дата и адрес
     * есть почти на каждом скриншоте (таймстемп переписки — тоже `entity.date`, #244), и
     * гейт видимости по «хоть одному полю» звал «Отследить отправление» на любой чат
     * (ревью #260). Про посылку говорят трек и перевозчик — универсальные поля читаются
     * схемой, но карточку не зовут.
     */
    val anchor: Boolean = critical,
    /**
     * Ключ поля, **то же требование** которого закрывает это поле (#262).
     *
     * «Куда ехать» читается адресом ИЛИ координатами: это одно требование действия с двумя
     * законными чтениями, а не два поля. Без этого маршрут по координатам считался бы неготовым
     * («не хватает адреса»), хотя ехать по нему можно, — метрика #262 занижала бы себя на ровном
     * месте, а карточка требовала бы от человека дописать то, что уже есть.
     *
     * Замена — только между **критическими** полями и только внутри одной схемы: побочные поля
     * друг друга не заменяют, потому что ничего и не требуют. Пусто — поле само по себе.
     */
    val insteadOf: String? = null,
)

/**
 * Требование, которое закрывает поле: у замены — ключ заменяемого, у остальных — собственный.
 * Одно требование — одна строка «не хватает», сколькими бы фактами оно ни читалось.
 */
private val FieldSpec.requirement: String get() = insteadOf ?: key

/**
 * Готовность действия по фактам объекта: бинарная, по критическим полям.
 *
 * [Missing.missing] — только критические: «не хватает только X» обязано называть то, без чего
 * действие не работает, а не всё незаполненное — иначе это та же форма из девяти полей.
 */
sealed interface Readiness {
    data class Ready(val present: List<FieldReading>) : Readiness
    data class Missing(val missing: List<FieldSpec>, val present: List<FieldReading>) : Readiness
}

/**
 * Прочитанное поле: значение и альтернативные чтения, если источники разошлись
 * (`<key>.alt`, [alternativesOf]). Спор не прячется за готовностью: действие может быть
 * готово по спорному значению, и человек обязан видеть, что оно спорное.
 */
data class FieldReading(
    val spec: FieldSpec,
    val value: String,
    val alternatives: List<String> = emptyList(),
    /**
     * Предположение (#261, design v3 §4): улики считались (`<key>.ev`) и независимых классов
     * меньше [CONFIRMED_CLASSES] — «одно доказательство — предположение, и оно видно как
     * предположение». Улики не считались вовсе (ключа нет) — поле не судили, и врать про него
     * маркером нельзя ни в одну сторону.
     *
     * Считается общим [isAssumption] (#264): то же самое слово «возможно» стоит под найденным
     * объектом, и две реализации одного суда разъехались бы на первой правке.
     */
    val assumption: Boolean = false,
    /**
     * То, что человек, скорее всего, передаст, — показание без ведущих нулей барабана
     * (`00001154` → `1154`, #262). **Производная, а не факт:** [value] остаётся дословным
     * и на экране, и в метаданных, подсказка его не подменяет нигде и ни на минуту.
     *
     * Выводится в момент чтения ([fieldHint]) и потому не может разъехаться со значением —
     * почему не ключ метаданных, разобрано там же. `null` — подсказывать нечего.
     */
    val hint: String? = null,
)

/** Готовность одной схемы по фактам объекта. Чистая функция — UI и тесты зовут её напрямую. */
fun ActionSchema.readiness(facts: Map<String, String>): Readiness {
    val present = fields.mapNotNull { spec ->
        facts[spec.key]?.takeIf { it.isNotBlank() }?.let { value ->
            // Спор о чтении (.alt) и другие значения того же типа на странице (.more) для
            // человека — один вопрос: «а не то ли это?» — и показываются одной строкой «или:».
            val readings = (alternativesOf(facts, spec.key) + moreOf(facts, spec.key))
                .distinct().filter { it != value }
            FieldReading(
                spec, value, readings,
                assumption = isAssumption(facts, spec.key),
                hint = fieldHint(spec.key, value),
            )
        }
    }
    // Считаются закрытые ТРЕБОВАНИЯ, а не прочитанные ключи: координаты закрывают то же «куда»,
    // что и адрес, и требовать оба значило бы объявить готовое действие неготовым (#262).
    val satisfied = present.map { it.spec.requirement }.toSet()
    val missingCritical = fields.filter { it.critical && it.requirement !in satisfied }
        .groupBy { it.requirement }
        .map { (_, specs) ->
            // Одно требование — одна строка, и она называет **все** его чтения: «не хватает
            // только: адрес или координаты». Подпись собирается из подписей полей, чтобы фраза
            // не жила вторым списком, разъезжающимся с первым на первой правке.
            specs.first().let { primary ->
                // «адрес, координаты или место» — перечисление через запятую и «или» перед
                // последним: три чтения через два «или» читались бы как три отдельных нехватки.
                if (specs.size == 1) {
                    primary
                } else {
                    val labels = specs.map { it.label }
                    primary.copy(label = labels.dropLast(1).joinToString(", ") + " или " + labels.last())
                }
            }
        }
    return if (missingCritical.isEmpty()) {
        Readiness.Ready(present)
    } else {
        Readiness.Missing(missingCritical, present)
    }
}

/** Схема и её готовность — строка секции готовности на экране объекта. */
data class ActionReadiness(val schema: ActionSchema, val readiness: Readiness)

/**
 * Чем строка запускается тапом (#464): пузырь того же действия из числа предложенных объекту —
 * либо `null`, и тогда строка не притворяется кнопкой.
 *
 * Три условия, и каждое закрывает свой способ соврать:
 * - **действие готово** — по неготовому тапать нечего, там тап по-прежнему раскрывает «чего не
 *   хватает»;
 * - **у схемы объявлено, что запускать** ([ActionSchema.runs]) — иначе глагол есть, а действия
 *   за ним нет: ровно та находка, из которой вырос #464;
 * - **это действие объекту реально предложено** — источник правды один, реестр возможностей.
 *   Поэтому «Построить маршрут», готовый по одним координатам, кнопкой НЕ станет: `MapRealizer`
 *   ищет адрес on-device, признака `HAS_ADDRESS` у объекта нет, пузыря нет — и строка честно
 *   молчит вместо «Адрес не найден» после тапа.
 *
 * Пузырь — тот же самый, что в списке действий ниже: тап по строке идёт тем же путём
 * (`Object → Intent → Capability → Realizer → Object`), никакой второй дороги исполнения нет.
 * И цепочку это не строит: один тап — одно действие, дальше человек снова выбирает.
 */
fun ActionReadiness.runner(bubbles: List<Bubble>): Bubble? {
    if (readiness !is Readiness.Ready) return null
    val id = schema.runs ?: return null
    return bubbles.firstOrNull { it.capabilityId == id }
}

/**
 * Значение, которое строка готовности **печатает** рядом с глаголом, — или `null`, если не печатает
 * ничего (#464, #564).
 *
 * Правило одно и живёт здесь одно: у готового действия это первое присутствующее критическое поле —
 * то самое, ради чего действие готово. Неготовая строка не печатает значения вовсе: там на месте
 * значения стоит «не хватает только X».
 *
 * Вынуто из `ReadinessSection` ровно затем, зачем [maskedForScreen] вынута из двух экранов: по этому
 * же правилу теперь решается, что **не** повторять ниже (#564), и две копии одного правила
 * разъехались бы молча — карточка печатала бы одно, а список найденного прятал другое.
 */
fun ActionReadiness.shownField(): FieldReading? =
    (readiness as? Readiness.Ready)?.present?.firstOrNull { it.spec.critical }

/**
 * Что карточка готовности уже сказала человеку: ключ факта → его значение (#564).
 *
 * **Один факт — одно место.** Живой снимок визитки владельца показывал один и тот же номер дважды:
 * «✓ Сохранить контакт · +380 67 …» в карточке готовности и «+380 67 … · Телефон» в списке
 * найденного. Чтобы выбрать между ними, человеку надо знать разницу между фактом, найденным
 * объектом и способностью, — то есть нашу внутреннюю механику.
 *
 * Побеждает карточка готовности: она **и** называет значение, **и** делает с ним то, что на ней
 * написано, одним тапом. Строка в «Нашёл» — только дверь на свой экран, и ни одной возможности за
 * этой дверью человек не теряет: признак (`HAS_PHONE`, `HAS_ADDRESS`) остаётся на самом документе,
 * поэтому «Позвонить» и «Открыть на карте» стоят в списке действий тут же, на том же экране.
 *
 * Ключ нужен «Point понял» (там факт узнают по имени: `entity.phone` → строка «Нашёл телефон»),
 * значение — списку найденного (там узел и есть своё значение). Сравнивать значения честнее, чем
 * типы: второй телефон на странице — другой факт, и прятать его не за что.
 */
fun readinessShownFacts(
    facts: Map<String, String>,
    schemas: List<ActionSchema> = ACTION_SCHEMAS,
): Map<String, String> = buildMap {
    actionReadiness(facts, schemas).forEach { row ->
        row.shownField()?.let { field -> put(field.spec.key, field.value) }
    }
}

/**
 * Готовность известных действий по фактам объекта — только тех, к которым документ имеет
 * отношение: схема видна, когда прочитано хотя бы одно её **якорное** поле ([FieldSpec.anchor]).
 * Пустой документ не получает список «не хватает всего», а чат с таймстемпом «18:24» — карточку
 * про посылку (ревью #260): универсальное поле схему не зовёт, оно только читается ею.
 */
fun actionReadiness(
    facts: Map<String, String>,
    schemas: List<ActionSchema> = ACTION_SCHEMAS,
): List<ActionReadiness> = schemas.mapNotNull { schema ->
    val readiness = schema.readiness(facts)
    val present = when (readiness) {
        is Readiness.Ready -> readiness.present
        is Readiness.Missing -> readiness.present
    }
    if (present.any { it.spec.anchor }) ActionReadiness(schema, readiness) else null
}

/**
 * Действия со схемой — и правило, по которому схема сюда попадает.
 *
 * **Схема заводится вместе с фактом, которым она считается.** «Построить маршрут» и «Передать
 * показание счётчика» (#262) пришли не одни: маршрут принёс [META_ENTITY_GEO], счётчик —
 * [META_ENTITY_METER], оба с офлайновым правилом формы и контрактным ключом модели. Тем же
 * порядком пришли три следующие: «Перевести по реквизитам» принесла [META_ENTITY_AMOUNT],
 * «Переслать квитанцию» — [META_ENTITY_RECEIPT], «Ответить» — [META_ENTITY_SUBJECT].
 *
 * **Кого сюда по-прежнему не пускают и почему.** Список не короче списка принятых, и он важнее:
 * - **«Извлечь позиции»** — честного факта «в документе есть таблица» у объекта не бывает, а
 *   схема, чью готовность нечем посчитать, лгала бы в обе стороны. Таблицы поэтому меряются по
 *   **результату** действия ([scoreTable]), а не по готовности полей.
 * - **«Собрать список в текст»** (карточка списка покупок в чужом приложении, кадр 16) — та же
 *   порода и тот же отказ. Признак «в документе есть список» — не свойство документа, а наша
 *   догадка о нём: галочки OCR не читает вовсе, а «много коротких строк» есть и у меню, и у
 *   оглавления. Мерить это нужно результатом — тем самым текстом, который человек забрал.
 *   Пересмотр кадра глазами (#262, третий заход) добавил к отказу два довода, и оба сильнее
 *   первого. **Готовность списка не бинарна:** у него нет одного значения, которое либо
 *   прочитано, либо нет, — тринадцать пунктов из четырнадцати схема объявила бы готовыми, а
 *   человек получил бы список без хлеба. **Якорь пришлось бы поставить на «нашли список»** — и
 *   он зовёт себя на дереве файлов кадра 21, на оглавлении, на меню и на любом чате: схема,
 *   которая ловит всё подряд, хуже отсутствующей, потому что накручивает метрику пустой
 *   готовностью.
 * - **«Найти и забрать нужный отчёт»** (дерево файлов на чужом экране, кадр 21) — здесь нет не
 *   факта, а самого действия: **какой отчёт нужен, знает человек**, на странице этого нет ни в
 *   каком виде. Схема, объявляющая кадр готовым за то, что мы прочитали хоть одно имя файла,
 *   меряла бы наше чтение и называла бы это выполненным действием. Кадр глазами это
 *   подтверждает: дерево называет отчёты, которые **существуют** (период, неделя, диапазон дат),
 *   а подсвеченная строка — то место, где стоит курсор человека, а не утверждение документа. И
 *   даже готовая схема солгала бы дважды: сам файл лежит на **чужом** компьютере, объект в Point
 *   — фотография монитора, и пути от снимка к файлу нет.
 *
 * Оба отказа названы поимённо ровно затем, зачем `unscored` называет кадры: молчаливое сужение
 * корпуса до удобных кадров — тот же грех, что «заполнено 6 из 9». Причина едет и в машинной
 * карте кадров (`tools/corpus/frames.tsv`, третье поле → [OutOfCount]), чтобы отчёт прогона не
 * обещал человеку работу, которую решили не делать.
 *
 * **С #464 у каждой схемы есть ещё одна графа: чем она запускается** ([ActionSchema.runs]).
 * Заполнена она у трёх из семи, и пустые три названы там же, при схеме, с причиной — потому что
 * пустая графа здесь означает строку, которая говорит человеку глагол и не даёт его сделать.
 * Список причин («выбрать чужой сервис», «войти в личный кабинет», «это деньги», «переслать не
 * квитанцию») — такой же именной отказ, как два выше, и живёт по тому же правилу: молчание об
 * этом дороже некрасивой правды.
 */
val ACTION_SCHEMAS: List<ActionSchema> = listOf(
    ActionSchema(
        id = "track-parcel",
        label = "Отследить отправление",
        // Запускать нечем (#464, хвост → #481). Отслеживание — это открыть страницу ПЕРЕВОЗЧИКА,
        // то есть выбрать чужой сервис и отправить туда номер посылки владельца. Это продуктовое
        // и приватное решение, а не проводка колбэка, и делать его молча здесь было бы ровно тем
        // сортом выдумки, из-за которого строка и оказалась мёртвой.
        runs = null,
        fields = listOf(
            FieldSpec(META_ENTITY_TRACK, "трек-номер", critical = true),
            // Перевозчик — якорь: роль «carrier» на странице значит «это про отправление».
            FieldSpec(META_GRAPH_ROLE_PREFIX + "carrier", "перевозчик", anchor = true),
            // Дата — универсал (таймстемп чата — тоже дата, #244): читается, но не зовёт.
            FieldSpec(META_ENTITY_PREFIX + "date", "дата"),
        ),
    ),
