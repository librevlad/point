     * когда он за ссылкой. Без любого из них Point перешлёт снимок банковского экрана вместо
     * квитанции, а получатель попросит настоящую — то есть действие без правок не выполнено.
     *
     * **Якорь — номер, а не ссылка.** Ссылка есть на каждом втором скриншоте (в подписи письма, в
     * шапке браузера, в сообщении), и якорь на ней звал бы «Переслать квитанцию» на чём попало.
     * Номер стоит рядом со словом «квитанція» — это уже утверждение документа о самом себе.
     *
     * **Названная цена:** кадр 08 (ссылка без номера) измерим, но карточку не покажет. Та же
     * цена и тот же довод, что у адреса в маршруте; метрики это не касается вовсе.
     */
    ActionSchema(
        id = "forward-receipt",
        label = "Переслать квитанцию",
        fields = listOf(
            FieldSpec(META_ENTITY_RECEIPT, "номер квитанции", critical = true),
            FieldSpec(
                META_ENTITY_PREFIX + "url", "ссылка на квитанцию",
                critical = true, insteadOf = META_ENTITY_RECEIPT, anchor = false,
            ),
            // Побочные: сумма и дата говорят, что именно переслали, но пересылке не мешают.
            FieldSpec(META_ENTITY_AMOUNT, "сумма"),
            FieldSpec(META_ENTITY_PREFIX + "date", "дата"),
        ),
    ),
    /*
     * «Ответить» (#262): 2 кадра из 23 — входящее сообщение клиента в поддержку и фото монитора с
     * письмом клиента. Оба — просьба, на которую человек пришёл ответить.
     *
     * **Критическое поле одно: адрес.** Текст, на который отвечают, — это сам объект, отдельным
     * фактом он не бывает; а вот кому уйдёт ответ, решает адрес почты, и без него ответ не
     * отправить. Черновик ответа полем схемы не является сознательно: это результат действия, а
     * не факт документа, и мерить им готовность значило бы мерить работу модели.
     *
     * **Якорь — тема, а не адрес** ([META_ENTITY_SUBJECT]): адрес почты стоит в подписи счёта, на
     * визитке и в шапке накладной, а тема бывает только у письма. Цена названа там же: письмо без
     * темы карточку не покажет, но измеримость от этого не меняется — [scoreCorpus] считает
     * [readiness], где якоря нет.
     */
    ActionSchema(
        id = "reply",
        label = "Ответить",
        fields = listOf(
            FieldSpec(META_ENTITY_PREFIX + "email", "адрес почты", critical = true, anchor = false),
            FieldSpec(META_ENTITY_SUBJECT, "тема", anchor = true),
            // Побочные: отправитель — кому мы отвечаем по имени, дата — универсал (#244).
            FieldSpec(META_GRAPH_ROLE_PREFIX + "sender", "отправитель"),
            FieldSpec(META_ENTITY_PREFIX + "date", "дата"),
        ),
    ),
)
