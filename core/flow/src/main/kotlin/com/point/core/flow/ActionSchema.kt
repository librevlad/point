/**
 * Что кладётся в буфер по тапу строки, которую запустить нечем (#481).
 *
 * Решение владельца 04.08.2026: «на что нет обработчиков — по тапу в буфер». Четыре схемы из семи
 * запускать нечем не по забывчивости, а потому что за ними нет честного действия: у показания
 * счётчика нет кабинета поставщика, у перевода по реквизитам — денег, которыми Point не
 * распоряжается. Но найденное значение человеку нужно — он всё равно понесёт его в чужое
 * приложение руками.
 *
 * Поэтому тап отдаёт **значение**, а не обещание действия: один найденный факт — сам факт без
 * подписи (номер посылки удобно вставить как есть), несколько — по строке «поле: значение», чтобы
 * реквизиты не слиплись в кашу. Пусто — копировать нечего, и строка молчит.
 */
fun copyableValue(readiness: Readiness): String? {
    val present = when (readiness) {
        is Readiness.Ready -> readiness.present
        is Readiness.Missing -> readiness.present
    }.filter { it.value.isNotBlank() }
    return when {
        present.isEmpty() -> null
        present.size == 1 -> present.single().value
        else -> present.joinToString("\n") { "${it.spec.label}: ${it.value}" }
    }
}
