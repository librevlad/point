package com.point.core.flow.capabilities

import com.point.core.flow.Capability
import com.point.core.flow.CapabilityMeta
import com.point.core.flow.Cost
import com.point.core.flow.Latency
import com.point.core.model.ActionYield
import com.point.core.model.CapabilityId
import com.point.core.model.ObjectKind
import com.point.core.model.ObjectState

/**
 * «Распознать текст» — намерение, а не устройство.
 *
 * Первая способность, переехавшая в общий словарь по контракту от 06.08.2026
 * (`docs/DESKTOP-CONTRACT.md`, инвариант И1: **`Capability` никогда не принадлежит устройству**).
 *
 * До переезда одно и то же намерение было объявлено дважды: телефоном как `ocr` («Распознать
 * текст») и компьютером как `pc-ocr` («Прочитать в облаке»). Из-за этого компьютер объявлял
 * телефону чтение снимка чужим сервисом — рядом с телефонным, локальным и бесплатным. Владелец
 * назвал это абсурдом, и он прав: спорили не реализации, спорили две декларации одного намерения.
 *
 * Теперь декларация одна, а **реализаций** несколько, и они честно разные:
 *
 * | где | чем | цена |
 * |---|---|---|
 * | телефон | Tesseract на устройстве | бесплатно, офлайн, любой размер |
 * | телефон | зрячая модель по цепочке | по тапу, наружу |
 * | компьютер | чужой сервис чтения | по тапу, наружу, до 1 МБ |
 *
 * Что из этого выбрать — работа `Resolver`, а не человека и не этой декларации.
 *
 * Декларация намеренно **ничего не знает о железе**: ни `@Inject`, ни зависимостей. Ядро не имеет
 * сторонних зависимостей и не получит их ради переезда — Hilt связывает эту способность через
 * `@Provides @IntoSet`, а компьютер собирает вручную.
 */
class OcrCapability : Capability {
    override val id = ID
    override val icon = "ocr"

    /**
     * Ключей и сети не нужно — с обычным случаем справляется устройство. Но **не быстро**, и
     * [Latency.FAST] здесь было прямой неправдой (#288): у чтения страницы бюджет в три минуты
     * (`OCR_READ_BUDGET_MS`), внутри которого помещается до четырёх полных проходов движка.
     *
     * Цена этой неправды была не косметическая. Работа, объявленная нескорой, идёт на экране
     * ожидания — там видно, что действие делает сейчас, и там же живёт кнопка отмены; работа,
     * объявленная быстрой, остаётся на объекте притушенным списком, без единого слова и **без
     * возможности передумать**. То есть самое долгое действие Point было единственным, которое
     * нельзя было ни понять, ни остановить, — ровно то, на что пожаловался владелец.
     *
     * Первый экран это не трогает: место пузырька считается по [Latency.INSTANT] против «всего
     * остального», и FAST с SLOW стоят по одну сторону.
     */
    override val meta = CapabilityMeta(cost = Cost.FREE, latency = Latency.SLOW)

    override fun label(state: ObjectState) = "Распознать текст"
    override fun accepts(state: ObjectState) = state.kind == ObjectKind.IMAGE
    override fun produces(state: ObjectState) = ObjectState(ObjectKind.TEXT)

    /**
     * Запасной путь назван до тапа, а не после (#558).
     *
     * Прогон по телефону владельца: подпись обещала просто «вернёт текст», человек тапал — и
     * первым, что он видел, был вопрос про отправку снимка в сервис. Цена появлялась ПОСЛЕ выбора,
     * то есть выбор делался вслепую.
     *
     * Формулировка условная, а не приговор, и она верна на обеих поверхностях: на телефоне цепочка
     * начинает с устройства и наружу уходит только не взятое им; на компьютере устройство не умеет
     * читать вовсе, и «не выйдет на устройстве» там — просто всегда.
     *
     * Объявление `meta.network` при этом НЕ меняется: `network` красит пузырёк на первом экране и
     * двигает его в другой ярус (#114), а действие правда начинает на устройстве. Правда о цепочке
     * живёт в `Resolver.leavesDevice` — здесь она сказана словами, единственным местом, которое
     * человек читает.
     */
    override fun yields(state: ObjectState) =
        ActionYield.New(ObjectKind.TEXT, "текст · не выйдет на устройстве — предложит сервис")

    companion object { val ID = CapabilityId("ocr") }
}
