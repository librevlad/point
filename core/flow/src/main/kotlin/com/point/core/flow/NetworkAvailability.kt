package com.point.core.flow

/**
 * Спросить у телефона, есть ли рабочая сеть, — перед тем как Point выйдет наружу
 * (#690, #691). Отрицательный ответ обязан быть фактом системы (Android
 * `NetworkCapabilities.NET_CAPABILITY_VALIDATED`), а не догадкой по одной неудачной
 * попытке: слабая, но живая связь — это работа, а не отказ. Реализация — за DI в
 * `:data` (см. `AndroidNetworkAvailability`), этот модуль об Android не знает.
 */
fun interface NetworkAvailability {
    fun isAvailable(): Boolean
}

/**
 * Слова человеку, когда сети действительно нет, — телефон подтвердил это сам.
 *
 * Одна константа на все пред-проверки (#1237): у чтения снаружи, у цепочки моделей и у связи
 * с компьютером было по своей фразе, и человек читал про одну и ту же выключенную сеть три
 * разных истории.
 *
 * Утверждение сильное, поэтому и место у него узкое: так говорит только тот, кто спросил
 * [NetworkAvailability] и получил «нет». Догадка по чужой строке — «timed out», «Connection
 * reset» — этого не доказывает: медленный сервис при живом интернете назвал бы человеку
 * ложную причину и ложный шаг. Для догадки есть своё слово — [CONNECTION_LOST_TEXT].
 */
const val NO_NETWORK_TEXT = "На телефоне нет интернета. Подключитесь и попробуйте ещё раз."

/**
 * Связь оборвалась по дороге — то, что видно по чужому отказу, и не больше (#1237).
 *
 * Сводка отказов знает лишь, что до сервисов не достучались: сеть могла выключиться, а мог
 * молчать и сам сервис. Про телефон здесь не утверждается ничего, а шаг назван тот, который
 * помогает в обоих случаях.
 */
const val CONNECTION_LOST_TEXT = "Связь с сервисом оборвалась — проверьте интернет и попробуйте ещё раз"

/**
 * Слово человеку про его положение, а не про устройство продукта (#569).
 *
 * Живёт здесь, а не у списка действий: то же самое положение бывает и у источника объекта
 * (#759), и описывать его на двух экранах по-разному — значит рассказывать человеку две
 * разные истории про одну выключенную сеть.
 */
const val NO_INTERNET_NOTE = "нет интернета"
