package com.point.core.model

/**
 * Что вернётся, если нажать (#491).
 *
 * Формула продукта — `Object → Intent → Capability → Realizer → Object`, и до этого среза
 * последнее звено человеку никто не называл: на экране стояло только имя действия. «Распознать
 * текст» вернёт текст, «В Excel» вернёт таблицу, «Поделиться» не вернёт ничего — всё это было
 * объявлено в коде и не сказано ни разу.
 *
 * **Почему отдельный тип, а не `produces`.** `produces` отвечает «каким станет состояние», и на
 * два разных ответа у него одно значение: терминальное действие возвращает `state`, и действие,
 * которое **обогащает тот же объект** («Понять» дописывает факты и отдаёт его же), возвращает
 * тоже `state`. По одному `produces` их не различить — а человеку это ровно та разница, ради
 * которой он и смотрит на строку.
 *
 * **Это ожидание, а не обещание.** Инвариант проекта: истинное состояние переклассифицируется
 * из реального выхода. Значит [New] — то, что действие объявляет о себе; если вышло иначе, Point
 * обязан сказать об этом словами (`yieldSurprise` в `:core:flow` сверяет объявленное с настоящим
 * видом после выполнения), а не молчать.
 */
sealed interface ActionYield {

    /** Нового объекта не будет: отправит, откроет, скопирует, покажет. */
    data object None : ActionYield

    /** Тот же объект — но Point узнает о нём больше («Понять»). */
    data object Same : ActionYield

    /**
     * Новый объект вида [kind].
     *
     * [noun] — уточнение там, где вид слишком широк: `OFFICE` это и документ Word, и таблица
     * Excel, а человеку нужно знать, что именно. Пусто — говорим словом самого вида.
     */
    data class New(val kind: ObjectKind, val noun: String? = null) : ActionYield

    /** Заранее неизвестно: зависит от того, что человек попросит (AI). */
    data object Unknown : ActionYield
}
