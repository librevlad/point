package com.point.core.model

/**
 * Происхождение значения — **вместо** одного числа «насколько уверены» (#264, поправка 1 к ADR-0001).
 *
 * `confidence: Float` был суррогатом с самого начала. Дословный прецедент: на карточке посылки
 * трек `20 4514 9154 9395`, найденный офлайновым правилом **дословно на странице**, получал 0.8;
 * название перевозчика «Нова Пошта», которое модель назвала сама, — 0.7; спорный адрес — 0.5.
 * Три разных числа, три несравнимые шкалы (self-assessed probability, а не измеренная точность —
 * практика Textract / Google DI / Azure DI), и **одна и та же подпись на экране**: «возможно».
 * Число не отвечало на вопрос, который человек на самом деле задаёт, — **кто это утверждает**.
 *
 * Point не принимает решение «верить или нет»: он хранит происхождение и показывает его.
 *
 * **Порядок объявления = сила.** `enum` сравним из коробки, поэтому правило «происхождение не
 * понижается» (ревью #261) пишется как `новое > старое`: подтверждение моделью значения,
 * прочитанного правилом со страницы, не делает его диктовкой, а правка человека не переписывается
 * прилетевшим позже ответом модели (#243).
 *
 * **Почему `enum`, а не `sealed class Provenance(source, evidence, alternatives)` из текста ADR.**
 * Два из трёх полей той структуры уже реализованы и протестированы своими контрактами: улики —
 * `EvidenceClass` + `<key>.ev`, альтернативы — `<key>.alt` / `<key>.more`. Склеить их в одну
 * структуру значило бы завести **третий** источник истины о том же самом. У происхождения
 * собственной полезной нагрузки нет — это ровно одно слово, и оно уже ездит в журнале как
 * `<key>.src`. Отклонение от буквы ADR в пользу его смысла зафиксировано в `docs/DECISIONS.md`.
 */
enum class Provenance(
    /** Слово, которым происхождение живёт в метаданных (`<key>.src`) и переживает журнал. */
    val wire: String,
) {
    /**
     * Объект дал человек: файл из Share, снимок, вставленный текст. Его **никто не читал** —
     * подписывать нечего, и это самое слабое состояние, а не «плохое».
     *
     * Не путать с [HUMAN]: там человек **правил прочитанное**, здесь он просто принёс исходник.
     */
    GIVEN("given"),

    /** ПРОЧИТАНО МОДЕЛЬЮ: диктовка без указания на страницу — проверить против слов нечем. */
    MODEL("model"),

    /**
     * ВЫВЕДЕНО: значение **вычислено** правилом, а не прочитано (курс, сумма, разложенный
     * словарём код). Слот словаря — писателя в этом срезе ещё нет: неполный словарь происхождения
     * заставил бы следующего автора выдумать своё слово.
     *
     * Сюда **не** относится итог расчёта со страницы (`arithmeticTotals`, #262): его правило
     * сверило, а не вычислило, и на странице он напечатан дословно — поэтому у него [OCR].
     * (Прежде здесь стояла ссылка на `EvidenceClass.ARITHMETIC` как на такой же пустой слот;
     * у того класса писателей уже два — контрольная цифра S10 и этот расчёт.)
     */
    RULE("rule"),

    /** ПРОЧИТАНО: дословно со страницы — правило нашло в распознанном тексте либо модель указала
     *  метками, а текст собрали атомы. Модель в этом случае цифру изменить не может по построению. */
    OCR("ocr"),

    /** ПОДТВЕРЖДЕНО ЧЕЛОВЕКОМ: правка человека. Сильнее всех — её не переписывает никакая модель (#243). */
    HUMAN("human"),
}

/**
 * Происхождение по слову из метаданных. Незнакомое слово и `null` — [Provenance.GIVEN]: «не знаем,
 * кто это читал» и «никто не читал» — одно и то же состояние, и оно обязано быть слабейшим.
 * Легаси-журнал без `.src` поэтому не врёт, а молчит.
 */
fun provenanceOf(wire: String?): Provenance =
    Provenance.entries.firstOrNull { it.wire == wire } ?: Provenance.GIVEN
