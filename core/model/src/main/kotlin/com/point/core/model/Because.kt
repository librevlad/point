package com.point.core.model

/**
 * Что из найденного в вещи сделало действие возможным.
 *
 * «Позвонить» продолжает найденный номер, «Открыть на карте» — адрес, «Создать событие» —
 * срок. Действие, у которого такой причины нет, продолжает саму вещь: сохранить, отправить,
 * открыть. Эта разница — не порядок и не вид функции, а то, *о чём* действие.
 *
 * [key] — ключ знания, по которому действия одного значения узнают друг друга; [name] — как
 * это значение называется человеку («Телефон»); [value] — само значение так, как его видно
 * на экране, или `null`, когда у найденного нет значения, которое стоит повторять (код на
 * кадре, чьё содержимое уже лежит ссылкой).
 */
data class Because(
    val key: String,
    val name: String,
    val value: String? = null,
)
