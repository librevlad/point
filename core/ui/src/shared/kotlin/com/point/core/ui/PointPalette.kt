package com.point.core.ui

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/**
 * Палитра Point — одна на телефон и ПК (#851).
 *
 * До этого те же десять цветов были набраны литералами дважды: в `theme/PointTheme.kt`
 * внутри `darkColorScheme(...)` и в `desktop/ui/PointDesktopTheme.kt` в `object PointColors`.
 * В шапке десктопного файла было написано, откуда они взяты, — но приписка не мешает
 * поменять оттенок поверхности на телефоне и забыть про ПК, и ни один тест не покраснеет.
 * Ровно та же дыра, что была у значков до #849.
 *
 * Каталог `src/shared/kotlin` компилируют обе стороны, каждая своим Compose, поэтому здесь
 * можно держать не описание палитры, а саму палитру.
 *
 * Цвета — стекла поверх тёплой сливовой земли (макет владельца «Point · концепт в стиле
 * Gestalt», 19.10.2026; телефон — решение владельца 20.10.2026). Прежняя почти чёрная земля,
 * яркий фиолетовый и плоские тёмные карточки ушли с обоих устройств разом: макет рисует
 * телефон и компьютер одним языком — мягкий контраст, стекло, приглушённый фиолетовый Point
 * вместо терракоты Gestalt.
 */
object PointPalette {

    /** Земля под стеклом: фон экрана телефона и того, что видно сквозь окно ПК. */
    val canvas = Color(0xFF2B2531)

    /** Стекло окна ПК, сведённое на землю в один цвет, — там, где сквозь него ничего не видно. */
    val window = Color(0xFF26212C)

    /** Плотная тёмная поверхность: меню, поле ввода, диалог. */
    val surfaceDeep = Color(0xFF282230)

    val text = Color(0xFFEDE7EA)

    /** Цвет самого Point — приглушённый фиолетовый. */
    val violet = Color(0xFFB6A3E3)

    /** Фиолетовый для слова-ссылки на тёмном стекле: светлее, чтобы читался. */
    val link = Color(0xFFCBBEEE)

    /** Компьютер; ссылка как вид объекта. */
    val blue = Color(0xFF8FB4E8)

    /** Найденное значение; текст как вид объекта. */
    val cyan = Color(0xFF8BC9D6)

    val pink = Color(0xFFE39DB9)

    val orange = Color(0xFFE3A27C)

    /** Телефон рядом и на связи. */
    val green = Color(0xFF86CBA6)

    val yellow = Color(0xFFE0CC8B)

    /** Единственный тёплый тон: «закрыть», «отключить», сорвавшийся шаг. */
    val warm = Color(0xFFD98B63)

    /**
     * Выделение поверх снимка и страницы: найденное слово, обведённая область. Насыщенный
     * фиолетовый Point — на белой бумаге пастель стекла не видна.
     */
    val highlight = Color(0xFF8B6CFF)

    /** Тёплое слово на тёмном стекле — светлее самого тона, чтобы читалось: «Отключить», «Убрать». */
    val warmText = Color(0xFFEFBE9F)

    /** Тёмный текст на светлой главной строке — цвет самой земли. */
    val ink = canvas

    /** Светлая главная строка: верх и низ её мягкого градиента. */
    val lightTop = Color(0xF7F1ECF4)
    val lightBottom = Color(0xEBE5DEED)

    /** Панель на стекле: группа строк, блок содержимого. */
    val surface = Color.White.copy(alpha = 0.055f)

    /** Кромка стекла. */
    val border = Color.White.copy(alpha = 0.12f)

    /** Тонкая линия между строками и частями окна. */
    val hairline = Color.White.copy(alpha = 0.08f)

    /** Вторая строка о самом объекте: вид, откуда пришёл, когда. */
    val soft = text.copy(alpha = 0.74f)

    /** Подпись, обещание действия, счётчик. */
    val muted = text.copy(alpha = 0.58f)

    /** Самое тихое: время в строке, моно-строка файла. */
    val faint = text.copy(alpha = 0.48f)
}

/** Скругление строки стекла — у строки действия, объекта в списке и настройки. */
val PortalCardShape = RoundedCornerShape(20.dp)

/** Скругление плашки, которая не круг: QR, кнопка отправки, вложенный блок. */
val PortalPlateShape = RoundedCornerShape(14.dp)
