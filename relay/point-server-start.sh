#!/bin/sh
# Поднять сервер аккаунтов, если он ещё не слушает.
#
# Скрипт лежит в репозитории, а не только на сервере: его отсутствие здесь и стоило приёма
# файла. `python-multipart` был объявлен в requirements.txt, но на сервере никто не
# переустанавливал зависимости — и приём отвечал 500 на каждую загрузку, пока `/health`
# показывал 200 (найдено 2026-08-10). Теперь установка — часть запуска, а не отдельная
# память человека.
#
# «Уже запущен?» решается по СЛУШАТЕЛЮ ПОРТА, а не по имени процесса: прежняя проверка по
# pgrep ловила сам сторож (урок релея 03.08.2026).
cd "$HOME/point-server" || exit 1
ss -ltn 2>/dev/null | grep -q "127.0.0.1:8080" && exit 0

# Зависимости доводятся до объявленных на каждом запуске. Идемпотентно и занимает секунды,
# когда ставить нечего; зато объявленное и установленное больше не расходятся молча.
./.venv/bin/pip install -q -r requirements.txt || exit 1

set -a
. ./point-server.env
set +a
exec ./.venv/bin/python -m uvicorn point_server.main:app --host 127.0.0.1 --port 8080 >> server.log 2>&1
