package com.point.data

/**
 * Как Point представляется чужому серверу.
 *
 * Заголовка не было вовсе, и `HttpURLConnection` подставлял своё умолчание (`Dalvik/…` на телефоне,
 * `Java/…` на JVM). Двух бесплатных поставщиков это стоило нам целиком: Groq и Cerebras отвечали
 * отказом 403 **только** из-за этого — замер зрячих моделей 04.08.2026 (`docs/VISION-MODELS.md`)
 * поймал их живыми, стоило запросу назвать себя. То есть «мёртвый провайдер» был не мёртв, а
 * неузнан, и платил за это человек своим временем.
 *
 * Представляемся честно — именем приложения и версией, а не подделкой под браузер: цель заголовка
 * здесь — быть узнанным, а не притвориться кем-то. Обход блокировок маскировкой был бы обещанием,
 * которое мы не сможем держать при следующей их правке.
 */
const val POINT_USER_AGENT = "Point/0.2 (Android)"

/**
 * Заголовки одного исходящего запроса: наш паспорт, потом заголовки транспорта, потом заголовки
 * вызывающего.
 *
 * Порядок значащий и потому проверяется тестом: **вызывающий выигрывает**. Клиент, которому нужен
 * свой `Content-Type` или своё представление, обязан суметь их поставить — иначе общий паспорт
 * превратился бы в потолок вместо умолчания.
 *
 * Функция чистая, и это единственный способ проверить заголовки без сети: сама отправка
 * (`setRequestProperty` в цикле) — тонкая обвязка, у неё проверять нечего.
 */
internal fun pointHeaders(own: Map<String, String>, caller: Map<String, String>): Map<String, String> =
    mapOf("User-Agent" to POINT_USER_AGENT) + own + caller
