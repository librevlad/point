package com.point

/**
 * Пример-объект (#210): что именно Point кладёт во флоу по строке «Посмотреть на примере».
 *
 * Три поля — ровно то, что нужно обычной двери [FlowViewModel.onShared]: откуда взять байты, чем
 * они являются и как это называется человеку. Больше у примера нет ничего: ни своего состояния,
 * ни своих действий, ни своего экрана.
 */
data class ExampleObject(val uri: String, val mime: String, val name: String)

/**
 * Как пример называется в «Недавнем» и в шапке объекта.
 *
 * Слово «пример» стоит в имени, а не в подписи под ним: имя объекта человек увидит и через день,
 * когда о том, откуда взялась чужая визитка, он уже не вспомнит. Выдавать её за принесённую им
 * значило бы соврать один раз и надолго.
 */
internal const val EXAMPLE_OBJECT_NAME = "Визитка · пример"

/**
 * Пример живёт ресурсом приложения и открывается ссылкой на него, а не копией в кэше.
 *
 * `android.resource://` — обычный источник для `ContentResolver`, то есть тот же путь, которым в
 * Point входит расшаренный файл: рабочую копию сделает `ObjectStore.ingest`, и она же уедет в
 * `clear()` в конце флоу. Своего копирования здесь нет намеренно — второй способ приносить байты
 * означал бы второе место, где можно забыть про уборку.
 *
 * Сеть, ключ и разрешения на этом пути не встречаются ни разу: байты лежат в APK, чтение картинки
 * идёт Tesseract'ом с диска (`rus`/`eng` тоже в APK). Человек, поставивший Point минуту назад,
 * доходит до понятого текста, не согласившись ни на что.
 *
 * [resId] параметром, а не константой внутри: подстановка ресурса — единственное, что мешает
 * судить эту строку обычным JVM-тестом, а адрес примера — как раз то, что стоит проверить.
 */
internal fun exampleObject(packageName: String, resId: Int = R.raw.example_card): ExampleObject =
    ExampleObject(
        uri = "android.resource://$packageName/$resId",
        // Снимок, а не PNG-скриншот: пример обязан быть тем, что человек приносит чаще всего, —
        // фотографией бумаги. JPEG к тому же лежит в APK несжатым, и `openInputStream` отдаёт
        // его без оговорок.
        mime = "image/jpeg",
        name = EXAMPLE_OBJECT_NAME,
    )
