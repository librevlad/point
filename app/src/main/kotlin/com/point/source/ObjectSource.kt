package com.point.source

import android.content.Context
import android.content.Intent

/**
 * Источник объекта — дверь из шторки (#246).
 *
 * Живёт в `:app`, а не в core: источники по природе завязаны на Android (камера, буфер, диктофон),
 * и тащить это в Android-free модули нельзя. Регистрируется через Hilt `@IntoSet`, как Capability:
 * добавить источник = добавить класс, экран выбора вырастает сам.
 *
 * Шторка только создаёт объект и никогда его не обрабатывает — это требование #246 дословно.
 */
interface ObjectSource {
    /** Устойчивый идентификатор: по нему экран выбора помнит, кого запускали. */
    val id: String

    /** Как источник называется человеку. */
    val label: String

    /**
     * Ключ иконки из того же словаря, которым подписаны действия (`bubbleIcon`/`bubbleColor`).
     *
     * Экран выбора рисует источник строкой дизайн-системы — той же, что действие на экране
     * объекта, — а у строки есть иконная плита. Умолчание держит обещание «добавить источник =
     * добавить класс»: новый источник появится на экране и без своей иконки.
     */
    val icon: String get() = "open-in"

    /** Есть ли чем добывать: нет системной камеры — плашки не показываем вовсе. */
    fun isAvailable(context: Context): Boolean

    /**
     * Runtime-разрешения, без которых источник не работает.
     *
     * Пусто у всех, кроме места: Point не просит у человека ничего, пока без этого действительно
     * нельзя обойтись, и спрашивает только по тапу — то есть тогда, когда человек сам попросил.
     */
    val permissions: List<String> get() = emptyList()

    /**
     * Чужая активити, если нужна; `null` — источник добывает сам (буфер).
     *
     * `suspend`, потому что заготовка файла — работа с диском: камере нужно, куда писать.
     */
    suspend fun request(context: Context): Intent?

    /** Что получилось. [data] — результат чужой активити, `null` для источников без неё. */
    suspend fun read(context: Context, data: Intent?): Produced?

    /**
     * Что источник обязан помнить между «запросили» и «вернулись», одной строкой (#454).
     *
     * Экран выбора прозрачный и лёгкий, а стоит он за камерой — самым тяжёлым приложением
     * телефона. Прижало по памяти — выгружают первым его, и всё, что источник держал обычным
     * полем, к возвращению уже мертво: у камеры это путь к файлу, куда пишется кадр. Строка
     * уходит в `Bundle` экрана и возвращается сюда же при пересоздании.
     *
     * Умолчание — `null`: источнику, которому нечего помнить (буфер, голос, место), дописывать
     * ничего не нужно.
     */
    fun saveState(): String? = null

    /** Вернуть то, что [saveState] сохранил до выгрузки; `null` — сохранять было нечего (#454). */
    fun restoreState(state: String?) = Unit
}
