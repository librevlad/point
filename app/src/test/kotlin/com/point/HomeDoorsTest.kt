package com.point

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/**
 * Подпись двери «Новый объект» (#456).
 *
 * Дверь одна, а источников за ней пять — и если их не назвать, «камера, голос, буфер, место»
 * останутся догадкой, просто на один тап ближе. Имена берутся у самих источников, поэтому здесь
 * судится только сборка строки: что перечислено, что пусто и что делать с мусором.
 */
class HomeDoorsTest {

    @Test fun `подпись перечисляет источники поимённо`() {
        assertEquals(
            "Буфер обмена · Голос · Камера",
            sourcesSubtitle(listOf("Буфер обмена", "Голос", "Камера")),
        )
    }

    @Test fun `без источников подписи нет вовсе`() {
        // Пустой набор — законное состояние (`@Multibinds`): рассказывать не о чем, и выдумывать
        // «источники недоступны» тоже незачем — дверь просто стоит без подписи.
        assertNull(sourcesSubtitle(emptyList()))
    }

    @Test fun `источник без имени не оставляет дырки в перечислении`() {
        assertEquals("Камера · Место", sourcesSubtitle(listOf("Камера", "  ", "Место")))
        assertNull(sourcesSubtitle(listOf("", " ")))
    }
}
