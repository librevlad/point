package com.point

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Режим «не спрашивать» приходит включённым только в отладочной сборке (#1265).
 *
 * `dogfood` — та самая сборка, которую раздаёт публичный лендинг: `tools/publish-dogfood.sh`
 * выкладывает её предварительным релизом, а сайт нарочно берёт именно предварительный. Пока
 * умолчание держалось на «не релиз», человек, скачавший Point с сайта, получал приложение,
 * которое отправляет объект чужому сервису без единого вопроса — вопреки конституции (§11).
 *
 * Проверка идёт в каждой сборке отдельно: тесты гоняются по всем типам, и каждый спрашивает
 * себя сам — умолчание обязано совпасть с тем, отладочная ли это сборка.
 */
class YoloDefaultTest {

    @Test
    fun `умолчание режима без вопросов совпадает с типом сборки`() {
        assertEquals(
            "сборка «${BuildConfig.BUILD_TYPE}» приходит с включённым YOLO, а обязана спрашивать согласие",
            BuildConfig.DEBUG,
            YoloDefaultModule.yoloByDefault(),
        )
    }
}
